def ftables():
    out = []
    for i in range(512):
        if i == 4:
            out.append('\t.quad\twpt + (1<<PTE_V)')
        else:
            out.append('\t.quad\t%d + (1<<PTE_V|1<<PTE_R|1<<PTE_W|1<<PTE_X|1<<PTE_A|1<<PTE_D)' % (i << 21))
    return '\n'.join(out) + '\n\t.align\t4096\nwpt:\t.space\t4096\n\t.align\t8\nustack:\t.space\t512\nustack_top:\n'
