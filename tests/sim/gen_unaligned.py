#!/usr/bin/env python3
"""Generate tests/sim/unaligned.s: a plain load or store works at any address (errata 217, C10 of docs/encoding-work/instruction-pass.md).

Every plain move (MOVQ, MOVL, MOVW, MOVB, MOVZL, MOVZW, MOVZB), in the base, indexed and auto-increment forms, loads and stores at every offset from 0 to 7 of a quad and across the end of a page
(the buffer is two pages: the access starts in the first and ends in the second).  The expected values are worked out here from the bytes of the buffer, a store is checked byte by byte
with the bytes around it, and the add-to-memory form is checked on a quad that crosses a page.  A failed check n exits with n.

usage: gen_unaligned.py OUTDIR"""
import sys as _sys, os as _os
_sys.path.insert(0, _os.path.join(_os.path.dirname(_os.path.abspath(__file__)), '..', '..', 'tools'))
import marks		# the words of the encoding written with the width suffixes (tools/marks.py)
import os, sys


def pat(i): return (i * 37 + 11) & 255


def sext(v, bits):
    v &= (1 << bits) - 1
    return v - (1 << bits) if v >> (bits - 1) else v


class T:
    def __init__(self):
        self.l = []; self.n = 0
    def a(self, *ls): self.l += ['\t' + x for x in ls]
    def chk(self, reg, want):
        self.n += 1
        self.a('movq\t=0x%x, r6' % (want & (2 ** 64 - 1)), 'cbne\t%s, r6, fail%d' % (reg, self.n))


def gen():
    t = T()
    t.l = ['; GENERATED by tests/sim/gen_unaligned.py -- do not edit.  A plain load or store works at any address: every size at every offset of a quad and across the end of a page.  A failed check n exits with n.',
           '\t.text', '\t.globl\t_start', '_start:',
           '\tlea\tbuf, r8', '\tmovq\t$0, r1', '1:', '\tmovq\tr1, r2', '\tmovq\t$37, r3', '\tmul\tr3, r2', '\tadd\t$11, r2', '\tmovb\tr2, (r8)', '\tadd\t$1, r8', '\tadd\t$1, r1',
           '\tcbne\tr1, $8192, 1b']
    sizes = (('movq', 8, True), ('movl', 4, True), ('movw', 2, True), ('movb', 1, True), ('movzl', 4, False), ('movzw', 2, False), ('movzb', 1, False))
    # the load offsets: 0 to 8 in the first page, and the ones that end in the second
    offs = list(range(0, 9)) + [4096 - 8 + k for k in range(0, 9)] + [4096 - 3, 4096 - 1]
    for mn, size, sx in sizes:
        for off in offs:
            v = sum(pat(off + i) << (8 * i) for i in range(size))
            want = sext(v, 8 * size) if sx else v
            t.a('lea\tbuf, r8', '%s\t%d(r8), r2' % (mn, off)); t.chk('r2', want)
        # indexed and auto-increment forms
        off = 4096 - size // 2 - 1 if size > 1 else 4095
        v = sum(pat(off + i) << (8 * i) for i in range(size))
        want = sext(v, 8 * size) if sx else v
        t.a('lea\tbuf, r8', 'movq\t$%d, r9' % (off - 3), '%s\t3(r8)(r9*1), r2' % mn); t.chk('r2', want)
        t.a('lea\tbuf+%d, r8' % off, '%s\t(r8)+, r2' % mn); t.chk('r2', want)
        t.a('lea\tbuf+%d, r2' % (off + size), 'cbne\tr8, r2, fail%d' % (t.n + 1)); t.n += 1
    # the stores: the value lands in the bytes, the neighbours do not change
    for mn, size in (('movq', 8), ('movl', 4), ('movw', 2), ('movb', 1)):
        for off in list(range(1, 8)) + [4096 - 8 + k for k in range(1, 8)] + [4096 - 1]:
            t.a('lea\tbuf, r8', 'movq\t=0x%x, r1' % (0x1122334455667788 & ((1 << (8 * size)) - 1)), '%s\tr1, %d(r8)' % (mn, off))
            vv = 0x1122334455667788 & ((1 << (8 * size)) - 1)
            for i in range(-1, size + 1):
                want = (vv >> (8 * i)) & 255 if 0 <= i < size else pat(off + i)
                t.a('movzb\t%d(r8), r2' % (off + i)); t.chk('r2', want)
            # put the buffer back
            for i in range(size):
                t.a('movq\t$%d, r3' % sext(pat(off + i), 8), 'movb\tr3, %d(r8)' % (off + i))
    # a quad store with auto-decrement, across a page
    t.a('lea\tbuf+4100, r8', 'movq\t=0x0102030405060708, r1', 'movq\tr1, -(r8)', 'lea\tbuf+4092, r5', 'cbne\tr8, r5, fail%d' % (t.n + 1)); t.n += 1
    for i in range(8):
        t.a('movzb\t%d(r8), r2' % i); t.chk('r2', 8 - i)
    # an add to memory on a quad that crosses a page
    t.a('lea\tbuf+4093, r8', 'movq\t=0x00000000ffffffff, r1', 'movq\tr1, (r8)', 'movq\t$1, r2', 'addm\tr2, (r8)', 'movq\t(r8), r3'); t.chk('r3', 0x100000000)
    t.a('clr\tr0', 'trap\t$0')
    for i in range(1, t.n + 1):
        t.l.append('fail%d:\tmovq\t$%d, r0' % (i, (i - 1) % 255 + 1))
        t.a('trap\t$0')
    t.l += ['\t.data', '\t.align\t4096', 'buf:\t.space\t8192']
    return '\n'.join(t.l) + '\n'


if __name__ == '__main__':
    open(os.path.join(sys.argv[1], 'unaligned.s'), 'w').write(marks.spell_text(gen()))
    print('gen_unaligned: unaligned.s')
