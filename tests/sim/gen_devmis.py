#!/usr/bin/env python3
"""gen_devmis.py -- the tests of the misaligned plain access and the memory type (manual 9.x, 2.x; the corpus probe SEC-M13).  Both are QEMU only (they need page tables and devices).

    python3 tests/sim/gen_devmis.py     writes tests/qemu/mmu-misaligned.S and tests/qemu/sec-device-split.S

A plain access that is not aligned to its size works on normal memory (cached, uncached) and on weakly ordered device memory (the machine makes two accesses where it must), and takes the
misalignment fault on strongly ordered device memory (memory type device, 3): precise, EVA the address of the access, EPC the instruction, nothing performed (no register written, no byte of
memory written, no device register read or written).  An access that touches two pages is judged by the stricter of the two.  A physical access (translation off) is strongly ordered where
the address is in the space of devices.

mmu-misaligned: the pages of the window at 0x800000 (page n at 0x800000 + n * 0x1000):
  0 RAM cached   1 RAM cached   2 RAM uncached   3 the timer, device weak   4 RAM cached   5 the timer, device strongly ordered   6 RAM cached   7 the timer, device weak   8 the timer, device
  strongly ordered   9 RAM cached
The timer's COMPARE register (offset 8) is the register the cases read and write; QEMU does an access that is not aligned as aligned pieces (up to 8 bytes) at the page's own offsets, so a quad at
offset 4 is a piece of 4 bytes at 4 (no register: reads zero, ignored) and a piece of 4 bytes at 8 (COMPARE).
sec-device-split: the console's receive data register (offset 8) is cleared by a read and the character after it is accepted; a transmit write sends a character.  A split access onto it must do neither.

Registers: r3 the address, r1 the value, r4 the result; r13 where the handler resumes; r17 the scratch of the check macros.  Failed case n: exit n."""
import sys as _sys, os as _os
_sys.path.insert(0, _os.path.join(_os.path.dirname(_os.path.abspath(__file__)), '..', '..', 'tools'))
import marks		# the words of the encoding written with the width suffixes (tools/marks.py)
import os, sys
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, '..', 'sec'))
from secgen import Prog, HEADER, KVEC, KHANDLERS, KDATA

M64 = (1 << 64) - 1
GEN = '; GENERATED by tests/sim/gen_devmis.py: do not edit.  '
BASE = 0x800000


def hx(v): return '0x%x' % (v & M64)


class CProg(Prog):
    def __init__(s):
        super().__init__(user=False)
        s.cur = 0
        s.lab = 0

    def case(s, what):
        s.cur += 1
        assert s.cur < 250
        s.e('\t; ---- case %d: %s' % (s.cur, what))

    def chk(s, a, b, what=''):
        s.e('\tcbeq\t%s, %s, 1f%s\n%s\n1:' % (a, b, '\t; case %d: %s' % (s.cur, what) if what else '', s.fail(s.cur)))

    def setaddr(s, addr, reg='r3'):
        s.e('\tmovq\t=(%s), %s' % (hx(addr), reg))

    def pre(s, reg, val): s.e('\tmovq\t=(%s), %s' % (hx(val), reg))

    def run(s, insn, fault, eva=None, before=''):
        """the instruction at a label; if `fault` one exception (misalignment, EVA, EPC) else none"""
        s.lab += 1
        n = s.lab
        s.e('\tmovq\t#0, r10\n\tmovq\tr10, cnt')
        if before: s.e(before)
        s.e('\tlea\tN%d, r13' % n)
        s.e('I%d:\t%s' % (n, insn))
        s.e('N%d:\tmovq\tcnt, r12' % n)
        if fault:
            s.eq('r12', '1', 'one exception')
            s.e('\tmovq\tlast_cause, r12')
            s.eq('r12', 'VECTOR_MISALIGNED', 'it is the misalignment fault')
            s.e('\tmovq\tlast_eva, r12')
            s.eq('r12', hx(eva), 'EVA is the address of the access')
            s.e('\tmovq\tlast_epc, r12\n\tlea\tI%d, r11' % n)
            s.chk('r12', 'r11', 'EPC is the instruction')
        else:
            s.eq('r12', '0', 'no exception')

    def eq(s, reg, val, what=''):
        s.e('\tmovq\t=(%s), r17' % val)
        s.chk(reg, 'r17', what)


def tables(pages):
    """pages: list of (physical address, flags text); the window at 0x800000 is L1 entry 4"""
    l = ['\t.align\t4096', 'l2:\t.quad\tl1 + (1<<PTE_V)', '\t.space\t4088', '\t.align\t4096', 'l1:']
    for i in range(512):
        l.append('\t.quad\twpt + (1<<PTE_V)' if i == 4 else '\t.quad\t%d + (1<<PTE_V|1<<PTE_R|1<<PTE_W|1<<PTE_X|1<<PTE_A|1<<PTE_D)' % (i << 21))
    l += ['\t.align\t4096', 'wpt:']
    for pa, mt in pages:
        l.append('\t.quad\t%s + (1<<PTE_V|1<<PTE_R|1<<PTE_W|1<<PTE_A|1<<PTE_D%s)' % (pa, mt))
    l += ['\t.space\t%d' % (4096 - 8 * len(pages)), '']
    return '\n'.join(l)


MMU_ON = r"""
	lea	l2, r1
	mtsr	ptbr, r1
	movq	#1, r1
	mtsr	mmuctl, r1
	isync
"""


def page(n): return BASE + 0x1000 * n


def gen_misaligned():
    p = CProg()
    p.e(HEADER + '\t.text\n\t.globl\t_start\n_start:' + KVEC + MMU_ON)
    CMP = 0x1122334455667788
    T3, T2 = page(5), page(3)
    # ---- the normal types
    for pg, what in ((0, 'normal cached memory'), (2, 'normal uncached memory')):
        a = page(pg)
        for mn, off, size, val in (('movq', 3, 8, 0x1122334455667788), ('movq', 5, 8, 0x8877665544332211), ('movl', 1, 4, 0x44332211), ('movw', 1, 2, 0x2211)):
            p.case('%s %s at offset %d of %s: it works' % (mn, 'store', off, what))
            p.setaddr(a); p.pre('r1', val)
            p.run('%s\tr1, %d(r3)' % (mn, off), False)
            p.e('\t%s\t%d(r3), r4' % ('movzl' if size == 4 else 'movzw' if size == 2 else 'movq', off))
            p.eq('r4', hx(val), 'it reads back what was stored')
            p.case('%s load at offset %d of %s: it works' % (mn, off, what))
            p.run('%s\t%d(r3), r5' % ('movzl' if size == 4 else 'movzw' if size == 2 else 'movq', off), False)
            p.eq('r5', hx(val), 'the load reads it')
    # ---- the strongly ordered device page: control, then every size and direction faults, nothing performed
    p.case('control: an aligned store and load of the timer\'s COMPARE through the strongly ordered page')
    p.setaddr(T3); p.pre('r1', CMP)
    p.e('\tmovq\tr1, 8(r3)\n\tmovq\t8(r3), r4')
    p.eq('r4', hx(CMP), 'aligned access to a strongly ordered page works')
    for mn, off, size in (('movq', 4, 8), ('movq', 1, 8), ('movl', 10, 4), ('movl', 2, 4), ('movw', 7, 2), ('movw', 1, 2)):
        p.case('%s load at offset %d of a strongly ordered device page: the misalignment fault, nothing performed' % (mn, off))
        p.setaddr(T3); p.pre('r4', 0x5a5a5a5a5a5a5a5a)
        p.run('%s\t%d(r3), r4' % (mn, off), True, T3 + off)
        p.eq('r4', '0x5a5a5a5a5a5a5a5a', 'the destination is as it was')
        p.e('\tmovq\t8(r3), r5')
        p.eq('r5', hx(CMP), 'COMPARE is as it was')
        p.case('%s store at offset %d of a strongly ordered device page: the misalignment fault, nothing performed' % (mn, off))
        p.setaddr(T3); p.pre('r1', 0xaabbccdd99887766)
        p.run('%s\tr1, %d(r3)' % (mn, off), True, T3 + off)
        p.e('\tmovq\t8(r3), r5')
        p.eq('r5', hx(CMP), 'COMPARE is as it was: no piece of the store reached the device')
    # ---- the weakly ordered device page
    p.case('control: COMPARE through the weakly ordered page')
    p.setaddr(T2); p.pre('r1', CMP)
    p.e('\tmovq\tr1, 8(r3)\n\tmovq\t8(r3), r4')
    p.eq('r4', hx(CMP), 'aligned access works')
    p.case('movq load at offset 4 of a weakly ordered device page: it works (two pieces: nothing at 4, COMPARE\'s low half at 8)')
    p.run('movq\t4(r3), r4', False)
    p.eq('r4', '0x%x' % ((CMP & 0xffffffff) << 32), 'the access is made, in two pieces')
    p.case('movl load at offset 6 of a weakly ordered device page: it works')
    p.run('movl\t6(r3), r4', False)
    p.eq('r4', '0x77880000', 'the access is made')
    p.case('movq store at offset 4 of a weakly ordered device page: it works (the high half reaches COMPARE)')
    p.pre('r1', 0xaabbccdd11223344)
    p.run('movq\tr1, 4(r3)', False)
    p.e('\tmovq\t8(r3), r4')
    p.eq('r4', '0xaabbccdd', 'the second piece of the store reached COMPARE')
    # ---- an access across two pages is judged by the stricter of them
    p.case('control: the bytes of RAM page 4 and 6 and 9 and the page boundaries')
    for pg in (1, 2, 4, 6, 9):
        p.setaddr(page(pg)); p.pre('r1', 0x5a5a5a5a5a5a5a5a)
        p.e('\tmovq\tr1, (r3)\n\tmovq\tr1, 4088(r3)')
    X = 0x1122334455667788
    p.case('a quad store across two normal cached pages (0 into 1): it works')
    p.setaddr(page(0) + 0xffc); p.pre('r1', X)
    p.run('movq\tr1, (r3)', False)
    p.e('\tmovq\t(r3), r4')
    p.eq('r4', hx(X), 'it reads back')
    p.case('a quad load across a cached page into an uncached one (1 into 2): it works')
    p.setaddr(page(1) + 0xffc); p.pre('r1', X)
    p.e('\tmovq\tr1, (r3)')
    p.run('movq\t(r3), r5', False)
    p.eq('r5', hx(X), 'the load reads it')
    p.case('a quad store from an uncached page into a weakly ordered device page (2 into 3): it works, the RAM half is written')
    p.setaddr(page(2) + 0xffc); p.pre('r1', X)
    p.run('movq\tr1, (r3)', False)
    p.e('\tmovl\t(r3), r4')
    p.eq('r4', '0x55667788', 'the four bytes in RAM are written')
    p.case('a quad load from a weakly ordered device page into a cached page (3 into 4): it works')
    p.setaddr(page(4)); p.pre('r1', 0x0badf00d)
    p.e('\tmovl\tr1, (r3)')
    p.setaddr(page(3) + 0xffc)
    p.run('movq\t(r3), r4', False)
    p.eq('r4', '0x0badf00d00000000', 'zero from the device (no register), then the RAM')
    p.case('a quad store from a cached page into a strongly ordered device page (4 into 5): the fault, nothing written')
    p.setaddr(page(4) + 0xffc); p.pre('r1', X)
    p.run('movq\tr1, (r3)', True, page(4) + 0xffc)
    p.e('\tmovl\t(r3), r4')
    p.eq('r4', '0x5a5a5a5a', 'the four bytes in RAM are as they were')
    p.case('a quad load from a cached page into a strongly ordered device page (4 into 5): the fault, the destination as it was')
    p.setaddr(page(4) + 0xffc); p.pre('r4', 0x5a5a5a5a5a5a5a5a)
    p.run('movq\t(r3), r4', True, page(4) + 0xffc)
    p.eq('r4', '0x5a5a5a5a5a5a5a5a', 'the destination is as it was')
    p.case('a quad store from a strongly ordered device page into a cached page (5 into 6): the fault, nothing written')
    p.setaddr(page(6)); p.pre('r1', 0x0c0ffee0)
    p.e('\tmovl\tr1, (r3)')
    p.setaddr(page(5) + 0xffc); p.pre('r1', X)
    p.run('movq\tr1, (r3)', True, page(5) + 0xffc)
    p.setaddr(page(6))
    p.e('\tmovl\t(r3), r4')
    p.eq('r4', '0x0c0ffee0', 'the four bytes in RAM are as they were')
    p.case('a quad load from a strongly ordered device page into a cached page (5 into 6): the fault')
    p.setaddr(page(5) + 0xffc); p.pre('r4', 0x5a5a5a5a5a5a5a5a)
    p.run('movq\t(r3), r4', True, page(5) + 0xffc)
    p.eq('r4', '0x5a5a5a5a5a5a5a5a', 'the destination is as it was')
    p.case('a quad store from a weakly ordered device page into a strongly ordered one (7 into 8): the fault')
    p.setaddr(page(7) + 0xffc); p.pre('r1', X)
    p.run('movq\tr1, (r3)', True, page(7) + 0xffc)
    p.case('a quad load from a strongly ordered device page into a cached page (8 into 9): the fault')
    p.setaddr(page(8) + 0xffc); p.pre('r4', 0x5a5a5a5a5a5a5a5a)
    p.run('movq\t(r3), r4', True, page(8) + 0xffc)
    p.eq('r4', '0x5a5a5a5a5a5a5a5a', 'the destination is as it was')
    # ---- the aligned accesses next to the strongly ordered pages are not affected
    p.case('an aligned quad at the last eight bytes of a cached page next to a strongly ordered one: it works')
    p.setaddr(page(4) + 0xff8); p.pre('r1', X)
    p.run('movq\tr1, (r3)', False)
    p.e('\tmovq\t(r3), r4')
    p.eq('r4', hx(X), 'it reads back')
    # ---- translation off: the address decides
    p.case('translation off: a quad at an odd address of RAM works')
    p.e('\tmovq\t#0, r1\n\tmtsr\tmmuctl, r1\n\tisync')
    p.setaddr(0xa00000); p.pre('r1', X)
    p.run('movq\tr1, 3(r3)', False)
    p.e('\tmovq\t3(r3), r4')
    p.eq('r4', hx(X), 'it reads back')
    p.case('translation off: a quad load at an odd address of the space of devices (the timer) is the fault')
    p.e('\tmovq\t=MAP_TIMER, r3')
    p.pre('r4', 0x5a5a5a5a5a5a5a5a)
    p.run('movq\t4(r3), r4', True, 0x8000000000 + 4)
    p.eq('r4', '0x5a5a5a5a5a5a5a5a', 'the destination is as it was')
    p.case('translation off: the same store is the fault, and the aligned access to COMPARE still works')
    p.pre('r1', 0xaabbccdd99887766)
    p.run('movq\tr1, 4(r3)', True, 0x8000000000 + 4)
    p.e('\tmovq\t8(r3), r4')
    p.eq('r4', '0xaabbccdd', 'COMPARE is as the weak case left it: the store reached nothing')
    p.done()
    pages = [(hx(page(0)), ''), (hx(page(1)), ''), (hx(page(2)), '|MT_UNCACHED<<PTE_MT'), ('MAP_TIMER', '|MT_DEVICE_WEAK<<PTE_MT'), (hx(page(4)), ''), ('MAP_TIMER', '|MT_DEVICE<<PTE_MT'),
             (hx(page(6)), ''), ('MAP_TIMER', '|MT_DEVICE_WEAK<<PTE_MT'), ('MAP_TIMER', '|MT_DEVICE<<PTE_MT'), (hx(page(9)), '')]
    body = p.text() + KHANDLERS + KDATA + '\n' + tables(pages)
    hdr = ['A plain access that is not aligned to its size works on normal memory and on weakly ordered device memory and is the misalignment fault on strongly ordered device memory (memory type 3): precise, EVA the',
           'address, EPC the instruction, nothing performed; an access across two pages is judged by the stricter; with translation off an address at which a device answers is strongly ordered.  QEMU only (page',
           'tables, the timer\'s registers).  Failed case n: exit n.']
    return hdr, body


def gen_split():
    """SEC-M13: the console's receive data register is cleared by a read; a split read that reached it would take the character, a split write to the transmit data register would send one"""
    p = CProg()
    p.e(HEADER + '\t.text\n\t.globl\t_start\n_start:' + KVEC + MMU_ON)
    C = page(0)
    p.case('control: the console is ready with a character (the first of the input), the page is strongly ordered')
    p.setaddr(C)
    p.e('1:\tmovq\t0(r3), r4\n\tand\t#(1<<CONSOLE_CSR_READY), r4\n\tcbeq\tr4, #0, 1b')
    p.case('a quad load at offset 4 (a piece of RXDB at offset 8) is the fault and does not take the character')
    p.pre('r5', 0x5a5a5a5a5a5a5a5a)
    p.run('movq\t4(r3), r5', True, C + 4)
    p.eq('r5', '0x5a5a5a5a5a5a5a5a', 'the destination is as it was')
    p.case('a word load at offset 6 and a half-word load at offset 7 (pieces of RXDB) are the fault and do not take it')
    p.run('movl\t6(r3), r5', True, C + 6)
    p.run('movzw\t7(r3), r5', True, C + 7)
    p.case('the receive register is still ready and holds the first character')
    p.e('\tmovq\t0(r3), r4\n\tand\t#(1<<CONSOLE_CSR_READY), r4')
    p.eq('r4', '(1<<CONSOLE_CSR_READY)', 'the ready bit is set: nothing took the character')
    p.e('\tmovq\t8(r3), r5')
    p.eq('r5', '0x78', 'the aligned read gives the first character, once')
    p.case('a quad store at offset 20 (a piece at TXDB, offset 24) is the fault and sends nothing')
    p.pre('r1', 0x4141414141414141)
    p.run('movq\tr1, 20(r3)', True, C + 20)
    p.run('movl\tr1, 22(r3)', True, C + 22)
    p.case('an aligned write to the transmit register sends exactly one character')
    p.pre('r1', 0x5a)
    p.e('\tmovq\tr1, 24(r3)')
    p.done()
    pages = [('MAP_CONSOLE', '|MT_DEVICE<<PTE_MT')]
    body = p.text() + KHANDLERS + KDATA + '\n' + tables(pages)
    hdr = ['SEC-M13: a plain access that is not aligned and touches a register of a strongly ordered device is the misalignment fault and reaches none of it: the split read does not take the character out of the',
           'console\'s receive register (a read clears it), the split write sends no character (the standard output is exactly one Z).  QEMU only.  Failed case n: exit n.']
    return hdr, body


def main():
    root = os.path.join(HERE, '..', 'qemu')
    for name, fn in (('mmu-misaligned', gen_misaligned), ('sec-device-split', gen_split)):
        hdr, body = fn()
        open(os.path.join(root, name + '.S'), 'w').write(GEN + hdr[0] + '\n' + ''.join('; ' + l + '\n' for l in hdr[1:]) + marks.spell_text(body))
    open(os.path.join(root, 'sec-device-split.in'), 'w').write('xy\n')
    open(os.path.join(root, 'sec-device-split.out'), 'w').write('Z')


if __name__ == '__main__':
    main()
