#!/usr/bin/env python3
"""Generate tests/sim/absminmax.s: abs, min, minu, max and maxu are assembler aliases that expand over existing instructions (abs: movq, sar, xor, sub; min and kin: setCC, neg, bsel;
r12 is the scratch register the expansion may write).  Every pair of boundary values, every aliasing of the destination with the sources (destination distinct, destination one of the
sources, both sources the same register, all three the same), the most negative number for abs, and the registers that are neither operand (they keep their values; r12 is the only other register written).  The
expected values are computed here from the manual's meaning, not from the executor.  A failed check jumps to `fail`, which exits with 1.

usage: gen_absminmax.py OUTDIR"""
import os, sys
M = (1 << 64) - 1
def s(v): return v - (1 << 64) if v >> 63 else v
VALS = [1 << 63, (1 << 63) + 1, (-(1 << 32)) & M, (-2) & M, M, 0, 1, 2, 1 << 32, (1 << 63) - 2, (1 << 63) - 1]
OPS = {'min': lambda a, b: a if s(a) < s(b) else b, 'max': lambda a, b: a if s(a) > s(b) else b,
       'minu': lambda a, b: a if a < b else b, 'maxu': lambda a, b: a if a > b else b}
o = ['; GENERATED by tests/sim/gen_absminmax.py -- do not edit.  abs, min, minu, max and maxu expand over existing instructions; every pair of boundary values and every aliasing of the registers.  A failed check jumps to fail (exit 1).',
     '\t.text', '\t.globl\t_start', '_start:']
def a(*ls): o.extend('\t' + x for x in ls)
def c(v): return '=0x%x' % (v & M)
def chk(reg, want): a('movq\t%s, r30' % c(want), 'cbne\t%s, r30, fail' % reg)
def sentinels(): a('movq\t=0x5a5a5a5a5a5a5a5a, r5', 'movq\t=0xa5a5a5a5a5a5a5a5, r6', 'movq\t=0x1122334455667788, r20')
def keep(): chk('r5', 0x5a5a5a5a5a5a5a5a); chk('r6', 0xa5a5a5a5a5a5a5a5); chk('r20', 0x1122334455667788)
for x in VALS:                       # abs: the destination is the source, or another register (the source stays)
    want = x if x == 1 << 63 else (x if not x >> 63 else (-s(x)) & M)
    sentinels(); a('movq\t%s, r1' % c(x), 'abs\tr1, r1'); chk('r1', want); keep()
    sentinels(); a('movq\t%s, r1' % c(x), 'movq\t#-1, r2', 'abs\tr1, r2'); chk('r2', want); chk('r1', x); keep()
    sentinels(); a('movq\t%s, r17' % c(x), 'abs\tr17, r18'); chk('r18', want); chk('r17', x); keep()
for mn, f in OPS.items():
    for x in VALS:
        for y in VALS:
            w = f(x, y)
            sentinels(); a('movq\t%s, r1' % c(x), 'movq\t%s, r2' % c(y), 'movq\t#-1, r3', '%s\tr1, r2, r3' % mn); chk('r3', w); chk('r1', x); chk('r2', y); keep()
            a('movq\t%s, r1' % c(x), 'movq\t%s, r2' % c(y), '%s\tr1, r2, r1' % mn); chk('r1', w); chk('r2', y)
            a('movq\t%s, r1' % c(x), 'movq\t%s, r2' % c(y), '%s\tr1, r2, r2' % mn); chk('r2', w); chk('r1', x)
            a('movq\t%s, r21' % c(x), 'movq\t%s, r22' % c(y), '%s\tr22, r21, r23' % mn); chk('r23', f(y, x))
        a('movq\t%s, r1' % c(x), 'movq\t#-1, r3', '%s\tr1, r1, r3' % mn); chk('r3', x); chk('r1', x)
        a('movq\t%s, r1' % c(x), '%s\tr1, r1, r1' % mn); chk('r1', x)
a('movq\t#0, r0', 'trap\t#0', 'fail:', 'movq\t#1, r0', 'trap\t#0')
open(os.path.join(sys.argv[1], 'absminmax.s'), 'w').write('\n'.join(o) + '\n')
