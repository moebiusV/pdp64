#!/usr/bin/env python3
"""Generate tests/sim/rotate-map.s: rol is an assembler mapping onto ror, and every spelling of a rotate by a constant (the short two-byte form, the four-byte form, a register that is the source and
the destination or not, registers above r15) gives the rotation of the model below, computed here from the manual and not from the executor.  Also the register count of ror, taken modulo 64 (so that
a rotate left by a register is the negated register), and the rotate that leaves a neighbour register alone.  A failed check n exits with n.

usage: gen_rotate.py OUTDIR"""
import sys as _sys, os as _os
_sys.path.insert(0, _os.path.join(_os.path.dirname(_os.path.abspath(__file__)), '..', '..', 'tools'))
import marks		# the words of the encoding written with the width suffixes (tools/marks.py)
import os, sys
M = (1 << 64) - 1
def ror(v, n): n %= 64; return ((v >> n) | (v << (64 - n))) & M
def rol(v, n): return ror(v, -n)
V = 0x0123456789abcdef
n = [0]
o = ['; GENERATED by tests/sim/gen_rotate.py -- do not edit.  rol is an assembler mapping onto ror; every spelling of a rotate by a constant, the short and the long form, rotates as the model says.  A failed check n exits with n.',
     '\t.text', '\t.globl\t_start', '_start:']
def a(*ls): o.extend('\t' + x for x in ls)
def chk(reg, want):
    n[0] += 1
    a('movq\t=0x%x, r30' % (want & M), 'cbne\t%s, r30, f%d' % (reg, n[0]))
def load(reg): a('movq\t=0x%x, %s' % (V, reg))
counts = [0, 1, 3, 7, 8, 9, 15, 16, 32, 55, 56, 57, 63]
for c in counts:
    for srcdst in (('r1', 'r2'), ('r3', 'r3'), ('r17', 'r18'), ('r20', 'r20')):
        s, d = srcdst
        for mn, fn in (('rol', rol), ('ror', ror)):
            load(s)
            if s != d: a('movq\t#-1, %s' % d)
            a('%s\t%s, #%d, %s' % (mn, s, c, d)); chk(d, fn(V, c))
            if s == d:
                load(s); a('%s\t#%d, %s' % (mn, c, d)); chk(d, fn(V, c))
    # the neighbour is untouched by an in-place rotate
    load('r4'); a('movq\t#77, r5', 'ror\t#%d, r4' % c); chk('r5', 77)
# negative counts: rotate left; a count beyond the short form's range
for c in (-1, -3, -8, -9, -33, -63, -64):
    load('r6'); a('ror\t#%d, r6' % c); chk('r6', ror(V, c))
    load('r6'); a('rol\t#%d, r6' % c); chk('r6', rol(V, c))
# a register count of ror is taken modulo 64: the negated register rotates left
for cnt in (0, 1, 7, 64, 65, -1, -64):
    load('r1'); a('movq\t#%d, r2' % cnt, 'ror\tr1, r2, r3'); chk('r3', ror(V, cnt))
    load('r1'); a('movq\t#%d, r2' % cnt, 'neg\tr2', 'ror\tr1, r2, r3'); chk('r3', rol(V, cnt))
# the 32-bit rotate is not touched
load('r1'); a('ror32\tr1, #8, r2'); chk('r2', ((0x89abcdef >> 8 | 0x89abcdef << 24) & 0xffffffff) - (1 << 32))
a('movq\t#0, r0', 'trap\t#0')
for i in range(1, n[0] + 1):
    o.append('f%d:\tmovq\t#%d, r0\n\ttrap\t#0' % (i, i))
assert n[0] < 250
open(os.path.join(sys.argv[1], 'rotate-map.s'), 'w').write(marks.spell_text('\n'.join(o)) + '\n')
print('gen_rotate: rotate-map.s (%d checks)' % n[0])
