"""Generate tests/sim/newops.s (registers r0-r15) and newops32.s (registers r16-r31): the instructions that only the pdp64 has, with
expectations computed here, not by the simulator.  A failed check n exits with n (halt).  usage: gen_newops.py OUTDIR"""
import sys
M = (1 << 64) - 1
out = sys.argv[1]

class T:
    def __init__(self, title):
        self.l = ['; GENERATED by tests/sim/gen_newops.py -- do not edit.  ' + title, '\t.text', '\t.globl\t_start', '_start:', '\tlea\tstack_top, sp']
        self.n = 0
        self.lab = 0
    def a(self, *lines):
        self.l.extend('\t' + x if not x.endswith(':') else x for x in lines)
    def chk(self, reg, val):
        self.n += 1
        val &= M
        self.a('movq\t=0x%x, r15' % val, 'cmp\t%s, r15' % reg, 'bne\tF%d' % self.n)
    def chkmem(self, addr, val, size=8):
        self.n += 1
        mn = {8: 'movq', 4: 'movzl', 2: 'movzw', 1: 'movzb'}[size]
        self.a('%s\t%s, r15' % (mn, addr), 'movq\t=0x%x, r12' % (val & ((1 << (8 * size)) - 1)), 'cmp\tr15, r12', 'bne\tF%d' % self.n)
    def flags(self, n, z, v, c):
        """check the flags: mfps, mask, compare"""
        self.n += 1
        self.a('mfps\tr15', 'and\t#15, r15', 'cmp\tr15, #%d' % (c | (v << 1) | (z << 2) | (n << 3)), 'bne\tF%d' % self.n)
    def write(self, name, tail=''):
        self.a('clr\tr0', 'halt')
        for k in range(1, self.n + 1): self.a('F%d:' % k, 'movq\t#%d, r0' % k, 'halt')
        self.a('F9999:', 'movq\t#99, r0', 'halt')
        self.l.append(tail)
        self.l += ['\t.data', '\t.align 8', 'ubuf:\t.space 32', '\t.bss', '\t.align 16', '\t.space 256', 'stack_top:', '\t.space 64']
        open('%s/%s' % (out, name), 'w').write('\n'.join(self.l) + '\n')

def s64(v): return v - (1 << 64) if v >> 63 else v

