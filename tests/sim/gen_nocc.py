#!/usr/bin/env python3
"""Writes tests/sim/nocc.s: the compare into a register (setCC Ra, Rb|#imm, Rd), the floating-point compare-and-branch (fcbCC, fcbCC32, with NaN, infinity and signed zero), and the
long forms of the compare-and-branch for the unsigned conditions (the target far beyond the short forms), taken and not taken, forward and backward.  A failed check n exits with n.
    python3 tests/sim/gen_nocc.py > tests/sim/nocc.s"""
import sys as _sys, os as _os
_sys.path.insert(0, _os.path.join(_os.path.dirname(_os.path.abspath(__file__)), '..', '..', 'tools'))
import marks		# the words of the encoding written with width marks (tools/marks.py)
import struct, itertools
M = (1 << 64) - 1
S = lambda v: v - (1 << 64) if v >> 63 else v
VALS = [0, 1, 5, 7, M, M - 1, 1 << 63, (1 << 63) - 1, 0x100000000, 0xFFFFFFFF]
CC = {'eq': lambda a, b: a == b, 'ne': lambda a, b: a != b, 'lt': lambda a, b: S(a) < S(b), 'le': lambda a, b: S(a) <= S(b), 'gt': lambda a, b: S(a) > S(b),
      'ge': lambda a, b: S(a) >= S(b), 'cs': lambda a, b: a < b, 'cc': lambda a, b: a >= b, 'hi': lambda a, b: a > b, 'los': lambda a, b: a <= b}
out = []
n = 0
fails = []
def check(reg, want):
    global n
    n += 1
    out.append('\tcbne\t%s, #%d, f%d' % (reg, want, n))
    fails.append(n)
out.append('; GENERATED by tests/sim/gen_nocc.py: do not edit')
out.append('\t.text\n\t.globl\t_start\n_start:')
# set, register against register
for cc, f in CC.items():
    for a, b in itertools.product(VALS[:8], VALS[:8]):
        if (hash((cc, a, b)) % 5): continue
        out.append('\tmovq\t=%d, r1\n\tmovq\t=%d, r2\n\tmovq\t#9, r3\n\tset%s\tr1, r2, r3' % (S(a), S(b), cc))
        check('r3', int(f(a, b)))
# set against an immediate (the destination may be an operand)
for cc, f in CC.items():
    for a in VALS[:8]:
        for k in (-128, -1, 0, 1, 5, 127):
            if (hash((cc, a, k)) % 4): continue
            out.append('\tmovq\t=%d, r1\n\tset%s\tr1, #%d, r1' % (S(a), cc, k))
            check('r1', int(f(a, k & M)))
# set with r12 and r31 as operands
out.append('\tmovq\t#3, r12\n\tmovq\t#4, r31\n\tsetlt\tr12, r31, r30')
check('r30', 1)
out.append('\tsethi\tr12, r31, r30')
check('r30', 0)
# floating point, double and binary32
D = [0.0, -0.0, 1.0, -1.5, 2.5, float('inf'), float('-inf'), float('nan')]
def bits64(x): return struct.unpack('<q', struct.pack('<d', x))[0]
def bits32(x): return struct.unpack('<i', struct.pack('<f', x))[0]
FC = {'eq': lambda a, b: a == b, 'ne': lambda a, b: a != b, 'lt': lambda a, b: a < b, 'le': lambda a, b: a <= b, 'gt': lambda a, b: a > b, 'ge': lambda a, b: a >= b,
      'uo': lambda a, b: a != a or b != b, 'or': lambda a, b: not (a != a or b != b)}
for w32 in (0, 1):
    for cc, f in FC.items():
        for a, b in itertools.product(D, D):
            conv = bits32 if w32 else bits64
            exp = f(a, b)
            if cc == 'ne': exp = a != b
            out.append('\tmovq\t=%d, r1\n\tmovq\t=%d, r2\n\tclr\tr3\n\tfcb%s%s\tr1, r2, 1f\n\tbr\t2f\n1:\tmovq\t#1, r3\n2:' % (conv(a), conv(b), cc, '32' if w32 else ''))
            check('r3', int(bool(exp)))
# the long forms: a cbCC against r12 (not a hot register) and against an immediate, to a target 20000 bytes away (past the short forms), taken forward, taken backward, and not taken
for cc in ('cs', 'cc', 'hi', 'los', 'lt', 'ge', 'gt', 'le'):
    f = CC[cc]
    for a, b in ((3, 4), (4, 4), (5, 4), (M, 1), (1, M)):
        n += 1
        out.append('\tmovq\t=%d, r1\n\tmovq\t=%d, r12\n\tclr\tr3\n\tcb%s\tr1, r12, FA%d\n\tbr\tFB%d' % (S(a), S(b), cc, n, n))
        out.append('\t.fill\t20000, 1, 0\nFA%d:\tmovq\t#1, r3\nFB%d:' % (n, n))
        check('r3', int(f(a, b)))
        n += 1
        out.append('\tmovq\t=%d, r1\n\tclr\tr3\n\tbr\tFD%d\nFE%d:\tmovq\t#1, r3\n\tbr\tFF%d\n\t.fill\t20000, 1, 0' % (S(a), n, n, n))
        out.append('FD%d:\tcb%s\tr1, #%d, FE%d\nFF%d:' % (n, cc, b if b < 100 else -1, n, n))
        check('r3', int(f(a, b if b < 100 else M)))
out.append('\tmovq\t#0, r0\n\ttrap\t#0')
for i in fails:
    out.append('f%d:\tmovq\t#%d, r0\n\ttrap\t#0' % (i, i))
print(marks.spell_text('\n'.join(out)))
