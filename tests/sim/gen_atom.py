def gen_rmw():
    p = CProg(user=False)
    head(p)
    G = 0xA5A5A5A5A5A5A5A5
    GH = 0xC3C3C3C3
    cases = {8: [(0xFFFFFFFFFFFFFFF0, 0x10), (0x000000007FFFFFF0, 0x8000000000000020), (0x8000000000000000, 0xFFFFFFFFFFFFFFFF), (0x123456789ABCDEF0, 0x0F0F0F0F0F0F0F0F)],
             4: [(0x80000010, 0xDEADBEEF00000010), (0x7FFFFFF0, 0x1234567800000020), (0x80000000, 0xFFFFFFFFFFFFFFFF), (0x89ABCDEF, 0x0F0F0F0F)]}
    for mn, op, size in words():
        if op in ('sc', 'll', 'cas'):
            continue
        for k, (M, S) in enumerate(cases[size]):
            nv = model(op, size, M, S)
            tag = '%s case %d' % (mn, k)
            p.case(tag)
            p.e('\tlea\tbuf+16, r3')
            load(p, 'r17', G); p.e('\tmovq\tr17, -8(r3)\n\tmovq\tr17, 8(r3)')
            if size == 8:
                load(p, 'r17', M)
            else:
                load(p, 'r17', GH << 32 | M)
            p.e('\tmovq\tr17, (r3)')
            load(p, 'r1', 0x1234567812345678)
            load(p, 'r2', S)
            p.e('\t%s\tr1, r2, (r3)' % mn)
            old = sext(M, size * 8) & M64
            p.eq('r1', hx(old), tag + ': Rd is the old value' + (' sign-extended' if size == 4 else ''))
            p.eq('r2', hx(S), tag + ': Rs unchanged')
            p.e('\tmovq\t(r3), r4')
            p.eq('r4', hx(nv if size == 8 else (GH << 32 | nv)), tag + ': the word is the result' + ('; the neighbour half is untouched' if size == 4 else ''))
            p.e('\tmovq\t-8(r3), r4')
            p.eq('r4', hx(G), tag + ': the word below is untouched')
            p.e('\tmovq\t8(r3), r4')
            p.eq('r4', hx(G), tag + ': the word above is untouched')
    # Rd is also a source or the address register: every source is read before Rd is written
    for size, suf in ((8, ''), (4, 'l')):
        M, S = (0x100, 0x23) if size == 8 else (0x80000100, 0xFFFFFFFF00000023)
        p.case('xadd%s and swap%s with Rd the same register as Rs and as Ra' % (suf, suf))
        p.e('\tlea\tbuf+16, r3\n\tmovq\tr3, r5')
        load(p, 'r17', M if size == 8 else GH << 32 | M); p.e('\tmovq\tr17, (r3)')
        load(p, 'r2', S)
        p.e('\txadd%s\tr2, r2, (r3)' % suf)
        p.eq('r2', hx(sext(M, size * 8) & M64), 'xadd%s Rd = Rs: Rd is the old value' % suf)
        p.e('\tmovq\t(r3), r4')
        load(p, 'r17', model('xadd', size, M, S) if size == 8 else GH << 32 | model('xadd', size, M, S))
        p.chk('r4', 'r17', 'xadd%s Rd = Rs: the operand was read first' % suf)
        load(p, 'r2', S)
        p.e('\tswap%s\tr3, r2, (r3)' % suf)
        p.eq('r3', hx(sext(model('xadd', size, M, S), size * 8) & M64), 'swap%s Rd = Ra: Rd is the old value' % suf)
        p.e('\tmovq\t(r5), r4')
        load(p, 'r17', S if size == 8 else GH << 32 | (S & 0xffffffff))
        p.chk('r4', 'r17', 'swap%s Rd = Ra: the address was read first' % suf)
    p.done()
    return ['The read-modify-write atomics, every word of the grammar except CAS (gen_atom.py gen_cas): swap, xadd, xand, xor_, xxor, xmax, xmin, xmaxu, xminu in both sizes',
            '(the bare name 8 bytes, the suffix l 4 bytes), four operand pairs each; the old value in Rd (a 4-byte one sign-extended), Rs and Ra unchanged, the word changed as the manual says and the words',
            'around it untouched; then Rd the same register as Rs and as Ra.  Failed check n: exit n.'], p.text() + '\t.data\n\t.align\t128\nbuf:\t.space\t128\n'


def gen_cas():
    p = CProg(user=False)
    head(p)
    G = 0xA5A5A5A5A5A5A5A5
    GH = 0xC3C3C3C3
    for mn, op, size in words():
        if op != 'cas':
            continue
        bits = size * 8
        M = 0x1122334455667788 if size == 8 else 0x91223344
        NEW = 0x8877665544332211 if size == 8 else 0x99887766
        UP = 0x5A5A5A5A00000000 if size == 4 else 0
        for what, exp in (('success', M | UP), ('failure', (M ^ 1) | UP), ('4-byte compare ignores bits 32 to 63 of Rd', M | 0x7F7F7F7F00000000) if size == 4 else ('failure, high byte differs', M ^ (0xFF << 56))):
            ok = (exp & ((1 << bits) - 1)) == M
            tag = '%s %s' % (mn, what)
            p.case(tag)
            p.e('\tlea\tbuf+16, r3')
            load(p, 'r17', G); p.e('\tmovq\tr17, -8(r3)\n\tmovq\tr17, 8(r3)')
            load(p, 'r17', M if size == 8 else GH << 32 | M); p.e('\tmovq\tr17, (r3)')
            load(p, 'r1', exp)
            load(p, 'r2', NEW)
            p.e('\t%s\tr1, r2, (r3)' % mn)
            p.eq('r1', hx(sext(M, bits) & M64), tag + ': Rd is the old value (' + ('the swap happened' if ok else 'the swap did not happen') + ')')
            p.eq('r2', hx(NEW), tag + ': Rs unchanged')
            p.e('\tmovq\t(r3), r4')
            nv = (NEW & ((1 << bits) - 1)) if ok else M
            p.eq('r4', hx(nv if size == 8 else GH << 32 | nv), tag + ': the word is ' + ('the new value' if ok else 'unchanged (a failed compare writes nothing)'))
            p.e('\tmovq\t-8(r3), r4')
            p.eq('r4', hx(G), tag + ': the word below is untouched')
            p.e('\tmovq\t8(r3), r4')
            p.eq('r4', hx(G), tag + ': the word above is untouched')
        # Rd = Rs: the expected and the new value are one register
        sfx = 'l' if size == 4 else ''
        p.case(mn + ' with Rd the same register as Rs')
        p.e('\tlea\tbuf+16, r3')
        load(p, 'r17', M if size == 8 else GH << 32 | M); p.e('\tmovq\tr17, (r3)')
        load(p, 'r1', M)
        p.e('\t%s\tr1, r1, (r3)' % mn)
        p.eq('r1', hx(sext(M, bits) & M64), mn + ' Rd = Rs: the old value')
        p.e('\tmovq\t(r3), r4')
        p.eq('r4', hx(M if size == 8 else GH << 32 | M), mn + ' Rd = Rs: swapping a value for itself leaves the word')
    p.case('a retry loop')
    # a retry loop, the way C11 writes it: the failed compare leaves the old value in the expected register
    p.e('\tlea\tbuf+16, r3\n\tmovq\t#5, r17\n\tmovq\tr17, (r3)\n\tmovq\t#0, r1\n\tmovq\t#9, r2\n\tmovq\t#0, r6')
    p.e('retry:\tmovq\tr1, r7\n\tadd\t#1, r6\n\tcas\tr1, r2, (r3)\n\tcbne\tr1, r7, retry')
    p.eq('r6', '2', 'a retry loop: the second try holds the old value in Rd and succeeds')
    p.e('\tmovq\t(r3), r4')
    p.eq('r4', '9', 'a retry loop: the word is the new value')
    p.done()
    return ['Compare and swap in both sizes: the swap happens only when the old value is the expected one in Rd; Rd always ends as the old value (a 4-byte one sign-extended); only the',
            'low 4 bytes of Rd and Rs count in the 4-byte form; a failed compare writes nothing; the words around are untouched; Rd the same register as Rs; a retry loop.  Failed check n: exit n.'], \
        p.text() + '\t.data\n\t.align\t128\nbuf:\t.space\t128\n'


