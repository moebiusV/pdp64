def gen_fault_align():
    p = CProg(user=False)
    head(p, KVEC)
    p.e('\tmovq\t=(0x1111111111111111), r1\n\tmovq\t=(0x2222222222222222), r2')
    lab = 0
    for mn, op, size in words():
        offs = (4, 1, 7) if size == 8 else (2, 1, 3)
        for off in offs:
            lab += 1
            tag = '%s at +%d' % (mn, off)
            p.case(tag)
            p.e('\tlea\tbuf+%d, r3' % (16 + off))
            p.e('\tlea\tbuf+16, r7')
            for k in range(0, 48, 8):
                load(p, 'r17', 0x0101010101010101 * (k // 8 + 1))
                p.e('\tmovq\tr17, %d(r7)' % (k - 16))
            p.e('\tmovq\t=(0x1111111111111111), r1\n\tmovq\t#0, r4\n\tmovq\tr4, cnt')
            p.e('\tlea\tN%d, r13' % lab)
            if op in ('sc',):
                p.e('\tlll\tr6, (r7)' if size == 4 else '\tll\tr6, (r7)')
            p.e('I%d:' % lab)
            if op in ('ll',):
                p.e('\t%s\tr1, (r3)' % mn)
            else:
                p.e('\t%s\tr1, r2, (r3)' % mn)
            p.e('N%d:\tmovq\tcnt, r4' % lab)
            p.eq('r4', '1', tag + ': one exception')
            p.e('\tmovq\tlast_cause, r4')
            p.eq('r4', 'VECTOR_MISALIGNED', tag + ': it is the misalignment fault')
            p.e('\tmovq\tlast_eva, r4\n\tlea\tbuf+%d, r5' % (16 + off))
            p.chk('r4', 'r5', tag + ': EVA is the address')
            p.e('\tmovq\tlast_epc, r4\n\tlea\tI%d, r5' % lab)
            p.chk('r4', 'r5', tag + ': EPC is the instruction (precise)')
            p.eq('r1', '0x1111111111111111', tag + ': Rd unchanged')
            p.eq('r2', '0x2222222222222222', tag + ': Rs unchanged')
            for k in range(0, 48, 8):
                p.e('\tmovq\t%d(r7), r4' % (k - 16))
                p.eq('r4', hx(0x0101010101010101 * (k // 8 + 1)), tag + ': the memory around is untouched (%d)' % (k - 16))
    p.done()
    return ['A misaligned atomic is a precise fault, for every atomic word of the grammar (all 24) at three misaligned addresses each (the 8-byte words off by 4, 1 and 7; the 4-byte words by 2, 1 and 3): the',
            'misalignment vector, EVA the address, EPC the instruction, Rd and Rs unchanged and every byte around the word as it was (a misaligned atomic never half-runs: no split lock).  -K.  Failed check n: exit n.'], \
        p.text() + KHANDLERS + KDATA + '\t.align\t128\nbuf:\t.space\t128\n'


def gen_fault_page():
    """an atomic on a page that is not present: the first touch faults as a STORE (vector 8, also for LL), nothing changed; after the handler maps the page the instruction runs once"""
    p = CProg(user=False)
    head(p, FSETUP)
    p.e('\tlea\tustack_top, sp')
    cases = [('swap', 'swap', 8), ('xadd', 'xadd', 8), ('cas', 'cas', 8), ('xmaxul', 'xmaxul', 4), ('ll', 'll', 8), ('lll', 'lll', 4), ('sc', 'sc', 8), ('xor_l', 'xor_l', 4)]
    page = 0x810000
    for i, (mn, base, size) in enumerate(cases):
        a = page + 0x1000 * i + 0x40
        tag = mn
        p.case(mn + ' on a page that is not present')
        p.e('\tmovq\t=(%s), r3\n\tmovq\t#0, r4\n\tmovq\tr4, cnt' % hx(a))
        p.e('\tmovq\t=(0x1111111111111111), r1\n\tmovq\t#5, r2')
        if base == 'cas':
            p.e('\tmovq\t#0, r1')
        p.e('p%d:' % i)
        if base in ('ll', 'lll'):
            p.e('\t%s\tr1, (r3)' % mn)
        else:
            p.e('\t%s\tr1, r2, (r3)' % mn)
        p.e('\tmovq\tcnt, r11')
        p.eq('r11', '1', tag + ': one fault')
        p.e('\tmovq\tlast_cause, r11')
        p.eq('r11', 'VECTOR_SFAULT', tag + ': an atomic faults as a store' + (' (so does LL)' if base.startswith('l') else ''))
        p.e('\tmovq\tlast_eva, r11\n\tmovq\t=(%s), r12' % hx(a))
        p.chk('r11', 'r12', tag + ': EVA is the address')
        p.e('\tlea\tp%d, r11\n\tmovq\tlast_epc, r12' % i)
        p.chk('r12', 'r11', tag + ': EPC is the instruction')
        p.e('\tmovq\thr1, r11')
        if base in ('cas',):
            p.eq('r11', '0', tag + ': at the fault Rd is as before')
        else:
            p.eq('r11', '0x1111111111111111', tag + ': at the fault Rd is as before')
        # after the restart: the page is mapped and zero; the effect happened once
        if base in ('ll', 'lll'):
            p.eq('r1', '0', tag + ': after the restart Rd is the (zero) word')
        elif base == 'sc':
            p.chkne('r1', '#0', tag + ': after the restart the SC has no reservation and fails')
        elif base == 'cas':
            p.eq('r1', '0', tag + ': after the restart the old value is 0')
            p.e('\tmovq\t(r3), r4')
            p.eq('r4', '5', tag + ': the swap happened once')
        elif base == 'xadd' or base == 'swap':
            p.eq('r1', '0', tag + ': after the restart Rd is the old value, zero')
            p.e('\tmovq\t(r3), r4')
            p.eq('r4', '5', tag + ': the word is changed once')
        elif base == 'xmaxul':
            p.eq('r1', '0', tag + ': after the restart Rd is the old value, zero')
            p.e('\tmovl\t(r3), r4')
            p.eq('r4', '5', tag + ': the word is changed once')
        else:
            p.eq('r1', '0', tag + ': after the restart Rd is the old value, zero')
            p.e('\tmovl\t(r3), r4')
            p.eq('r4', '5', tag + ': the word is changed once')
    p.done()
    body = p.text() + FHANDLERS.replace('h_fault:\n', 'h_fault:\n\tmovq\tr1, hr1\n', 1) + FDATA.replace('redirect:\t.quad\t0', 'redirect:\t.quad\t0\nhr1:\t.quad\t0') + ftables()
    return ['An atomic on a page that is not present faults as a store (the store fault, vector 8, for LL as well as the read-modify-write words and SC): nothing is changed, EVA is the address, EPC the',
            'instruction, Rd as before; when the handler has mapped the page the instruction runs again and its effect happens once.  sim64 -K -x 0x800000:0xa00000; QEMU with its tables.  Failed check n: exit n.'], body


