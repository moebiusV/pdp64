#!/usr/bin/env python3
"""gen_atom.py -- the tests of the atomic words (errata 211; manual 7.4, 9.13) and the corpus probes for the holes atomics can open (docs/security-corpus.md, SEC-A01 to SEC-A07).

    python3 tests/sim/gen_atom.py            writes tests/sim/atom-*.S, tests/sim/sec-atomic-*.S, tests/sim/sec-llsc-*.S and their .flags (run by tools/check-sim64.sh and tools/check-qemu.sh)
                                             and tests/qemu/*atomic*.S (QEMU only: they need page tables)

The expected values come from the small Python model below, written from the manual and not from the executor.  A failed check n ends the program with status n (halt, with r0 = n).
Registers: r1 Rd, r2 Rs, r3 Ra; r17 the scratch of the check macros; r11, r12 the handlers'; r13 where a handler resumes."""
import os, sys
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, '..', 'sec'))
from secgen import Prog, HEADER, KVEC, KHANDLERS, KDATA, FSETUP, FHANDLERS, FDATA, ftables

class CProg(Prog):
    """a program whose failed check ends it with the number of the CASE (the exit status holds 255 numbers; the comment of each case says what it is; the checks inside a case are told apart by the comment)"""

    def __init__(s, user=False):
        super().__init__(user)
        s.cur = 0

    def case(s, what):
        s.cur += 1
        assert s.cur < 250, 'too many cases for one program'
        s.e('\t; ---- case %d: %s' % (s.cur, what))

    def chk(s, a, b, what=''):
        s.e('\tcbeq\t%s, %s, 1f%s\n%s\n1:' % (a, b, '\t; case %d: %s' % (s.cur, what) if what else '', s.fail(s.cur)))
        return s.cur

    def chkne(s, a, b, what=''):
        s.e('\tcbne\t%s, %s, 1f%s\n%s\n1:' % (a, b, '\t; case %d: %s' % (s.cur, what) if what else '', s.fail(s.cur)))
        return s.cur


GEN = '; GENERATED by tests/sim/gen_atom.py: do not edit.  '

M64 = (1 << 64) - 1


def sext(v, bits):
    v &= (1 << bits) - 1
    return v - (1 << bits) if v >> (bits - 1) else v


def model(op, size, old, a, b=0):
    """the value the word becomes (None: not written); a the operand (CAS: the expected value), b the new value of a CAS"""
    bits = size * 8
    m = (1 << bits) - 1
    old &= m
    a &= m
    b &= m
    sa, so = sext(a, bits), sext(old, bits)
    return {'swap': a, 'xadd': (old + a) & m, 'xand': old & a, 'xor_': old | a, 'xxor': old ^ a,
            'xmax': (old if so > sa else a), 'xmin': (old if so < sa else a),
            'xmaxu': max(old, a), 'xminu': min(old, a),
            'cas': (b if old == a else None)}[op]


OPS = ['cas', 'swap', 'xadd', 'xand', 'xor_', 'xxor', 'xmax', 'xmin', 'xmaxu', 'xminu']


def words():
    """every atomic word of the grammar: (mnemonic, base operation, size)"""
    out = []
    for size in (8, 4):
        for o in OPS:
            out.append((o + ('l' if size == 4 else ''), o, size))
        out.append(('sc' + ('l' if size == 4 else ''), 'sc', size))
        out.append(('lll' if size == 4 else 'll', 'll', size))
    return out


def hx(v):
    return '0x%x' % (v & M64)


def head(p, extra='', pre=''):
    p.e(HEADER + '\t.text\n\t.globl\t_start\n' + pre + '_start:' + extra)


def load(p, reg, val):
    p.e('\tmovq\t=(%s), %s' % (hx(val), reg))


