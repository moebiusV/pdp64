#!/usr/bin/env python3
"""Generate tests/qemu/hv-stage2.S: stage 2 of the hypervisor mode (errata 195, 196; design 1.7, 2.4, 2.5; decisions 11 to 13, 23) on the QEMU machine (hypervisor=on).

What it proves, one scenario after another (a failure halts with the number of the check in r0):
  T1  a guest with its translation off reads and writes a guest-physical page that stage 2 puts at another physical address (guest-physical + 32 MiB), and the hypervisor sees it there and not at the guest's address;
  T2  stage 1 and stage 2 composed (the guest's page-table reads go through stage 2 too): virtual 0x40001000 -> guest-physical 0x201000 -> physical 0x2201000, the code fetched through both;
  T3  a stage-2 fault on a load, a store and an instruction fetch is an exit (code 19 invalid, vectors 19, 20, 18) with HEPC the instruction, HEVA the guest-virtual address, HGPA the guest-physical address
      and HINSN the instruction (0 for the fetch); the hypervisor fills stage 2, issues TLBIA and enters again: the guest retries and completes;
  T4  an entry that refuses (A clear, D clear on a store, U set, a reserved bit) is code 20; a read of a clean page works, the store exits, the hypervisor sets D (dirty tracking);
  T5  a stage-2 miss on a page-table read of the guest's stage-1 walk: WALK flag, HGPA the entry's guest-physical address, HEVA the address the guest was reaching;
  T6  a stage-2 miss on the vector fetch of the guest's TRAP: VEC flag, HGPA = VBR + 8 * vector, HEPC the TRAP itself, nothing changed (EPC and ECAUSE of the guest); then the same for a virtual interrupt (the
      line stays pending); after the fill the exception is taken;
  T7  PROBER and PROBEW test both stages: a stage-2 miss exits (HINSN the probe), a stage-1 miss returns 0 with no exit;
  T8  a stale translation after a stage-2 change without an invalidate is observable, and gone after TLBIA at H = 1, or after TLBI of its page (the other page stays stale);
  T9  the guest tag: two guests with the same guest-virtual address and different contents (the tag keeps them apart); an entry of a tag survives the run of another and goes stale; a write to GTBR that changes
      the root discards the entries of its tag (rule G-c), one that changes only the tag does not; a guest's own TLBIA acts on its own tag only (G-a); TLBIA at H = 1 acts on the tag in GTBR (G-d).
"""
import os
import sys
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'sim'))
from gen_hv import Prog, KPSW, PSW_VALID   # noqa: E402

LEAF = '(1<<PTE_V|1<<PTE_R|1<<PTE_W|1<<PTE_X|1<<PTE_A|1<<PTE_D)'
OFF = 0x2000000                        # stage 2 maps guest-physical g (g >= 2 MiB) to physical g + OFF
p = Prog()
n_lab = [0]


def e(t):
    p.e(t)


def st(addr, val):
    """a 64-bit store at a physical address, by the hypervisor (H = 1 is untranslated); an address that starts with a lower-case letter is a label expression"""
    if addr[0].islower():
        e('\tlea\t%s, r25\n\tmovq\t=(%s), r26\n\tmovq\tr26, (r25)' % (addr, val))
    else:
        e('\tmovq\t=(%s), r25\n\tmovq\t=(%s), r26\n\tmovq\tr26, (r25)' % (addr, val))


def ld(addr, reg='r27'):
    e('\tmovq\t=(%s), r25\n\tmovq\t(r25), %s' % (addr, reg))


def enter(label, psw=0, back=None):
    back = back or 'B%d' % (n_lab.__setitem__(0, n_lab[0] + 1) or n_lab[0])
    e('\tlea\t%s, r22\n\tmtsr\thepc, r22\n\tmovq\t=(%s), r22\n\tmtsr\thepsw, r22\n\tlea\t%s, r20\n\tmovq\t#99, r0\n\tgenter\n%s:' % (label, psw, back, back))


def resume():
    """enter again where the exit left HEPC and HEPSW"""
    back = 'B%d' % (n_lab.__setitem__(0, n_lab[0] + 1) or n_lab[0])
    e('\tlea\t%s, r20\n\tmovq\t#99, r0\n\tgenter\n%s:' % (back, back))


def exit_is(code, vec, epc, eva=0, gpa=0, flags='0', insn='skip'):
    for reg, val in (('hexitr', '(%s)|(%s)' % (code, flags)), ('hcause', vec), ('heva', eva), ('hgpa', gpa)):
        e('\tmfsr\tr22, %s' % reg)
        p.eq('r22', val)
    e('\tmfsr\tr22, hepc\n\tlea\t%s, r23' % epc)
    p.cbne('r22', 'r23')
    if insn == 'skip':
        return
    e('\tmfsr\tr22, hinsn')
    if insn:
        e('\tshr\t#16, r22\n\tmovzw\t%s, r23' % insn)
        p.cbne('r22', 'r23')
    else:
        p.cbne('r22', '#0')


def halted():
    e('\tmfsr\tr22, hexitr')
    p.eq('r22', 'XCODE_HALT')


def pte_phys(l0, idx):                 # the address of an entry of a stage-2 level-0 table
    return '%s+%d' % (l0, idx * 8)


S2L0 = 's2l0'
S2L0B = 's2l0b'
GUEST = 'GUEST'
e('; GENERATED by tests/qemu/gen_hv_stage2.py: do not edit.  Stage 2 of the hypervisor mode: see the generator for what each scenario proves.')
e('#include "pdp64-consts.h"\n#define LEAF %s\n#define PHYS(g) ((g)+%d)\n\t.text\n\t.globl\t_start\n_start:' % (LEAF, OFF))
e('\tlea\thtab, r1\n\tmtsr\thvbr, r1\n\tlea\txh, r22\n\tmovq\t#512, r23\nfill1:\tmovq\tr22, (r1)+\n\tsob\tr23, fill1')
e('\tlea\tgvtab, r1\n\tmtsr\tvbr, r1\n\tlea\tgh, r22\n\tmovq\t#512, r23\nfill2:\tmovq\tr22, (r1)+\n\tsob\tr23, fill2')
e('\tlea\tgstk_top, r22\n\tmtsr\tgksp, r22\n\tmovq\t#0, r1\n\tmtsr\thtrap, r1')
# ---- the stage-2 tables, tree A (root s2root) and tree B (root s2rootb): the first 2 MiB identity (the code and the tables), 2 to 4 MiB at +OFF, 4 to 6 MiB by 4 KB pages at +OFF (16 of them)
for root, l1, l0 in (('s2root', 's2l1', 's2l0'), ('s2rootb', 's2l1b', 's2l0b')):
    e('\tlea\t%s, r1\n\tbis\t#(1<<PTE_V), r1\n\tmovq\tr1, %s' % (l1, root))
    e('\tmovq\t=(LEAF), r1\n\tmovq\tr1, %s' % l1)
    e('\tmovq\t=(PHYS(0x200000)|LEAF), r1\n\tmovq\tr1, %s+8' % l1)
    e('\tlea\t%s, r1\n\tbis\t#(1<<PTE_V), r1\n\tmovq\tr1, %s+16' % (l0, l1))
    for i in range(16):
        e('\tmovq\t=(PHYS(0x%x)|LEAF), r1\n\tmovq\tr1, %s+%d' % (0x400000 + 0x1000 * i, l0, 8 * i))
# ---- the guest's stage-1 tables (guest-physical = physical here: the first 2 MiB), root g1root: 1 GiB identity at index 0; index 1 -> g1l1 -> g1l0 (4 KB pages): 0x40000000 -> GPA 0x200000, 0x40001000 -> 0x201000
e('\tmovq\t=(LEAF), r1\n\tmovq\tr1, g1root')
e('\tlea\tg1l1, r1\n\tbis\t#(1<<PTE_V), r1\n\tmovq\tr1, g1root+8')
e('\tlea\tg1l0, r1\n\tbis\t#(1<<PTE_V), r1\n\tmovq\tr1, g1l1')
e('\tmovq\t=(0x200000|LEAF), r1\n\tmovq\tr1, g1l0\n\tmovq\t=(0x201000|LEAF), r1\n\tmovq\tr1, g1l0+8')
# the second stage-1 root g1b: index 1 -> a level-1 table at GPA 0x407000 (not in stage 2 at first), written by the hypervisor at its physical address
e('\tmovq\t=(LEAF), r1\n\tmovq\tr1, g1broot')
e('\tmovq\t=(0x407000|(1<<PTE_V)), r1\n\tmovq\tr1, g1broot+8')
e('\tlea\tg1l0, r1\n\tbis\t#(1<<PTE_V), r1\n\tmovq\t=(PHYS(0x407000)), r25\n\tmovq\tr1, (r25)')

def gtbr(root, tag):
    return '(%s_PA)|(1<<GTBR_S2EN)|(%d<<GTBR_TAG)' % (root, tag)

def set_gtbr(root, tag):
    e('\tlea\t%s, r22\n\tmovq\t=(%d<<GTBR_TAG|1<<GTBR_S2EN), r23\n\tbis\tr23, r22\n\tmtsr\tgtbr, r22' % (root, tag))
set_gtbr('s2root', 1)
e('\tmfsr\tr22, gtbr\n\tlea\ts2root, r24\n\tmovq\t=(1<<GTBR_S2EN|1<<GTBR_TAG), r23\n\tbis\tr23, r24')
p.cbne('r22', 'r24')
# =====================================================================================================================================================
e('\t; --- T1: translation off, stage 2 only: guest-physical 0x200000 is at physical 0x2200000')
st('PHYS(0x200000)', '0xa1a1')
st('0x200008', '0')
enter('g1')
exit_is('XCODE_HALT', 'VECTOR_HEXIT', 'g1e')
e('\tmovq\t=(PHYS(0x200008)), r25\n\tmovq\t(r25), r27')
p.eq('r27', '0x77')
p.eq('r1', '0xa1a1')
e('\tmovq\t=(0x200008), r25\n\tmovq\t(r25), r27')
p.eq('r27', '0')
# T2: stage 1 on, tables in guest-physical memory (identity in the first 2 MiB)
e('\t; --- T2: stage 1 and stage 2 composed')
st('PHYS(0x201000)', '0xb2b2')
e('\tlea\tg1root, r22\n\tmtsr\tptbr, r22\n\tmovq\t#1, r22\n\tmtsr\tmmuctl, r22')
enter('g2')
exit_is('XCODE_HALT', 'VECTOR_HEXIT', 'g2e')
p.eq('r1', '0xb2b2')
e('\tmovq\t=(PHYS(0x201010)), r25\n\tmovq\t(r25), r27')
p.eq('r27', '0x88')
e('\tmovq\t#0, r22\n\tmtsr\tmmuctl, r22')
# T3: faults
e('\t; --- T3: stage-2 faults are exits; the hypervisor fills stage 2 and the guest retries')
st('PHYS(0x401008)', '0xc3c3')
st(pte_phys(S2L0, 1), '0')
enter('g3l', back='T3a')
exit_is('XCODE_S2_INVALID', 'VECTOR_GLFAULT', 'g3li', '0x401008', '0x401008', '0', 'g3li')
e('\tmfsr\tr22, epc')
p.eq('r22', '0')
st(pte_phys(S2L0, 1), '(PHYS(0x401000)|LEAF)')
e('\ttlbia\n\ttlbsync')
resume()
halted()
p.eq('r1', '0xc3c3')
st(pte_phys(S2L0, 1), '0')
e('\ttlbia')
enter('g3s', back='T3b')
exit_is('XCODE_S2_INVALID', 'VECTOR_GSFAULT', 'g3si', '0x401010', '0x401010', '0', 'g3si')
st(pte_phys(S2L0, 1), '(PHYS(0x401000)|LEAF)')
e('\ttlbia')
resume()
halted()
e('\tmovq\t=(PHYS(0x401010)), r25\n\tmovq\t(r25), r27')
p.eq('r27', '0xd4d4')
st(pte_phys(S2L0, 2), '0')
e('\ttlbia')
enter('g3f', back='T3c')
e('\tmfsr\tr22, hexitr')
p.eq('r22', 'XCODE_S2_INVALID')
e('\tmfsr\tr22, hcause')
p.eq('r22', 'VECTOR_GIFAULT')
e('\tmfsr\tr22, hepc')
p.eq('r22', '0x402000')
e('\tmfsr\tr22, heva')
p.eq('r22', '0x402000')
e('\tmfsr\tr22, hgpa')
p.eq('r22', '0x402000')
e('\tmfsr\tr22, hinsn')
p.cbne('r22', '#0')
st(pte_phys(S2L0, 2), '(PHYS(0x402000)|LEAF)')
# the code at guest-physical 0x402000 (physical 0x2402000): a store of 0x99 to r1 then halt, written by the hypervisor
e('\tmovq\t=(PHYS(0x402000)), r25\n\tmovq\tcode_ret_, r26\n\tmovq\tr26, (r25)')
e('\ttlbia')
resume()
halted()
p.eq('r1', '0x99')
# T4: refusals
e('\t; --- T4: an entry that refuses: A clear, D clear on a store, U set, a reserved bit')
st('PHYS(0x403008)', '0xe5e5')
st(pte_phys(S2L0, 3), '(PHYS(0x403000)|(LEAF&~(1<<PTE_A)))')
e('\ttlbia')
enter('g4a', back='T4a')
exit_is('XCODE_S2_REFUSED', 'VECTOR_GLFAULT', 'g4ai', '0x403008', '0x403008', '0', 'g4ai')
st(pte_phys(S2L0, 3), '(PHYS(0x403000)|LEAF)')
e('\ttlbia')
resume()
halted()
p.eq('r1', '0xe5e5')
st('PHYS(0x404008)', '0xf6f6')
st(pte_phys(S2L0, 4), '(PHYS(0x404000)|(LEAF&~(1<<PTE_D)))')
e('\ttlbia')
enter('g4d', back='T4b')
exit_is('XCODE_S2_REFUSED', 'VECTOR_GSFAULT', 'g4ds', '0x404010', '0x404010', '0', 'g4ds')
p.eq('r1', '0xf6f6')                                  # the read of the clean page worked
st(pte_phys(S2L0, 4), '(PHYS(0x404000)|LEAF)')       # dirty tracking: the hypervisor sets D
e('\ttlbia')
resume()
halted()
e('\tmovq\t=(PHYS(0x404010)), r25\n\tmovq\t(r25), r27')
p.eq('r27', '0x5151')
st(pte_phys(S2L0, 5), '(PHYS(0x405000)|LEAF|(1<<PTE_U))')
e('\ttlbia')
enter('g4u', back='T4c')
exit_is('XCODE_S2_REFUSED', 'VECTOR_GLFAULT', 'g4ui', '0x405008', '0x405008', '0', 'g4ui')
st(pte_phys(S2L0, 5), '(PHYS(0x405000)|LEAF|(1<<62))')
e('\ttlbia')
resume()
e('\tmfsr\tr22, hexitr')
p.eq('r22', 'XCODE_S2_REFUSED')
st(pte_phys(S2L0, 5), '(PHYS(0x405000)|LEAF)')
e('\ttlbia')
# T5: a stage-2 miss on a page-table read of the guest
e('\t; --- T5: the guest\'s stage-1 walk reads a table at guest-physical 0x407000, which stage 2 does not map: WALK')
st('PHYS(0x200008)', '0x7a7a')
st(pte_phys(S2L0, 7), '0')
e('\tlea\tg1broot, r22\n\tmtsr\tptbr, r22\n\tmovq\t#1, r22\n\tmtsr\tmmuctl, r22')
enter('g5', back='T5a')
exit_is('XCODE_S2_INVALID', 'VECTOR_GLFAULT', 'g5i', '0x40000008', '0x407000', '1<<XFLAG_WALK', 'g5i')
st(pte_phys(S2L0, 7), '(PHYS(0x407000)|LEAF)')
e('\ttlbia')
resume()
halted()
p.eq('r1', '0x7a7a')
e('\tmovq\t#0, r22\n\tmtsr\tmmuctl, r22')
# T6: the vector fetch
e('\t; --- T6: a stage-2 miss on the guest\'s vector fetch: VEC, nothing changed, the instruction is run again')
st(pte_phys(S2L0, 8), '0')
e('\tmovq\t=0x408000, r22\n\tmtsr\tvbr, r22\n\tmovq\t=0x1234, r22\n\tmtsr\tgecause, r22')
e('\tmovq\t=0x5678, r22\n\tmtsr\tepc, r22\n\ttlbia')
enter('g6', back='T6a')
exit_is('XCODE_S2_INVALID', 'VECTOR_GLFAULT', 'g6', '0', '0x408000+8*(VECTOR_TRAP_BASE+1)', '1<<XFLAG_VEC', 'g6')
e('\tmfsr\tr22, epc')
p.eq('r22', '0x5678')
e('\tmfsr\tr22, ecause')
p.eq('r22', '0x1234')
st(pte_phys(S2L0, 8), '(PHYS(0x408000)|LEAF)')
e('\tlea\tgh, r22\n\tmovq\t=(PHYS(0x408000+8*(VECTOR_TRAP_BASE+1))), r25\n\tmovq\tr22, (r25)\n\ttlbia')
resume()
halted()
e('\tmfsr\tr22, ecause')
p.eq('r22', 'VECTOR_TRAP_BASE+1')
e('\tmfsr\tr22, epc\n\tlea\tg6e, r23')
p.cbne('r22', 'r23')
# a virtual interrupt whose vector fetch misses stage 2: the line stays pending
st(pte_phys(S2L0, 8), '0')
e('\ttlbia\n\tmovq\t=(100<<16), r22\n\tmtsr\tvivec, r22\n\tmovq\t#(1<<3), r22\n\tmtsr\tvirq, r22\n\tmovq\t#0, r22\n\tmtsr\tepc, r22')
enter('g6v', back='T6b')
exit_is('XCODE_S2_INVALID', 'VECTOR_GLFAULT', 'g6v', '0', '0x408000+8*100', '1<<XFLAG_VEC', None)
e('\tmfsr\tr22, virq')
p.eq('r22', '1<<3')
e('\tmfsr\tr22, epc')
p.eq('r22', '0')
st(pte_phys(S2L0, 8), '(PHYS(0x408000)|LEAF)')
e('\tlea\tgh, r22\n\tmovq\t=(PHYS(0x408000+8*100)), r25\n\tmovq\tr22, (r25)\n\ttlbia')
resume()
halted()
e('\tmfsr\tr22, virq')
p.eq('r22', '0')
e('\tmfsr\tr22, ecause')
p.eq('r22', '100')
e('\tmovq\t#0, r22\n\tmtsr\tvbr, r22\n\tlea\tgvtab, r22\n\tmtsr\tvbr, r22')
# T7: probes
e('\t; --- T7: PROBER and PROBEW test both stages: a stage-2 miss exits, a stage-1 miss gives 0')
st(pte_phys(S2L0, 9), '0')
e('\ttlbia')
enter('g7r', back='T7a')
exit_is('XCODE_S2_INVALID', 'VECTOR_GLFAULT', 'g7ri', '0x409000', '0x409000', '0', 'g7ri')
st(pte_phys(S2L0, 9), '(PHYS(0x409000)|(LEAF&~(1<<PTE_D)))')
e('\ttlbia')
enter('g7w', back='T7b')
exit_is('XCODE_S2_REFUSED', 'VECTOR_GSFAULT', 'g7wi', '0x409000', '0x409000', '0', 'g7wi')
st(pte_phys(S2L0, 9), '(PHYS(0x409000)|LEAF)')
e('\ttlbia')
resume()
halted()
p.eq('r4', '1')
e('\tlea\tg1root, r22\n\tmtsr\tptbr, r22\n\tmovq\t#1, r22\n\tmtsr\tmmuctl, r22')
enter('g7s', back='T7c')
halted()
p.eq('r4', '0')                                      # a stage-1 miss: 0, no exit
e('\tmovq\t#0, r22\n\tmtsr\tmmuctl, r22')
# T8: stale and invalidate
e('\t; --- T8: a stage-2 change with no invalidate is not seen; TLBIA at H = 1 (the tag in GTBR) and TLBI of the page make it seen')
st('PHYS(0x40a000)', '0xaaaa')
st('PHYS(0x40b000)', '0xbbbb')
st('PHYS(0x40c000)', '0xcccc')
st('PHYS(0x40d000)', '0xdddd')
for pg, a in ((10, 0x40a000), (11, 0x40b000)):
    st(pte_phys(S2L0, pg), '(PHYS(0x%x)|LEAF)' % a)
e('\ttlbia')
enter('g8', back='T8a')
halted()
p.eq('r1', '0xaaaa')
p.eq('r4', '0xbbbb')
st(pte_phys(S2L0, 10), '(PHYS(0x40c000)|LEAF)')
st(pte_phys(S2L0, 11), '(PHYS(0x40d000)|LEAF)')
enter('g8', back='T8b')                              # no invalidate: still the old pages
p.eq('r1', '0xaaaa')
p.eq('r4', '0xbbbb')
e('\tmovq\t=0x40a000, r22\n\ttlbi\tr22')
enter('g8', back='T8c')                              # TLBI of the page of 10: new; page 11 is still stale
p.eq('r1', '0xcccc')
p.eq('r4', '0xbbbb')
e('\ttlbia')
enter('g8', back='T8d')                              # TLBIA: both new
p.eq('r1', '0xcccc')
p.eq('r4', '0xdddd')
# T9: the guest tag
e('\t; --- T9: the guest tag; rules G-a to G-d')
for pg, a_ in ((10, 0x40a000), (11, 0x40b000)):
    st(pte_phys(S2L0, pg), '(PHYS(0x%x)|LEAF)' % a_)
st('PHYS(0x40e000)', '0xeeee')
st(pte_phys(S2L0B, 10), '(PHYS(0x40e000)|LEAF)')
st(pte_phys(S2L0B, 11), '(PHYS(0x40a000)|LEAF)')
e('\t; (1) two roots: the same guest-virtual addresses, different contents; the entries of tag 1 are in the cache while tag 2 runs and must not be used for it')
set_gtbr('s2root', 1)
e('\ttlbia')
enter('g8', back='T9a')
p.eq('r1', '0xaaaa')
p.eq('r4', '0xbbbb')
set_gtbr('s2rootb', 2)
e('\ttlbia')
enter('g8', back='T9b')
p.eq('r1', '0xeeee')
p.eq('r4', '0xaaaa')
e('\t; (2) two tags on one root: a write that changes only the tag discards nothing, so the entries of a tag survive the run of the other (and go stale)')
set_gtbr('s2root', 1)
e('\ttlbia')
set_gtbr('s2root', 2)
e('\ttlbia')
set_gtbr('s2root', 1)
enter('g8', back='T9c')
p.eq('r1', '0xaaaa')
p.eq('r4', '0xbbbb')
set_gtbr('s2root', 2)
enter('g8', back='T9d')
p.eq('r1', '0xaaaa')
st(pte_phys(S2L0, 10), '(PHYS(0x40c000)|LEAF)')
st(pte_phys(S2L0, 11), '(PHYS(0x40d000)|LEAF)')
set_gtbr('s2root', 1)
enter('g8', back='T9e')
p.eq('r1', '0xaaaa')                                 # tag 1's entries survived tag 2's run: stale
p.eq('r4', '0xbbbb')
e('\t; (3) G-a: the guest of tag 2 executes TLBIA: its own entries go, tag 1\'s stay')
set_gtbr('s2root', 2)
enter('g8t', back='T9f')
p.eq('r1', '0xcccc')
set_gtbr('s2root', 1)
enter('g8', back='T9g')
p.eq('r1', '0xaaaa')
p.eq('r4', '0xbbbb')
e('\t; (4) G-d: TLBIA at H = 1 with the tag 1 in GTBR discards tag 1\'s entries and not tag 2\'s')
e('\ttlbia')
enter('g8', back='T9h')
