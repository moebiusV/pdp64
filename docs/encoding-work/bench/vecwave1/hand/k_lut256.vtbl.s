; lut256 with the 16-entry table lookup: out[i] = t[in[i]] for a 256-byte table, as 16 lookups of 16 entries each (vtbl.b gives 0 for an index of 16 or more),
; the high nibble of the index choosing the slice (vceq + vbsl).  The table slices are named by 16 pointer registers (vtbl.b has the (Ra) form only); r24..r31 are saved.
; r0 = t, r1 = in, r2 = out, r3 = n.
k_lut256:
	push	r24
	push	r25
	push	r26
	push	r27
	push	r28
	push	r29
	push	r30
	push	r31
	lea	0(r0),r16
	lea	16(r0),r17
	lea	32(r0),r18
	lea	48(r0),r19
	lea	64(r0),r20
	lea	80(r0),r21
	lea	96(r0),r22
	lea	112(r0),r23
	lea	128(r0),r24
	lea	144(r0),r25
	lea	160(r0),r26
	lea	176(r0),r27
	lea	192(r0),r28
	lea	208(r0),r29
	lea	224(r0),r30
	lea	240(r0),r31
	lea	(r1)(r3),r9
	vec	r1,r9
	vld.b	v0,(r1)+
	vand.b	v1,v0,#15
	vshr.b	v2,v0,#4
	vmov.b	v5,#0
	vtbl.b	v4,(r16),v1
	vceq.b	v3,v2,#0
	vbsl	v5,v3,v4,v5
	vtbl.b	v4,(r17),v1
	vceq.b	v3,v2,#1
	vbsl	v5,v3,v4,v5
	vtbl.b	v4,(r18),v1
	vceq.b	v3,v2,#2
	vbsl	v5,v3,v4,v5
	vtbl.b	v4,(r19),v1
	vceq.b	v3,v2,#3
	vbsl	v5,v3,v4,v5
	vtbl.b	v4,(r20),v1
	vceq.b	v3,v2,#4
	vbsl	v5,v3,v4,v5
	vtbl.b	v4,(r21),v1
	vceq.b	v3,v2,#5
	vbsl	v5,v3,v4,v5
	vtbl.b	v4,(r22),v1
	vceq.b	v3,v2,#6
	vbsl	v5,v3,v4,v5
	vtbl.b	v4,(r23),v1
	vceq.b	v3,v2,#7
	vbsl	v5,v3,v4,v5
	vtbl.b	v4,(r24),v1
	vceq.b	v3,v2,#8
	vbsl	v5,v3,v4,v5
	vtbl.b	v4,(r25),v1
	vceq.b	v3,v2,#9
	vbsl	v5,v3,v4,v5
	vtbl.b	v4,(r26),v1
	vceq.b	v3,v2,#10
	vbsl	v5,v3,v4,v5
	vtbl.b	v4,(r27),v1
	vceq.b	v3,v2,#11
	vbsl	v5,v3,v4,v5
	vtbl.b	v4,(r28),v1
	vceq.b	v3,v2,#12
	vbsl	v5,v3,v4,v5
	vtbl.b	v4,(r29),v1
	vceq.b	v3,v2,#13
	vbsl	v5,v3,v4,v5
	vtbl.b	v4,(r30),v1
	vceq.b	v3,v2,#14
	vbsl	v5,v3,v4,v5
	vtbl.b	v4,(r31),v1
	vceq.b	v3,v2,#15
	vbsl	v5,v3,v4,v5
	vst.b	v5,(r2)+
	vend
	pop	r31
	pop	r30
	pop	r29
	pop	r28
	pop	r27
	pop	r26
	pop	r25
	pop	r24
	ret
