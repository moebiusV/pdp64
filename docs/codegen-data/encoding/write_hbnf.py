#!/usr/bin/env python3
"""write_hbnf -- write the generated parts of the encoding grammar: three whole files, parts of the drop-in directory spec/grammars.d/ (errata 179, 180).

The grammar is the source of truth of the encoding (spec/README.md, "The grammars").  The text a person edits and the text a tool writes are in different parts:

    spec/grammars.d/20-enc-forms.hbnf    GENERATED: the catalogue `forms`, and the forms and leaves, family by family (a form is `form-NAME`, a leaf `leaf-NAME-K` with its `sub-NAME-K` words)
    spec/grammars.d/21-enc-shapes.hbnf   GENERATED: the operand shapes of the forms, and `noop`
    spec/grammars.d/80-mn-ext.hbnf       GENERATED: the group mn-ext, the words only the prefix-coded encoding has (and the aliases)

(`insn`, the root, is the part 10-enc-insn.hbnf, written by tools/grammars_d.py from every leaf of every part, so that a hand-written family in a part of its own is in it.)
This writes the three parts and nothing else: never a part that a person edits.  The optimiser (export.py --write-grammar) and tools/encopt/addforms.py (the vec family) call
write_all().  Each part begins with the line `; GENERATED by ... do not edit` and has its `; targets:` line; tools/check-grammar-enc.sh checks that.

    write_hbnf.py OUTDIR 32=forms32.json      write OUTDIR/20-enc-forms.hbnf, 21-enc-shapes.hbnf, 80-mn-ext.hbnf
    (export_forms.py's dict, or what tools/encgram.py.load() returns; the JSON form is only for running this on a dict someone kept)

The vocabulary of the grammars (rule and field names) is defined in the header of spec/grammars.d/22-enc-vocabulary.hbnf; tools/encgram.py is its reader.
"""
import json, os, re, sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..', '..', 'tools'))
from encgram import guard_text, leaf_pieces, runs as _runs



def mangle(name):
    return re.sub(r'[./_]', '-', name)


def family(name):
    """The family of a form, as the optimiser groups them (docs/codegen-data/encoding/fam.py)."""
    k = re.sub(r'(_?\d+)?(/.*)?$', '', name)
    return re.sub(r'[hH]$', '', k) if len(k) > 4 else k


# ---------------------------------------------------------------- shapes
def shape(s):
    """(rule name, body) of an operand spec.  The name carries the kind and the attributes the body cannot (scale, unit, signedness of an absent field)."""
    k = s['k']
    sg = lambda v: 's' if v else 'u'
    def fld(name, w, signed=False):
        return '%s:%d%s' % (name, w, 's' if signed and w else '') if w else None
    if k == 'R':
        return 'reg%d' % s['w'], 'r:%d' % s['w']
    if k == 'V':
        return '%sreg%d' % (s['cls'], s['w']), '%s:%d' % (s['cls'], s['w'])
    if k == 'K':
        kind, v = s['op']
        if kind == 'R':
            return {14: ('k-sp', 'sp:bits(0)'), 16: ('k-dp', 'dp:bits(0)')}.get(v) or ('k-r%d' % v, 'r%d:bits(0)' % v)
        return 'k-imm%d' % v, 'imm%d:bits(0)' % v
    if k == 'I':
        assert s['vals'] is None
        sc = '' if s['scale'] == 1 else '-x%d' % s['scale']
        return 'imm%d%s%s' % (s['w'], sg(s['signed']), sc), fld('imm', s['w'], s['signed'])
    if k == 'B':
        rn = s['rn']
        if rn['k'] == 'K':                           # d(sp), d(dp): the base takes no bits
            assert rn['op'][0] == 'R' and rn['op'][1] in (14, 16) and s['dw']
            base, parts = {14: 'sp', 16: 'dp'}[rn['op'][1]], []
        else:
            base, parts = 'b%d' % rn['w'], ['base:%d' % rn['w']]
        parts += [fld('d', s['dw'], s['signed'])] if s['dw'] else []
        return '%sd%d%s-x%s' % (base if rn['k'] == 'K' else base, s['dw'], sg(s['signed']), s['scale']), ' '.join(parts) or 'none:bits(0)'
    if k == 'X':
        a, b = s['rn']['w'], s['rx']['w']
        parts = ['base:%d' % a, 'index:%d' % b, 'scale:2'] + ([fld('d', s['dw'], s['signed'])] if s['dw'] else [])
        return 'x%d-%dd%d%s' % (a, b, s['dw'], sg(s['signed'])), ' '.join(parts)
    if k in ('PI', 'PD'):
        rw = s['rn']['w']
        return '%s%d-s%d' % (k.lower(), rw, s['dw']), ' '.join(['base:%d' % rw] + (['stride:%d' % s['dw']] if s['dw'] else []))
    if k == 'PC':
        return 'pc%d-u%d' % (s['w'], s['unit']), 'pcrel:%d' % s['w']
    if k == 'A':
        return 'abs%d' % s['w'], 'abs:%d' % s['w']
    raise ValueError(k)



# ---------------------------------------------------------------- text helpers
def wrap(head, items, sep=' | ', width=150, cont='     | '):
    """head + items joined by sep, wrapped before an item that would pass the width; the continuation lines begin with `cont`."""
    lines = []
    cur = head + items[0]
    for it in items[1:]:
        if len(cur) + len(sep) + len(it) > width:
            lines.append(cur)
            cur = cont + it
        else:
            cur += sep + it
    lines.append(cur)
    return '\n'.join(lines)


# ---------------------------------------------------------------- the generated files
def gen_header(what, targets):
    """the first lines of a generated part: the marker that tools/check-grammar-enc.sh looks for, the targets line, what the part holds"""
    return ('; GENERATED by tools/encopt/addforms.py (through docs/codegen-data/encoding/write_hbnf.py) from the forms of the encoding: do not edit.\n'
            '; targets: %s\n'
            '; %s\n'
            '; Text a person edits goes in a part of its own (spec/README.md, "How a part is added"; errata 179, 180).\n' % (targets, what))


def write_shapes(ds):
    shapes = {}
    for d in ds:
        for f in d['forms']:
            for s in f['specs']:
                n, b = shape(s)
                assert shapes.setdefault(n, b) == b, (n, b, shapes[n])
    out = [gen_header('The operand shapes the forms use (their vocabulary is in the header of 22-enc-vocabulary.hbnf) and `noop`.', 'enc')]
    kinds = [('R', 'a register', lambda n: n.startswith('reg')),
             ('V', 'a vector register (a hidden register of the vec block)', lambda n: re.match(r'[vt]reg\d', n)),
             ('K', 'a constant operand (no bits)', lambda n: n.startswith('k-')),
             ('I', 'an immediate', lambda n: n.startswith('imm')),
             ('B', 'base register and displacement: d(rb)', lambda n: re.match(r'(b\d|sp|dp)', n)),
             ('X', 'indexed: d(rb,rx,scale)', lambda n: n.startswith('x')),
             ('P', 'auto-increment (r)+ and auto-decrement -(r)', lambda n: n[:2] in ('pi', 'pd')),
             ('C', 'pc-relative', lambda n: n.startswith('pc')),
             ('A', 'absolute', lambda n: n.startswith('abs'))]
    seen = set()
    for key, title, pred in kinds:
        names = sorted((n for n in shapes if pred(n) and n not in seen), key=lambda n: (len(n), n))
        if not names:
            continue
        out.append('; ---- operand shapes: %s\n' % title)
        for n in names:
            seen.add(n)
            out.append('%-14s = %s' % (n, shapes[n]))
        out.append('')
    assert seen == set(shapes), set(shapes) - seen
    out.append('; ---- no operand\nnoop           = none:bits(0)')
    return '\n'.join(out) + '\n'


EXT_ALIASES = [('cthis', 'ctcc'), ('ctlo', 'ctcs'), ('fcbgt', 'fcblt'), ('fcbge', 'fcble'), ('fcbgt32', 'fcblt32'), ('fcbge32', 'fcble32'), ('setlo', 'setcs'), ('sethis', 'setcc')]	# the compare-and-trap's spellings, as bhis and blo are the branches' (errata 152): the number is 0x1000 plus that of the word (the words of mn-ext go past 256)


def write_ext(words):
    """mn-ext: the words of the prefix-coded encodings that the original mnemonic grammar does not have; the number is the position (the C table ext_names); an alias is 0x1000 plus the number of its word."""
    items = ['"%s"@%d' % (w, i) for i, w in enumerate(words)] + ['"%s"@%d' % (a, 0x1000 + words.index(t)) for a, t in EXT_ALIASES if t in words]
    return gen_header('The words of the forms that no hand-written group mn-NAME numbers.', 'asm enc') + \
           '\n; ---- the mnemonics that only the prefix-coded encodings have (group mn-ext of the assembly grammar of as64): the number is the position in the list; an alias is 0x1000 plus the number of its word\n' + \
           wrap('mn-ext = ', items, cont='       | ') + '\n'


# ---------------------------------------------------------------- a member
def write_forms(d):
    forms, leaves = d['forms'], d['leaves']
    names = [mangle(f['name']) for f in forms]
    assert len(set(names)) == len(names) and len(set(n.lower() for n in names)) == len(names), 'form names collide when mangled'
    out = []
    o = out.append
    o(gen_header('The catalogue of forms, the forms and the leaves: %d forms, %d leaves.  `insn` (10-enc-insn.hbnf, tools/grammars_d.py) lists the leaves; a part may add forms of its own (`forms =/ "NAME"`).' % (len(forms), len(leaves)), 'enc'))
    o('; A first parcel that no leaf matches is an illegal instruction (the number of them is in spec/pdp64/tables.md).')
    # the catalogue
    o('; ---- the catalogue of forms: the number is the index of the form (the assembler tries the forms of a mnemonic, shorter first, in this order)')
    o(wrap('forms = ', ['"%s"@%d' % (f['name'], i) for i, f in enumerate(forms)], cont='      | '))
    o('')
    # families, in the order of their first form
    fams = []
    for i, f in enumerate(forms):
        fam = family(f['name'])
        if fam not in [x[0] for x in fams]:
            fams.append([fam, []])
        [x for x in fams if x[0] == fam][0][1].append(i)
    byform = {}
    for li, lf in enumerate(leaves):
        byform.setdefault(lf['form'], []).append(li)
    for fam, fidx in fams:
        mns = [m for i in fidx for m in forms[i]['mns']]
        o('; ' + '=' * 150)
        o('; family %s: %d form%s, %d leaves, %d parcel%s; mnemonics %s%s' % (fam, len(fidx), 's' if len(fidx) > 1 else '', sum(len(byform[i]) for i in fidx),
          forms[fidx[0]]['n'], '' if forms[fidx[0]]['n'] == 1 else 's', ' '.join(mns[:6]), ' ...' if len(mns) > 6 else ''))
        o('; ' + '=' * 150 + '\n')
        for fi in fidx:
            f = forms[fi]
            o('; form %s (index %d): %d parcel%s' % (f['name'], fi, f['n'], '' if f['n'] == 1 else 's'))
            if f['specs']:
                o('form-%s = %s' % (names[fi], ' '.join('o%d:%s' % (k + 1, shape(s)[0]) for k, s in enumerate(f['specs']))))
            else:
                o('form-%s = noop' % names[fi])
            for k, li in enumerate(byform[fi]):
                lf = leaves[li]
                o(write_leaf(lf, f, names[fi], k + 1, d))
            o('')
    return '\n'.join(out) + '\n'


def write_leaf(lf, f, mname, k, d):
    n16 = 16 * f['n']
    L = lf['L']
    nm = len(lf['mns'])
    pcs = leaf_pieces(lf, f['specs'])
    flds = ['0b' + format(lf['prefix'], '0%db' % L)] + ['%s:%d' % (name, w) for _, name, w, _ in pcs]
    assert L + sum(w for _, _, w, _ in pcs) == n16, (f['name'], lf)
    # the check that rejects the unused sub-opcodes
    for key in (('sub',), ('xsub',)):
        ws = [w for _, _, w, kk in pcs if kk == key]
        if ws and nm < 1 << sum(ws):
            flds.append(guard_text(key[0], ws, nm))
    leaf = 'leaf-%s-%d' % (mname, k)
    text = wrap('%s = ' % leaf, flds, sep=' ', width=150, cont='        ')
    en = wrap('sub-%s-%d = ' % (mname, k), ['"%s"' % m for m in lf['mns']], cont='     | ')
    return text + '\n' + en


# ---------------------------------------------------------------- main
def write_all(out, ds):
    """ds = [(tag, dict)], one member; writes out/21-enc-shapes.hbnf, out/80-mn-ext.hbnf and out/20-enc-forms.hbnf: whole parts, never a file a person edits"""
    ds = [x for x in ds if x[0] == '32']             # the pdp64 is the 32-register encoding; the 16-register study (export_forms.py writes both) has no grammar any more
    assert len(ds) == 1, 'write_all wants the member 32'
    sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..', '..', 'tools'))
    import mkgrammar
    en = mkgrammar.enums()
    old = {lit for g, items in en.items() if g.startswith('mn-') for lit, v in items}
    allmn = sorted({m for _, d in ds for f in d['forms'] for m in f['mns']} - old)
    os.makedirs(out, exist_ok=True)
    open(os.path.join(out, '21-enc-shapes.hbnf'), 'w').write(write_shapes([d for _, d in ds]))
    open(os.path.join(out, '80-mn-ext.hbnf'), 'w').write(write_ext(allmn))
    open(os.path.join(out, '20-enc-forms.hbnf'), 'w').write(write_forms(ds[0][1]))


def main():
    ds = []
    for a in sys.argv[2:]:
        tag, path = a.split('=')
        ds.append((tag, json.load(open(path))))
    write_all(sys.argv[1], ds)


if __name__ == '__main__':
    main()
