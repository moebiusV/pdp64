#!/usr/bin/env python3
"""gen-core-names.py -- the executor's name table of the core instructions (hdefs[]), from spec/facts/core.toml (errata 184).

    tools/gen-core-names.py            write common/pdp64exec_corehdefs.inc: the table `hdefs[]` { word, handler kind, argument } that common/pdp64exec_enc.inc includes
    tools/gen-core-names.py --check    exit 1 if the file on disk differs, or if the executor and the facts disagree: every `exec` of the facts is a handler kind of the enum of
                                       pdp64exec_enc.inc and has a `case` in its dispatch, and every `case H_x` is the exec of some base (H_VEC, which the vec family sets up, and
                                       H_UNIMPL, the default, excepted)

The executor's semantics (the `case H_xxx` code) and the enum stay hand-written; the name table is the fact."""
import os, re, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, 'tools'))
import facts

OUT = os.path.join(ROOT, 'common', 'pdp64exec_corehdefs.inc')
EXEC = os.path.join(ROOT, 'common', 'pdp64exec_enc.inc')


def rows():
    out = []
    for b, t in facts.load('core').items():
        if t['exec'] == 'H_UNIMPL':
            continue
        out.append((b, t['exec'], t['arg']))
        out += [('%s.%s' % (b, s), t['exec'], t['arg'] + {'u': ' | H_USER', 'ur': ' | H_USERR', 'uw': ' | H_USERW'}.get(s, '')) for s in t.get('exec_dotted', [])]
    return out


def generate():
    lines = ['/* The name table of the core instructions: GENERATED by tools/gen-core-names.py from spec/facts/core.toml (exec, arg, exec_dotted); never edit it. */',
             'static const struct hdef hdefs[] = {']
    row = '\t'
    for n, k, a in rows():
        item = '{ "%s", %s, %s }, ' % (n, k, a)
        if len(row) + len(item) > 150:
            lines.append(row.rstrip())
            row = '\t'
        row += item
    lines.append(row.rstrip())
    lines.append('};')
    return '\n'.join(lines) + '\n'


def problems():
    out = []
    F = facts.load('core')
    src = open(EXEC).read()
    enum = set(re.findall(r'\b(H_[A-Z0-9]+)\b', src[src.index('enum {'):src.index('};', src.index('enum {'))])) - {'H_UNIMPL', 'H_VEC'}
    cases = set(re.findall(r'\bcase (H_[A-Z0-9]+)\s*:', src)) - {'H_UNIMPL', 'H_VEC'}
    have = {t['exec'] for t in F.values()} - {'H_UNIMPL'}
    for b, t in F.items():
        if t['exec'] != 'H_UNIMPL' and t['exec'] not in enum:
            out.append('%s: exec %s is not in the enum of pdp64exec_enc.inc' % (b, t['exec']))
        elif t['exec'] != 'H_UNIMPL' and t['exec'] not in cases:
            out.append('%s: exec %s has no `case` in pdp64exec_enc.inc' % (b, t['exec']))
        if t['exec'] != 'H_UNIMPL' and 'arg' not in t:
            out.append('%s: exec %s and no arg' % (b, t['exec']))
    for c in sorted(cases - have):
        out.append('pdp64exec_enc.inc has `case %s` and no base of spec/facts/core.toml has exec = "%s"' % (c, c))
    for c in sorted(enum - have):
        out.append('the enum of pdp64exec_enc.inc has %s and no base has exec = "%s"' % (c, c))
    return out


def main(argv):
    text = generate()
    if argv[1:] == ['--check']:
        bad = ['exec: ' + p for p in problems()]
        if not os.path.exists(OUT) or open(OUT).read() != text:
            bad.append('common/pdp64exec_corehdefs.inc is not what spec/facts/core.toml says (run tools/gen-core-names.py)')
        for p in bad:
            print('gen-core-names: ' + p)
        if not bad:
            print('gen-core-names: ok')
        return 1 if bad else 0
    open(OUT, 'w').write(text)
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv))
