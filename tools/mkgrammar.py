#!/usr/bin/env python3
"""
mkgrammar -- the numbers of the architecture are written once, as the enum rules of the parts of spec/grammars.d/ (the words in 30-mn-core, 40-mn-system, the registers, the
conditions, the system registers, System v1 in 50-system-v1: errata 180).  This reads them (tools/grammars_d.py: every hand-written part that names asm or spec) and writes

    build/pdp64-consts.h   one #define per enumerator, for the C that needs a number by name (as64, sim64, ld64)
    build/pdp64-names.h    the assembly spelling of every word, for a compiler that writes assembly
    build/x/pdp64-groups.h the mnemonic groups of the assembler (enum mn_group, MNEMONIC_NUMBER), in the order of the alternatives of `mnemonic`

An enumerator "cmp"@0b011010 of the rule mn-alu is MN_ALU_CMP.  An enumerator without a number is the one before plus one, as in hbnf.  A part that a generator owns (mn-ext, the forms)
has no constants: its numbers are positions in the tables mkenc.py writes.  Before it reads anything it writes the generated parts and indexes of the directory again
(`tools/mkparts.py`: `insn`, `mnemonic`; `tools/grammars_d.py --write`: the include lists), so a part dropped into spec/grammars.d/ is in every build with no other step.  There are no copies of the grammars in
build/: hbnf reads spec/pdp64-asm.hbnf (the assembly language) and spec/pdp64/pdp64.hbnf (the encoding) as they are.
"""
import os, re, sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.join(HERE, '..')


def enums(root=None, generated=False, targets=('spec',)):
    """{rule: [(literal, number)]} of the enum rules of the parts that name `spec` (the numbers: the words, the registers, the conditions, the system registers, System v1), the
    hand-written ones unless told otherwise.  A rule with no literal is left out."""
    import grammars_d
    rules, _ = grammars_d.read_rules(root, generated=generated, targets=targets)
    out = {}
    for rule, (body, _, _) in rules.items():
        if rule.startswith('map-'):			# the tables of 61-asm-suffixes.hbnf: rows, not enumerators (written by marks_header)
            continue
        nxt = 0
        for lit, num in re.findall(r'"([^"]+)"(?:@(0[xbo][0-9A-Fa-f]+|\d+))?', body):
            if num:
                nxt = int(num, 0)
            out.setdefault(rule, []).append((lit, nxt))
            nxt += 1
    return out


def surface_rows(root=None):
    """[(spelling, word of the encoding, flags, printed)] of the rule map-rows of 61-asm-suffixes.hbnf: every accepted spelling of the width and kind suffixes (and the bare `mov`), the word of the
    encoding it is, the flags, and whether the disassembler prints this spelling for that word.  The number of a spelling is its position (tools/mkparts.py writes mn-surface from them)."""
    import mkparts
    return mkparts.surface_rows(root)


def withdrawn_words(root=None):
    """the words of the older notations (the letters, the f and d words, the words of the encoding that no spelling stands for): unknown mnemonics (the rule map-words)"""
    import grammars_d
    rules, _ = grammars_d.read_rules(root, generated=True, targets=('asm',))
    return re.findall(r'"([^"]+)"', rules['map-words'][0])


def shown_spellings(root=None):
    """{word of the encoding: the spelling the disassembler and the compilers print}: the `*` rows; a word with none is printed as it is"""
    return {w: sp for sp, w, fl, shown in surface_rows(root) if shown}


def marks_header(root=None):
    rows = surface_rows(root)
    out = ['/* generated by tools/mkgrammar.py from spec/grammars.d/61-asm-suffixes.hbnf -- do not edit.  The width and kind suffixes: the accepted spelling (the number of its mn-surface word is its position),',
           '   the word of the encoding it is, the flags (s sized move, u user move, z zero-extending load) and 1 where the disassembler prints this spelling for that word.  See the part. */',
           'static const struct surfrow { const char *spell, *word, *flags; int shown; } surface_rows[] = {']
    out += ['\t{ "%s", "%s", "%s", %d },' % (sp, w, fl, 1 if sh else 0) for sp, w, fl, sh in rows]
    out.append('\t{ 0, 0, 0, 0 }\n};')
    out.append('/* the words of the older notations: unknown mnemonics */')
    out.append('static const char *const surface_withdrawn[] = {')
    out += ['\t"%s",' % w for w in withdrawn_words(root)]
    out.append('\t0\n};')
    out.append('/* the words of the assembly language that have no suffix at all (add, lea, cbeq ...): a suffix on one of them is refused with that message */')
    out.append('static const char *const surface_plain[] = {')
    gone = set(withdrawn_words(root))
    plain = sorted({lit for rule, items in enums(root, generated=True, targets=('asm',)).items() if rule.startswith('mn-') for lit, _ in items
                    if '.' not in lit and lit not in gone and not lit.startswith('v')} - {sp for sp, _, _, _ in rows} - {sp.split('.')[0] for sp, _, _, _ in rows})
    out += ['\t"%s",' % w for w in plain]
    out.append('\t0\n};')
    return '\n'.join(out) + '\n'


def marks_pcc_header(root=None):
    """the words of the encoding that the assembly language writes with another spelling, for the output-time pass of pcc's pdp64 back end, which works with the words of the encoding (movq, movb,
    fadd32, fcvtds) as its templates and its peephole match them as text: each is renamed to the spelling the disassembler prints (movq to mov, fadd32 to fadd.f32); the operands are as they are"""
    out = ['/* generated by tools/mkgrammar.py from spec/grammars.d/61-asm-suffixes.hbnf -- do not edit.  The words of the encoding the assembly language spells otherwise: the word and the spelling',
           '   (the bare word for a 64-bit one, a suffix otherwise); the operands do not change. */',
           'static const struct { const char *word, *spell; } pdp64_mrow[] = {']
    for w, sp in shown_spellings(root).items():
        if w != sp:
            out.append('\t{ "%s", "%s" },' % (w, sp))
    out.append('\t{ 0, 0 }\n};')
    return '\n'.join(out) + '\n'


def group_order(root=None):
    """The mnemonic groups, in the order of the parts (the generated mn-ext included): the order of the alternatives of `mnemonic` (grammars_d.py).  With whole-word keywords (see
    60-asm-syntax.hbnf) the order does not matter to the grammar."""
    import mkparts
    return mkparts.mn_groups(root)


def main():
    import grammars_d, mkparts
    mkparts.write()
    grammars_d.write()
    bad = grammars_d.validate()
    if bad:
        sys.exit('mkgrammar: ' + '\n'.join(bad))
    en = enums()
    const = {}
    for rule, items in en.items():
        for lit, v in items:
            k = re.sub(r'\W', '_', rule).upper() + '_' + re.sub(r'\W', '_', lit).upper()
            if k in const:
                sys.exit('mkgrammar: %s is defined twice' % k)
            const[k] = v
    bd = os.path.join(ROOT, os.environ.get('BUILD', 'build'))
    os.makedirs(os.path.join(bd, 'x'), exist_ok=True)
    full = enums(generated=True, targets=('asm',))
    order = group_order()
    names = [g[3:].replace('-', '_').upper() for g in order]
    with open(os.path.join(bd, 'x', 'pdp64-groups.h'), 'w') as f:
        f.write('/* generated by tools/mkgrammar.py -- do not edit.  The groups of mnemonics in the order of the alternatives of `mnemonic`. */\n')
        f.write('enum mn_group {\n')
        for k, n in enumerate(names):
            f.write('\tMG_%s = %d,\n' % (n, k + 1))
        f.write('};\n#define MG_SYSREG 98\t/* mfsr, mtsr: they take a system register name (`mfsr r1, ptbr`): not in `mnemonic` */\n/* the number of the mnemonic that the parser matched, from the member of that group (single-word groups have no member: their number is the opcode) */\n')
        f.write('#define MNEMONIC_NUMBER(m, out) do { switch ((m)->_alt) { \\\n')
        for k, g in enumerate(order):
            if len(full[g]) == 1:
                key = 'OPGROUP_' + g[3:].replace('-', '_').upper()
                val = 'OPGROUP_%s' % g[3:].replace('-', '_').upper() if key in const else '0'
                f.write('\tcase %d: (out) = %s; break; \\\n' % (k + 1, val))
            else:
                f.write('\tcase %d: (out) = (m)->%s; break; \\\n' % (k + 1, g.replace('-', '_')))
        f.write('\t} } while (0)\n')
    # the width suffixes: the rows of 61-asm-suffixes.hbnf, for as64 (a spelling becomes the word of the encoding) and the disassembler (a word becomes its spelling)
    with open(os.path.join(bd, 'x', 'pdp64-marks.h'), 'w') as f:
        f.write(marks_header())
    with open(os.path.join(bd, 'pdp64-pcc-marks.h'), 'w') as f:
        f.write(marks_pcc_header())
    # the names, for a compiler that writes assembly: every word of the mnemonic groups as a string
    with open(os.path.join(bd, 'pdp64-names.h'), 'w') as f:
        f.write('/* generated by tools/mkgrammar.py from the parts of spec/grammars.d/ -- do not edit.  The assembly spelling of every mnemonic, for templates:\n'
                '   "\t" M_ALU_ADD " AL,AR\\n". */\n#ifndef PDP64_NAMES_H\n#define PDP64_NAMES_H\n')
        for rule, items in en.items():
            if rule.startswith('mn-'):
                for lit, v in items:
                    f.write('#define M_%s_%-12s "%s"\n' % (re.sub(r'\W', '_', rule[3:]).upper(), re.sub(r'\W', '_', lit).upper(), lit))
        for rule in ('rnum', 'ralias', 'basespec'):
            for lit, v in en[rule]:
                f.write('#define R_%s_%-12s "%s"\n' % (rule.upper(), re.sub(r'\W', '_', lit).upper(), lit))
        for lit, v in en['sysreg']:				# the system registers, for `mfsr r1, ptbr`
            f.write('#define S_SYSREG_%-12s "%s"\n' % (re.sub(r'\W', '_', lit).upper(), lit))
        f.write('#endif\n')
    with open(os.path.join(bd, 'pdp64-consts.h'), 'w') as f:
        f.write('/* generated by tools/mkgrammar.py from the parts of spec/grammars.d/ -- do not edit */\n#ifndef PDP64_CONSTS_H\n#define PDP64_CONSTS_H\n')
        for k in sorted(const, key=lambda k: (k.split('_')[0], const[k], k)):
            f.write('#define %-28s %s\n' % (k, '%d' % const[k]))
        f.write('/* the read-only system registers (rule sysreg-ro) */\n#define SYSREG_READONLY(n) (%s)\n' % ' || '.join('(n) == %d' % v for _, v in en['sysreg-ro']))
        f.write('#endif\n')


if __name__ == '__main__':
    main()
