#!/usr/bin/env python3
"""
mkparts -- the two generated parts that COLLECT what the other parts define (errata 180); each is a part directory owned whole by this tool:

    spec/grammars.d/10-enc-insn/prologue.hbnf    `insn`, the root of the encoding: every leaf-FORM-K rule of the parts in the order of the catalogue `forms`, then K.  A prologue, so
                                                 that it is the first rule of the encoding grammar (hbnf reads a grammar whose first rule is a bit rule as bits alone).
    spec/grammars.d/90-mnemonic/epilogue.hbnf    `mnemonic`: every group mn-NAME of the parts of target asm (not mn-cond, mn-sysreg), in the order of the parts.  An epilogue: it comes
                                                 after every group.

    python3 tools/mkparts.py [--check]     write them (tools/mkgrammar.py does, before every build), or fail if they are stale

A new instruction family or a new group is a new part; this tool finds its leaves and its group and the collecting rules change by themselves.  Everything content-specific lives here,
nothing in tools/grammars_d.py (the generic assembler of the parts).
"""
import os, re, sys
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import grammars_d
from grammars_d import read_rules, spec_dir, GrammarError

INSN_PART = '10-enc-insn/prologue.hbnf'
MNEMONIC_PART = '90-mnemonic/epilogue.hbnf'
NOT_IN_MNEMONIC = ('mn-cond', 'mn-sysreg')         # the groups that take a word of their own as an operand, not in `mnemonic` (pdp64-asm.hbnf: condinsn, srinsn)


def _header(what, targets):
    return '; GENERATED by tools/mkparts.py: do not edit.  %s\n; targets: %s\n' % (what, ' '.join(targets))


def mangle(name):
    return re.sub(r'[./_]', '-', name)


def literals(body):
    return re.findall(r'"([^"]*)"', body)


def gen_insn(root=None):
    """text of 10-enc-insn/prologue.hbnf: `insn`, one leaf of every leaf-FORM-K rule of the parts, in the order of the catalogue `forms` and then K"""
    rules, _ = read_rules(root)
    leaves = {}
    for rn in rules:
        m = re.match(r'^leaf-(.+)-(\d+)$', rn)
        if m:
            leaves.setdefault(m.group(1).lower(), []).append((int(m.group(2)), rn))
    if 'forms' not in rules:
        raise GrammarError('no rule `forms` (the catalogue of forms) in any part')
    order, seen = [], set()
    for fn in literals(rules['forms'][0]):
        key = mangle(fn).lower()
        seen.add(key)
        order += [rn for _, rn in sorted(leaves.get(key, []))]
    for key in leaves:
        if key not in seen:
            raise GrammarError('leaf rule %s: its form %s is not in the catalogue `forms` (a part adds a form with `forms =/ "NAME"`)' % (leaves[key][0][1], key))
    out = _header('The instruction: one leaf, every leaf-FORM-K rule of the parts in the order of the catalogue `forms` (the leaves are numbered by this order).', ['enc'])
    out += '\ninsn = leaf:( ' + '\n       | '.join(_wrap(order)) + ' )\n'
    return out


def _wrap(names, width=150):
    lines, cur = [], ''
    for n in names:
        if cur and len(cur) + 3 + len(n) > width:
            lines.append(cur)
            cur = n
        else:
            cur = n if not cur else cur + ' | ' + n
    lines.append(cur)
    return lines


def mn_groups(root=None):
    rules, _ = read_rules(root, targets=['asm'])
    return [g for g in rules if g.startswith('mn-') and g not in NOT_IN_MNEMONIC]


def gen_mnemonic(root=None):
    out = _header('The words the assembler takes as an instruction: every group mn-NAME of the parts of target asm, in the order of the parts (the order of the enum `mn_group` of build/pdp64-groups.h).', ['asm'])
    out += '\nmnemonic = ' + '\n         | '.join(mn_groups(root)) + '\n'
    return out



def generated_files(root=None):
    sd = spec_dir(root)
    return {os.path.join(sd, 'grammars.d', INSN_PART): gen_insn(root), os.path.join(sd, 'grammars.d', MNEMONIC_PART): gen_mnemonic(root)}


def write(root=None):
    for path, txt in generated_files(root).items():
        if not os.path.exists(path) or open(path).read() != txt:
            os.makedirs(os.path.dirname(path), exist_ok=True)
            open(path, 'w').write(txt)


def check(root=None):
    return ['%s is not what tools/mkparts.py writes (run python3 tools/mkparts.py)' % p for p, txt in generated_files(root).items()
            if not os.path.exists(p) or open(p).read() != txt]


if __name__ == '__main__':
    if '--check' in sys.argv:
        bad = check()
        print('\n'.join('mkparts: ' + b for b in bad))
        sys.exit(1 if bad else 0)
    write()
