#!/usr/bin/env python3
"""
grammars_d -- the drop-in directory of the grammars, spec/grammars.d/ (errata 180, R493).

The grammar of the pdp64 is not one file but a directory of PARTS, read in the sorted order of their names, as /etc/foo.d/ is:

    spec/grammars.d/NN-name.hbnf                          a part of one file (its whole text is its `grammar` section)
    spec/grammars.d/NN-name/{prologue,grammar,epilogue}.hbnf     a part of up to three files, at least one (the owner's refinement, 2026-11-18)

NN is two digits (the load order), name lowercase letters, digits and hyphens.  The assembly is made in THREE PASSES over the parts: first every part's prologue (what must
come before any rule: the rule that must be first, such as `insn`; hbnf directives), then every part's grammar (the rules), then every part's epilogue (what must come last: a rule
that collects what the earlier parts defined, such as the `mnemonic` alternation; closing or overriding extensions with `=/`).  Inside a pass the order is the NN order.

A section is a file of hbnf rules.  The directives (`prefix`, `language`, `whitespace`, `%start`, ...) belong to the hand-edited masters spec/pdp64/pdp64.hbnf, the encoding, and
spec/pdp64-asm.hbnf, the assembly language (which include the generated indexes below), or to a prologue.hbnf.  Its first lines say where it is used:

    ; targets: asm enc spec          asm   the assembly-language grammar (hbnf reads it through spec/pdp64-asm.hbnf)
                                      enc   the encoding grammar (hbnf's decoder, through spec/pdp64/pdp64.hbnf)
                                      spec  the numbers (words, registers, conditions, system registers, System v1): the constants of build/pdp64-consts.h, the manual

A part that a generator owns begins `; GENERATED by <tool> ...` and is rewritten whole by it.  Every tool reads the whole directory (`read_rules`), whatever the targets say; the
targets only decide which parts hbnf is given.  A new part is a new file; no other file is edited (spec/README.md says how).

Rules: a rule defined in two parts is an error naming both files.  The one way to extend a rule is hbnf's own `name =/ alternatives`, which adds alternatives to the rule
an earlier part defined (the system registers of a hypervisor extension: `sysreg =/ "hvctl"@13`; the catalogue of forms: `forms =/ "CRY1"`); a `=/` before any `=` is an error.
Nothing overrides a rule with a second `=` (hbnf would let the later one win; here it is a mistake).

What this module writes (`python3 tools/grammars_d.py --write`; `--check` compares with the committed files): the two include lists spec/generated/index-enc.hbnf and index-asm.hbnf, one
`include` per section of the parts of the target, in the three passes (hbnf has `include` but no glob).  It knows nothing of any grammar's content: the rules that collect what other parts
define (`insn`, `mnemonic`) are written by tools/mkparts.py into parts of their own.  The contract between the parts and this script is in spec/README.md ("The contract"); it is meant to be
replaced by hbnf reading the directory itself, with no part changing.
"""
import os, re, sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.join(HERE, '..')
NAME_RE = re.compile(r'^(\d\d)-([a-z0-9]+(?:-[a-z0-9]+)*)\.hbnf$')
TARGETS = ('asm', 'enc', 'spec')
DIRECTIVES = ('include', 'prefix', 'language', 'whitespace', 'sensitivity', 'dialect', 'layout', 'layout_ops', 'keywords', 'hidden', 'context')


class GrammarError(Exception):
    pass


def spec_dir(root=None):
    return os.path.join(root or os.environ.get('PDP64_SPEC_ROOT') or ROOT, 'spec')    # PDP64_SPEC_ROOT: another tree (an older grammar to compare with)


def strip_comment(line):
    out, q = [], False
    for ch in line:
        if ch == '"':
            q = not q
        if ch == ';' and not q:
            break
        out.append(ch)
    return ''.join(out).rstrip()


def mangle(name):
    return re.sub(r'[./_]', '-', name)


SECTIONS = ('prologue', 'grammar', 'epilogue')       # the three passes; a single-file part is a `grammar`
DIR_RE = re.compile(r'^(\d\d)-([a-z0-9]+(?:-[a-z0-9]+)*)$')


def _unit(path, name, nn, pas):
    head = []
    for raw in open(path):
        if raw.strip() and not raw.startswith(';'):
            break
        head.append(raw)
    tg = None
    for raw in head:
        t = re.match(r'^;\s*targets:\s*(.*?)\s*$', raw)
        if t:
            tg = t.group(1).split()
    gen = re.match(r'^; GENERATED by (\S+)', head[0]) if head else None
    return dict(name=name, path=path, nn=nn, pass_=pas, section=SECTIONS[pas], targets=tg, generated=bool(gen), tool=gen.group(1) if gen else None)


def parts(root=None, check=True):
    """the sections of the parts, in load order (the three passes: every prologue, then every grammar, then every epilogue; inside a pass the NN order):
    [dict(name, path, nn, section, targets, generated, tool)].  A part is a file NN-name.hbnf (one `grammar` section) or a directory NN-name/ holding any of prologue.hbnf,
    grammar.hbnf, epilogue.hbnf.  Raises GrammarError for a name that is not NN-name, a repeated NN, a section with no or a wrong `; targets:` line, a stray .hbnf file in a part directory."""
    d = os.path.join(spec_dir(root), 'grammars.d')
    out, byn = [], {}
    for fn in sorted(os.listdir(d)):
        full = os.path.join(d, fn)
        if os.path.isdir(full):
            m = DIR_RE.match(fn)
            if not m:
                raise GrammarError('%s: a part directory is named NN-name (two digits, then lowercase words joined by hyphens)' % full)
            secs = []
            for sf in sorted(os.listdir(full)):
                if not sf.endswith('.hbnf'):
                    continue
                if sf[:-5] not in SECTIONS:
                    raise GrammarError('%s/%s: a part directory holds %s .hbnf only' % (full, sf, ', '.join(s + '.hbnf' for s in SECTIONS)))
                secs.append(sf[:-5])
            if not secs:
                raise GrammarError('%s: a part directory holds at least one of %s' % (full, ', '.join(s + '.hbnf' for s in SECTIONS)))
            files = [(s, os.path.join(full, s + '.hbnf')) for s in secs]
        elif fn.endswith('.hbnf'):
            m = NAME_RE.match(fn)
            if not m:
                raise GrammarError('%s: a part is named NN-name.hbnf (two digits, then lowercase words joined by hyphens): this one is not numbered' % full)
            files = [('grammar', full)]
        else:
            continue                                 # README, 99-example-*.hbnf.disabled, ...
        if m.group(1) in byn:
            raise GrammarError('%s and %s have the same number %s: a number is used once (it is the load order)' % (byn[m.group(1)], full, m.group(1)))
        byn[m.group(1)] = full
        for s, path in files:
            u = _unit(path, os.path.relpath(path, d), int(m.group(1)), SECTIONS.index(s))
            if check:
                if u['targets'] is None:
                    raise GrammarError('%s: no `; targets: asm enc spec` line among its first comment lines (which grammars hbnf reads it in)' % path)
                if not u['targets'] or any(x not in TARGETS for x in u['targets']):
                    raise GrammarError('%s: targets are words of %s, not `%s`' % (path, ' '.join(TARGETS), ' '.join(u['targets'])))
            u['targets'] = u['targets'] or []
            out.append(u)
    out.sort(key=lambda u: (u['pass_'], u['nn']))
    return out


def read_rules(root=None, generated=True, targets=None):
    """({rule: (body, file, line)}, [the files read]) over the parts in load order.  `name =/ ...` adds alternatives to the rule before it (whichever part defined it); a rule
    twice is an error naming both files.  Every part is read, so that a `=/` finds its rule; the result is then limited to the rules defined by hand-written parts only (generated
    false) and by parts that name one of `targets`, if given (the extensions of a kept rule are kept with it)."""
    rules, files = {}, []
    ps = parts(root)
    for p in ps:
        files.append(p['path'])
        cur = None
        for ln, raw in enumerate(open(p['path']).read().split('\n'), 1):
            line = strip_comment(raw)
            if not line.strip():
                continue
            w = line.split()[0]
            if not line[0].isspace() and (w in DIRECTIVES or w.startswith('%')):
                if p['section'] == 'prologue':
                    cur = None
                    continue                         # a directive of hbnf: the prologue carries it (kept in the text of the part, hbnf reads it)
                raise GrammarError('%s:%d: `%s` is a directive: it goes in a prologue.hbnf (or a master grammar), not in a grammar or epilogue' % (p['path'], ln, w))
            m = re.match(r'^([A-Za-z][\w-]*)\s*(=/|=(?!/))\s*(.*)$', line)
            if m and not line[0].isspace():
                cur = m.group(1)
                if m.group(2) == '=/':
                    if cur not in rules:
                        raise GrammarError('%s:%d: `%s =/` adds alternatives to a rule, and no earlier part defines %s' % (p['path'], ln, cur, cur))
                    rules[cur][0] += ' | ' + m.group(3)
                else:
                    if cur in rules:
                        raise GrammarError('rule %s is defined twice: %s:%d and %s:%d (a rule is defined once; extend it with `%s =/ ...`)' % (cur, rules[cur][1], rules[cur][2], p['path'], ln, cur))
                    rules[cur] = [m.group(3), p['path'], ln]
            elif line[0].isspace() and cur:
                rules[cur][0] += ' ' + line.strip()
            else:
                raise GrammarError('%s:%d: cannot read this line: %s' % (p['path'], ln, line))
    keep = {p['path'] for p in ps if (generated or not p['generated']) and (not targets or set(targets) & set(p['targets']))}
    return {k: tuple(v) for k, v in rules.items() if v[1] in keep}, files


def text(root=None, target=None, generated=True):
    """the concatenated text of the parts of a target (a straight assembly of the drop-ins), for a reader that wants the comments too"""
    return ''.join(open(p['path']).read() for p in parts(root)
                   if (generated or not p['generated']) and (target is None or target in p['targets']))


# ---------------------------------------------------------------- the generated index
def _header(tool, what, targets):
    return ('; GENERATED by %s: do not edit.  %s\n; targets: %s\n' % (tool, what, ' '.join(targets)))


def gen_index(root, target):
    out = ('; GENERATED by tools/grammars_d.py: do not edit.  The parts of target %s in load order (hbnf has `include` and no glob): the master grammar includes this one file.\n'
           '; A new part is a new file in ../grammars.d/ (spec/README.md); run `python3 tools/grammars_d.py --write` and this list is written again.\n' % target)
    for p in parts(root):
        if target in p['targets']:
            out += 'include "../grammars.d/%s"\n' % p['name']
    return out


def write(root=None, outdir=None):
    """write the two include lists (index-enc.hbnf, index-asm.hbnf: one `include` per section of the parts of the target, in the three passes).  With outdir the files are only returned."""
    sd = spec_dir(root)
    done = {}
    for tg in ('enc', 'asm'):
        path = os.path.join(sd, 'generated', 'index-%s.hbnf' % tg)
        txt = gen_index(root, tg)
        done[path] = txt
        if outdir is None:
            os.makedirs(os.path.dirname(path), exist_ok=True)
            if not os.path.exists(path) or open(path).read() != txt:
                open(path, 'w').write(txt)
    return done


def validate(root=None):
    """the structural checks: names, targets, rules (read_rules), the generated marks.  Returns a list of messages."""
    bad = []
    try:
        ps = parts(root)
        read_rules(root)
    except GrammarError as e:
        return [str(e)]
    for p in ps:
        first = open(p['path']).readline()
        if p['generated'] and not re.match(r'^; GENERATED by \S+.* do not edit', first):
            bad.append('%s: a generated part begins `; GENERATED by <tool> ... do not edit`' % p['path'])
        if not p['generated'] and re.search(r'^; GENERATED by', open(p['path']).read(), re.M):
            bad.append('%s: a hand-written part must not carry the line `; GENERATED by` (a generated part has it as its first line, and a generator owns it whole)' % p['path'])
    return bad


def check(root=None):
    """validate(), the include lists are what write() writes, and each master includes its index and holds directives only"""
    bad = validate(root)
    if bad:
        return bad
    for path, txt in write(root, outdir='-').items():
        if not os.path.exists(path) or open(path).read() != txt:
            bad.append('%s is not what tools/grammars_d.py writes: a part was added, removed or renamed (run python3 tools/grammars_d.py --write)' % path)
    sd = spec_dir(root)
    for master, tg in (('pdp64/pdp64.hbnf', 'enc'), ('pdp64-asm.hbnf', 'asm')):
        t = open(os.path.join(sd, master)).read()
        if not re.search(r'^include\s+"%sgenerated/index-%s\.hbnf"' % ('../' if '/' in master else '', tg), t, re.M):
            bad.append('spec/%s does not include generated/index-%s.hbnf' % (master, tg))
        if re.search(r'^; GENERATED by', t, re.M):
            bad.append('spec/%s is a hand-edited master and must not carry the GENERATED line' % master)
        for ln, raw in enumerate(t.split('\n'), 1):
            if re.match(r'^[A-Za-z][\w-]*\s*=', strip_comment(raw)):
                bad.append('spec/%s:%d: a master holds directives and the include of its index, no rule: a rule is a part (spec/README.md)' % (master, ln))
    return bad


def main():
    if '--write' in sys.argv:
        for p in write():
            print('grammars_d: %s' % os.path.relpath(p, os.path.join(ROOT)))
        bad = validate()
    elif '--check' in sys.argv:
        bad = check()
    else:
        print(__doc__)
        return 2
    for b in bad:
        print('grammars_d: ' + b)
    return 1 if bad else 0


if __name__ == '__main__':
    sys.exit(main())
