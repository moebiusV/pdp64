#!/usr/bin/env python3
"""
gen-llvm-td.py -- derive from the grammar of the encoding (spec/pdp64/pdp64.hbnf, read with tools/encgram.py) what the LLVM back end needs,
and write it under llvm/target/PDP64/gen/ (never edited by hand):

    PDP64GenMnemonics.td   one `defvar MN_<mnemonic> = "<mnemonic>";` for every mnemonic of the grammar.  The hand-written
                           instruction definitions (PDP64InstrInfo.td ...) name their mnemonics through these variables, so a
                           mnemonic the grammar does not have is a tablegen error, and nothing here knows an opcode number.
    PDP64GenRegs.td        the register definitions r0..r31 (sp = r14, fp = r13) and the hot-register tables of the ABI as lists.
    PDP64GenLayout.td      the widths of the operand fields of the forms, as defvars (immediates, displacements, branch reach).
    PDP64GenLayout.h       the same numbers for C++ (namespace PDP64Layout), the condition-code table of the compare-and-branch
                           forms, the mnemonic list and the hot tables.  Used by the ISel, the printer and the tests.

The numbers are derived, never typed: e.g. the widest signed immediate of the forms of `add` (32), the widest displacement of a base
register form (28), the widest immediate of a `cbCC` form (16), the scale values of the indexed forms.  The opcode numbers are the
prefix optimiser's and change whenever it is re-run; the text back end emits assembly, so it needs none of them.

    tools/gen-llvm-td.py            write the files
    tools/gen-llvm-td.py --check    exit 1 if the files on disk differ from what the grammar says
"""
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import encgram  # noqa: E402
import facts  # noqa: E402

OUT = os.path.normpath(os.path.join(HERE, '..', 'llvm', 'target', 'PDP64', 'gen'))

HEADER = '// Generated by tools/gen-llvm-td.py from spec/pdp64/pdp64.hbnf -- do not edit.\n'


def mangle(mn):
    return re.sub(r'[^A-Za-z0-9_]', '_', mn)


def widest(forms, mn, kind, key, signed=None):
    """the largest `key` (w, dw) of a spec of `kind` in the forms that have mnemonic mn"""
    best = 0
    for f in forms:
        if mn not in f['mns']:
            continue
        for s in f['specs']:
            if s['k'] != kind:
                continue
            if signed is not None and s.get('signed') != signed:
                continue
            best = max(best, s.get(key, 0))
    return best


def widest_in(forms, mns, kind, key, signed=None):
    return max([widest(forms, m, kind, key, signed) for m in mns] + [0])


def generate():
    d = encgram.load()
    forms = d['forms']
    mns = []
    for f in forms:
        for m in f['mns']:
            if m not in mns:
                mns.append(m)
    mns.sort()

    # ---------------- derived layout numbers
    alu = ['add', 'sub', 'and', 'bis', 'xor', 'mul', 'cmp']
    lay = {}
    lay['AluImmBits'] = min(widest(forms, m, 'I', 'w', True) for m in alu)        # the signed immediate every one of them takes (32)
    lay['MovImmBits'] = widest(forms, 'movq', 'I', 'w', True)
    lay['ShiftImmBits'] = 6                                                           # shl/shr/sar #n: n in 0..63 (RRI: imm6)
    lay['DispBits'] = widest_in(forms, ['movq', 'movl', 'movw', 'movb', 'lea'], 'B', 'dw', True)   # d(rN): 28
    lay['IdxDispBits'] = widest_in(forms, ['movq', 'movl', 'movw', 'movb', 'lea'], 'X', 'dw', True)  # d(rN)(rX*s): 22
    cbs = sorted(m for m in mns if m.startswith('cb'))
    lay['CbImmBits'] = widest_in(forms, [m for m in cbs if m in ('cbeq', 'cbne', 'cblt', 'cbge', 'cbgt', 'cble', 'cbcs', 'cbcc', 'cbhi', 'cblos')], 'I', 'w', True)
    lay['BranchReachBits'] = widest(forms, 'br', 'PC', 'w')                           # bits of the parcel distance of br: 32
    lay['PcDispBits'] = widest_in(forms, ['movq', 'lea'], 'PC', 'w')                  # d(pc) operand of a load: 32
    lay['CtImmBits'] = widest_in(forms, ['ctcc', 'cthi', 'cteq', 'ctne'], 'I', 'w', False)   # the unsigned immediate of ctCC rs, #imm (12)
    lay['PushImmBits'] = widest(forms, 'push', 'I', 'w', True)
    lay['AccessBytes'] = d['acc']                                                      # movq 8, movl 4, ...
    # scale of the indexed forms: the assembler takes 1, 2, 4 or 8 (docs/asm-syntax.md); the grammar fixes it in the leaf, not as a field width
    lay['IdxScales'] = [1, 2, 4, 8]

    # condition codes of the compare-and-branch forms, in the order of the compare group: the ones with an immediate or register form
    ccs = []
    for m in cbs:
        c = m[2:]
        if c not in ccs:
            ccs.append(c)
    # mnemonic pairs: the branch group has b<cc> for these as well (bne ... blos), checked below
    bcc = [c for c in ccs if 'b' + c in mns]

    # the check instructions ctCC (trap if the compare-and-branch condition CC holds): the conditions with a register form, and those with an
    # immediate form (the grammar gives an unsigned immediate to few of them), and the two that test zero alone (cteq rs, ctne rs: forms of one operand)
    ctcs = [c for c in ccs if 'ct' + c in mns]
    ctimm = [c for c in ctcs if any(('ct' + c) in f['mns'] and any(sp['k'] == 'I' for sp in f['specs']) for f in forms)]
    ctz = [c for c in ('eq', 'ne') if any(('ct' + c) in f['mns'] and len(f['specs']) == 1 for f in forms)]
    assert 'chk2' in mns and ctcs and ctz

    vecmns = [m for m in mns if m in ('vec', 'vend', 'vec2', 'vskip') or re.match(r'^(v[a-z0-9]+)(\.[a-z]+)*$', m) and m not in ('vclr_',)]
    # only the words of the vector family: the ones that start with v and are not scalar words (checked against a list of the base names in the executor's table by the user of this list)
    vecbases = [b for b, f in facts.load('vec').items() if f.get('llvm')]		# the bases of spec/facts/vec.toml whose words LLVM carries
    vecmns = [m for m in vecmns if m.split('.')[0] in vecbases]

    regs = d['regnames']
    nreg = d['registers']

    # ---------------- PDP64GenMnemonics.td
    t = [HEADER, '// every mnemonic of the grammar; mangled: non-identifier characters become _\n']
    for m in mns:
        t.append('defvar MN_%s = "%s";\n' % (mangle(m), m))
    mn_td = ''.join(t)

    # ---------------- PDP64GenRegs.td
    t = [HEADER, '// r0..r%d; the class PDP64Reg is in PDP64RegisterInfo.td\n' % (nreg - 1)]
    for i in range(nreg):
        t.append('def R%d : PDP64Reg<%d, "r%d">, DwarfRegNum<[%d]>;\n' % (i, i, i, i))
    t.append('defvar HotRegs3 = [%s];\n' % ', '.join('R%d' % r for r in d['hot8']))
    t.append('defvar HotRegs4 = [%s];\n' % ', '.join('R%d' % r for r in d['hot16']))
    regs_td = ''.join(t)

    # ---------------- PDP64GenLayout.td
    t = [HEADER]
    for k, v in lay.items():
        if isinstance(v, int):
            t.append('defvar %s = %d;\n' % (k, v))
    t.append('defvar IdxScales = [%s];\n' % ', '.join(str(x) for x in lay['IdxScales']))
    t.append('defvar CondNames = [%s];\n' % ', '.join('"%s"' % c for c in ccs))
    layout_td = ''.join(t)

    # ---------------- PDP64GenLayout.h
    t = [HEADER, '#ifndef PDP64_GEN_LAYOUT_H\n#define PDP64_GEN_LAYOUT_H\n\nnamespace PDP64Layout {\n']
    for k, v in lay.items():
        if isinstance(v, int):
            t.append('constexpr unsigned %s = %d;\n' % (k, v))
    t.append('constexpr unsigned NumRegs = %d;\n' % nreg)
    t.append('constexpr unsigned Hot3[8] = {%s};\n' % ', '.join(str(r) for r in d['hot8']))
    t.append('constexpr unsigned Hot4[16] = {%s};\n' % ', '.join(str(r) for r in d['hot16']))
    t.append('} // namespace PDP64Layout\n\n')
    t.append('// the condition codes of the cbCC forms (suffix of the mnemonic), in grammar order; X(name)\n#define PDP64_CB_CONDS(X) \\\n')
    t.append(' \\\n'.join('  X(%s)' % c for c in ccs) + '\n\n')
    t.append('// the ones that also exist as b<cc> (cmp + branch on the flags)\n#define PDP64_B_CONDS(X) \\\n')
    t.append(' \\\n'.join('  X(%s)' % c for c in bcc) + '\n\n')
    for nm, lst, what in (('PDP64_CT_CONDS', ctcs, 'the conditions of ctCC rs, rb (trap if rs CC rb)'),
                          ('PDP64_CT_IMM_CONDS', ctimm, 'the ones with an immediate form (ctCC rs, #imm: CtImmBits unsigned)'),
                          ('PDP64_CT_ZERO_CONDS', ctz, 'the ones with a one-register form (cteq rs: trap if zero, ctne rs)')):
        t.append('// %s\n#define %s(X) \\\n' % (what, nm))
        t.append(' \\\n'.join('  X(%s)' % c for c in lst) + '\n\n')
    t.append('// the mnemonics of the vector, tile and GEMM family (vec-isa.md): vec, vend, vfin, vadd.w, vld.bu.w ...; X("mnemonic")\n#define PDP64_VEC_MNEMONICS(X) \\\n')
    t.append(' \\\n'.join('  X("%s")' % m for m in vecmns) + '\n\n')
    t.append('#endif\n')
    layout_h = ''.join(t)

    return {
        'PDP64GenMnemonics.td': mn_td,
        'PDP64GenRegs.td': regs_td,
        'PDP64GenLayout.td': layout_td,
        'PDP64GenLayout.h': layout_h,
    }


def main():
    files = generate()
    if '--check' in sys.argv[1:]:
        bad = 0
        for name, text in files.items():
            p = os.path.join(OUT, name)
            if not os.path.exists(p) or open(p).read() != text:
                print('stale: %s' % p, file=sys.stderr)
                bad = 1
        if os.path.isdir(OUT):
            for name in os.listdir(OUT):
                if name not in files:
                    print('unexpected file in gen/: %s' % name, file=sys.stderr)
                    bad = 1
        sys.exit(bad)
    os.makedirs(OUT, exist_ok=True)
    for name in os.listdir(OUT):
        if name not in files:
            print('gen/ holds a file the generator does not make: %s (not touched)' % name, file=sys.stderr)
    for name, text in files.items():
        with open(os.path.join(OUT, name), 'w') as f:
            f.write(text)
    print('wrote %d files to %s' % (len(files), OUT))


if __name__ == '__main__':
    main()
