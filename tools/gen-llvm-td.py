#!/usr/bin/env python3
"""
gen-llvm-td -- write the numbers and tables of the LLVM back end from the architecture's single sources.

Nothing the LLVM target needs as a number is typed by hand.  This reads

    spec/pdp64-mnemonics.hbnf      the opcodes, sub-opcodes, modes, registers, conditions, system registers (through tools/mkgrammar.py)
    build/pdp64-limits.h           the widths of the displacement and immediate fields (as64 --limits: measured from the grammar's encoder)
    common/p2.c                    the table of page 2 (the rows `E(NAME, ...)`)

and writes, into llvm/target/PDP64/gen/ (or the directory given with -o):

    PDP64Consts.td          defvars: opcodes, modes, length codes, forms (TSFlags), for the .td files
    PDP64RegisterInfo.td    the sixteen general registers
    PDP64InstrDefs.td       one `defm` / `def` per mnemonic, and the mnemonic aliases (the forms and lengths are multiclasses in
                            llvm/target/PDP64/PDP64InstrInfo.td)
    PDP64Layout.h           the same constants for C++, and the widths of the fields
    PDP64Tables.inc         conditions, system registers, register aliases, the page-2 table, the relaxation (widening) chain
    PDP64Fixups.def         the fixup kinds

    tools/gen-llvm-td.py              write
    tools/gen-llvm-td.py --check      fail if the files on disk differ from what would be written

The page-1 groups ATOM and MESC are not generated: as64 does not implement them either (no oracle), see llvm/README.md.
"""
import os, re, subprocess, sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, '..'))
sys.path.insert(0, HERE)
import mkgrammar

OUT = os.path.join(ROOT, 'llvm', 'target', 'PDP64', 'gen')

# --------------------------------------------------------------------------------------------------------------------
# the sources

en = mkgrammar.enums(os.path.join(ROOT, 'spec', 'pdp64-mnemonics.hbnf'))
ALIAS = dict(en['offset'])['alias']


def limits():
    """name -> value from build/pdp64-limits.h, regenerated from as64 when stale or missing."""
    b = os.environ.get('BUILD', 'build')
    path = os.path.join(ROOT, b, 'pdp64-limits.h')
    as64 = os.path.join(ROOT, b, 'as64')
    text = None
    if os.path.exists(as64):
        text = subprocess.run([as64, '--limits'], capture_output=True, text=True, check=True).stdout
    elif os.path.exists(path):
        text = open(path).read()
    else:
        sys.exit('gen-llvm-td: neither build/as64 nor build/pdp64-limits.h: run tools/build-as64.sh')
    return {m.group(1): int(m.group(2)) for m in re.finditer(r'#define\s+(PDP64_\w+)\s+(\d+)', text)}


LIM = limits()


def p2rows():
    """The rows of common/p2.c: E(NAME, opc, reg, mode, rm, dsrc, scale, idx)."""
    text = open(os.path.join(ROOT, 'common', 'p2.c')).read()
    rows = []
    for m in re.finditer(r'^\s*E\((\w+),\s*(\w+),\s*(\w+),\s*(\w+),\s*(\w+),\s*(\w+),\s*(\d+),\s*(\d+)\)', text, re.M):
        rows.append(m.groups())
    return rows


P2 = p2rows()


def const(name):
    """Resolve a name used by p2.c (MN_MOV_MOVQ, OPGROUP_SOP, AMODE_BASE, RALIAS_SP, MOVSTORE_MOVQ, P2OP_LD_Q) to its number."""
    rule, _, lit = name.partition('_')
    for r, items in en.items():
        # the rule prefix of the constant name: mn-mov -> MN_MOV
        pre = re.sub(r'\W', '_', r).upper()
        if name.startswith(pre + '_'):
            tail = name[len(pre) + 1:]
            for l, v in items:
                if re.sub(r'\W', '_', l).upper() == tail:
                    return v
    sys.exit('gen-llvm-td: cannot resolve %s' % name)


def items(rule):
    return [(l, v) for l, v in en[rule]]


def real(rule):
    return [(l, v) for l, v in en[rule] if v < ALIAS]


def aliases(rule):
    """(alias word, word it stands for) for the aliases of a group."""
    byval = {v: l for l, v in en[rule] if v < ALIAS}
    return [(l, byval[v - ALIAS]) for l, v in en[rule] if v >= ALIAS]


def up(s):
    return re.sub(r'\W', '_', s).upper()


# --------------------------------------------------------------------------------------------------------------------
# the vocabulary of forms (TSFlags{3-0}); the .td classes and the C++ share these numbers

# mode letters of the memory-operand forms, in the order of the amode rule
AMODES = {l: v for l, v in items('amode')}
MODE_LETTER = {'base': 'B', 'index': 'X', 'pcrel': 'PC', 'dp': 'D', 'imm': 'I', 'abs': 'A', 'postinc': 'PI', 'predec': 'PD'}
FORMS = ['NONE', 'REG'] + ['MEM_' + up(l) for l, v in sorted(items('amode'), key=lambda x: x[1])] + \
    ['BR0', 'BR', 'CB', 'CBW', 'CBR', 'SOB', 'TAG', 'SYS']
FORM = {n: k for k, n in enumerate(FORMS)}


class Out:
    def __init__(self):
        self.files = {}

    def w(self, name, text):
        self.files[name] = text


def hdr(comment):
    return comment + ' generated by tools/gen-llvm-td.py from spec/pdp64-mnemonics.hbnf, build/pdp64-limits.h and common/p2.c -- do not edit.\n'


# --------------------------------------------------------------------------------------------------------------------

def consts_td():
    t = hdr('//')
    t += '// The opcodes of the top-level groups, the addressing modes, the length codes and the forms (TSFlags{3-0}).\n'
    for rule in ('opgroup', 'amode', 'lencode', 'movstore'):
        for l, v in items(rule):
            t += 'defvar %s_%s = %d;\n' % (up(rule), up(l), v)
    for rule in ('mn-sop', 'mn-sys', 'mn-sys-none'):
        for l, v in real(rule):
            t += 'defvar %s_%s = %d;\n' % (up(rule), up(l), v)
    t += 'defvar SUBOP_SET = %d;\n' % dict(items('subop'))['set']
    t += 'defvar MN_SYSREG_MFSR = %d;\ndefvar MN_SYSREG_MTSR = %d;\n' % (dict(items('mn-sysreg'))['mfsr'], dict(items('mn-sysreg'))['mtsr'])
    for n, k in FORM.items():
        t += 'defvar FORM_%s = %d;\n' % (n, k)
    for k in (1, 2):
        for name in ('BASE_DISP', 'INDEX_DISP', 'WIDE', 'BRANCH', 'CB', 'CBR'):
            t += 'defvar %s_BITS_LEN%d = %d;\n' % (name, k, LIM['PDP64_%s_BITS_LEN%d' % (name, k)] if name != 'WIDE' else LIM['PDP64_WIDE_BITS_LEN%d' % k])
    t += 'defvar BRANCH_BITS_LEN0 = %d;\n' % LIM['PDP64_BRANCH_BITS_LEN0']
    t += 'defvar CB_IMM_BITS = %d;\ndefvar CBW_IMM_BITS = %d;\ndefvar CBW_BITS = %d;\n' % (LIM['PDP64_CB_IMM_BITS'], LIM['PDP64_CBW_IMM_BITS'], LIM['PDP64_CBW_BITS'])
    return t


def regs_td():
    t = hdr('//')
    t += 'let Namespace = "PDP64" in {\n'
    for l, v in items('rnum'):
        t += '  def %s : PDP64Reg<%d, "%s">, DwarfRegNum<[%d]>;\n' % (l.upper(), v, l, v)
    t += '}\n\n'
    t += 'def GPR : RegisterClass<"PDP64", [i64], 64, (add %s)>;\n' % ', '.join(l.upper() for l, v in sorted(items('rnum'), key=lambda x: x[1]))
    return t


# --------------------------------------------------------------------------------------------------------------------
# instructions

FESC_UNARY = {'fsqrt', 'fsqrt32', 'fneg', 'fabs', 'fclass', 'fclass32', 'frint', 'frintz', 'frintm', 'frintp', 'frinta', 'fcvtdq', 'fcvtqd',
              'fcvtds', 'fcvtsd', 'fcvtsl', 'fcvtls', 'fcvtdqu', 'fcvtqud', 'fsflags', 'fsqrt16', 'fclass16', 'fcvtsh', 'fcvths', 'fcvtdh',
              'fcvthd', 'fcvthl', 'fcvtlh'}
FESC_BINARY = {'fdiv', 'fadd32', 'fsub32', 'fmul32', 'fdiv32', 'fcmp32', 'fadd16', 'fsub16', 'fmul16', 'fdiv16', 'fcmp16'}
FESC_THREE = {'fcopysign', 'fmin', 'fmax'}
FESC_REGFIRST = {'fcmp32', 'fcmp16'}                  # fcmp32 rd, rs: register first, as cmp
BESC_TWO = {'clz', 'ctz', 'clo', 'cto', 'popcnt', 'bswap', 'bswapw', 'bswapl', 'bitrev', 'utf8len', 'utf8dec', 'utf8enc'}
BESC_COUNT = {'rori': 'uimm6', 'rori32': 'uimm5'}
BESC_FIELD = {'extb', 'extzb', 'insb'}
AESC_TWO = {'abs'}
SYS_REG = {'mtps', 'mfps', 'tlbi', 'mtasid', 'mfasid', 'mtdp', 'mfdp', 'mtdmw', 'mfcpuid', 'icinv'}
SYS_PROBE = {'prober', 'probew'}
CMP_FIRST = {'cmp', 'fcmp'}                           # cmp rd, src (errata 13)


def mov_stride(name):
    return {'q': 3, 'l': 2, 'w': 1, 'b': 0}[name[-1]]    # log2 of the size in bytes


def instr_defs():
    t = hdr('//')
    t += '// One line per mnemonic; the forms (register, the eight addressing modes, the lengths) are the multiclasses of PDP64InstrInfo.td.\n'
    t += '// ATOM and MESC are not here: as64 does not implement them (docs/CHANGES-SINCE-R20.md section 12), so there is no oracle.\n\n'
    B = lambda n, w=6: "0b" + format(n, '0%db' % w)
    flags = []

    def d(line):
        flags.append(line)

    # moves ---------------------------------------------------------------------------------------------------------
    d('// moves: load = n, store = n+1 (ISA 4.1)')
    stores = {l: v for l, v in items('movstore')}
    for l, v in real('mn-mov'):
        d('defm %s : MemRM<"%s", %d, "$m, $r", 1, 1, %d>;' % (up(l), l, v, mov_stride(l)))
        d('defm %sST : MemRM<"%s", %d, "$r, $m", 0, 0, %d>;' % (up(l), l, stores[l], mov_stride(l)))
    d('// zero-extending loads')
    for l, v in real('mn-movz'):
        d('defm %s : MemRM<"%s", %d, "$m, $r", 1, 1, %d>;' % (up(l), l, v, mov_stride(l)))
    d('// effective address')
    d('defm LEA : MemRM<"lea", OPGROUP_LEA, "$m, $r", 0, 0, 3>;')
    d('// ALU and floating-point ALU')
    for l, v in real('mn-alu'):
        d('defm %s : MemRM<"%s", %d, "%s", 1, 1, 3>;' % (up(l), l, v, '$r, $m' if l in CMP_FIRST else '$m, $r'))
    # SOP / XFER ----------------------------------------------------------------------------------------------------
    d('// single operand (the reg field is the sub-opcode)')
    for l, v in real('mn-sop'):
        if l in ('pushm', 'popm'):
            d('defm %s : MemMask<"%s", %d>;' % (up(l), l, v))
        else:
            d('defm %s : MemU<"%s", OPGROUP_SOP, %d, 1, 1>;' % (up(l), l, v))
    d('// control transfer through an operand')
    for l, v in real('mn-xfer'):
        if l == 'jtag':
            d('defm JTAG : MemTag<"jtag", OPGROUP_XFER, %d>;' % v)
        else:
            d('defm %s : MemU<"%s", OPGROUP_XFER, %d, 0, 1>;' % (up(l), l, v))
    # branches ------------------------------------------------------------------------------------------------------
    d('// branches (ISA 4.4)')
    for l, v in real('mn-branch'):
        extra = {'br': ', 1', }.get(l, ', 0')
        d('defm %s : Branch<"%s", %d%s>;' % (up(l), l, v, extra))
    d('// compare a register with an immediate or a register and branch (three opcodes: 0x28, 0x29, 0x2A)')
    for l, v in real('mn-cbranch'):
        d('defm %s : CBranch<"%s", %d>;' % (up(l), l, v))
    d('defm SOB : SobForm<"sob">;')
    for l, v in real('mn-tag'):
        d('defm %s : TagForm<"%s", %d>;' % (up(l), l, v))
    # SYS -----------------------------------------------------------------------------------------------------------
    d('// SYS class 0: no operand')
    for l, v in real('mn-sys-none'):
        flag = {'ret': 'isReturn', 'rti': 'isReturn', 'rtt': 'isReturn'}.get(l)
        d('def %s : Sys0<"%s", %d>;' % (up(l), l, v))
    d('// SYS classes with an operand')
    for l, v in real('mn-sys'):
        if l in ('spl',):
            d('def SPL : SysImm4<"spl", %d>;' % v)
        elif l == 'trap':
            d('def TRAP : SysImm4<"trap", %d>;' % v)
            d('def TRAPL : SysTrapL<"trap", %d>;' % dict(real('mn-sys'))['trapl'])
        elif l == 'trapl':
            continue
        elif l in SYS_PROBE:
            d('def %s : SysProbe<"%s", %d>;' % (up(l), l, v))
        else:
            assert l in SYS_REG, l
            d('def %s : SysReg1<"%s", %d>;' % (up(l), l, v))
    d('def MFSR : SysRegMove<"mfsr", MN_SYSREG_MFSR, 1>;')
    d('def MTSR : SysRegMove<"mtsr", MN_SYSREG_MTSR, 0>;')
    d('def SET : SetCond<"set">;')
    # escapes --------------------------------------------------------------------------------------------------------
    d('// BESC: bit operations')
    for l, v in real('mn-besc'):
        n = up(l)
        if l in BESC_COUNT:
            d('def %s : EscCount<OPGROUP_BESC, "%s", %d, %s>;' % (n, l, v, BESC_COUNT[l]))
        elif l == 'dshr':
            d('def DSHR : EscDshr<OPGROUP_BESC, "dshr", %d>;' % v)
        elif l in BESC_FIELD:
            d('def %s : EscField<OPGROUP_BESC, "%s", %d>;' % (n, l, v))
        elif l in BESC_TWO:
            d('def %s : Esc2<OPGROUP_BESC, "%s", %d>;' % (n, l, v))
        else:
            d('def %s : Esc3<OPGROUP_BESC, "%s", %d>;' % (n, l, v))
    d('// MBLK: block operations')
    for l, v in real('mn-mblk'):
        if l == 'mval':
            d('def MVAL : EscMval<OPGROUP_MBLK, "mval", %d>;' % v)
        else:
            d('def %s : Esc3Blk<OPGROUP_MBLK, "%s", %d>;' % (up(l), l, v))
    d('// AESC: arithmetic')
    for l, v in real('mn-aesc'):
        d('def %s : %s<OPGROUP_AESC, "%s", %d>;' % (up(l), 'Esc2' if l in AESC_TWO else 'Esc3', l, v))
    d('// FESC: floating point')
    for l, v in real('mn-fesc'):
        n = up(l)
        if l in FESC_REGFIRST:
            d('def %s : EscCmp<OPGROUP_FESC, "%s", %d>;' % (n, l, v))
        elif l in FESC_UNARY or l in FESC_BINARY:
            d('def %s : Esc2<OPGROUP_FESC, "%s", %d>;' % (n, l, v))
        elif l in FESC_THREE:
            d('def %s : Esc3<OPGROUP_FESC, "%s", %d>;' % (n, l, v))
        else:
            d('def %s : Esc4<OPGROUP_FESC, "%s", %d>;' % (n, l, v))
    t += '\n'.join(flags) + '\n\n'
    # aliases ----------------------------------------------------------------------------------------------------------------
    t += '// the assembler aliases of ISA 4.15 (one mnemonic, one instruction).  `rol` also changes an operand: the parser does it.\n'
    for rule in en:
        if rule.startswith('mn-'):
            for a, b in aliases(rule):
                if a == 'rol':
                    continue
                t += 'def : MnemonicAlias<"%s", "%s">;\n' % (a, b)
    return t


