def layout_h():
    t = hdr('//')
    t += '#ifndef PDP64_LAYOUT_H\n#define PDP64_LAYOUT_H\nnamespace llvm {\nnamespace PDP64Layout {\n'
    t += 'enum Form : unsigned {\n' + ''.join('  FORM_%s = %d,\n' % (n, k) for n, k in FORM.items()) + '};\n'
    t += 'enum AMode : unsigned {\n' + ''.join('  AMODE_%s = %d,\n' % (up(l), v) for l, v in items('amode')) + '};\n'
    t += 'enum OpGroup : unsigned {\n' + ''.join('  OPGROUP_%s = %d,\n' % (up(l), v) for l, v in items('opgroup')) + '};\n'
    t += 'enum LenCode : unsigned {\n' + ''.join('  LENCODE_%s = %d,\n' % (up(l), v) for l, v in items('lencode')) + '};\n'
    t += 'enum SopOp : unsigned {\n' + ''.join('  SOP_%s = %d,\n' % (up(l), v) for l, v in real('mn-sop')) + '};\n'
    t += 'enum AluOp : unsigned {\n' + ''.join('  ALU_%s = %d,\n' % (up(l), v) for l, v in real('mn-alu')) + '};\n'
    for k in (1, 2):
        for name in ('BASE_DISP', 'INDEX_DISP', 'WIDE', 'BRANCH', 'CB', 'CBR'):
            t += 'constexpr unsigned %s_BITS_LEN%d = %d;\n' % (name, k, LIM['PDP64_%s_BITS_LEN%d' % (name, k)])
    t += 'constexpr unsigned BRANCH_BITS_LEN0 = %d;\n' % LIM['PDP64_BRANCH_BITS_LEN0']
    t += 'constexpr unsigned CB_IMM_BITS = %d;\nconstexpr unsigned CBW_IMM_BITS = %d;\nconstexpr unsigned CBW_BITS = %d;\n' % \
        (LIM['PDP64_CB_IMM_BITS'], LIM['PDP64_CBW_IMM_BITS'], LIM['PDP64_CBW_BITS'])
    t += 'constexpr unsigned MAXLEN = %d;\n' % LIM['PDP64_MAXLEN']
    t += '} // end namespace PDP64Layout\n} // end namespace llvm\n#endif\n'
    return t


def tables_inc():
    t = hdr('//')
    t += '// conditions: name, number (the low nibble of the branch opcode; `set` puts it in the x field of parcel 1)\n#ifdef PDP64_CC_TABLE\n'
    for l, v in items('cc') + items('ccalias'):
        t += 'PDP64_CC("%s", %d)\n' % (l, v)
    t += '#endif\n\n// the canonical name of each condition (the first of its number)\n#ifdef PDP64_CC_PRINT\n'
    seen = set()
    for l, v in items('cc'):
        t += 'PDP64_CCP("%s", %d)\n' % (l, v)
    t += '#endif\n\n// system registers: name, number, read-only\n#ifdef PDP64_SYSREG_TABLE\n'
    ro = {v for l, v in items('sysreg-ro')}
    for l, v in items('sysreg'):
        t += 'PDP64_SYSREG("%s", %d, %d)\n' % (l, v, 1 if v in ro else 0)
    t += '#endif\n\n// register aliases: name, register number\n#ifdef PDP64_REGALIAS_TABLE\n'
    for l, v in items('ralias'):
        t += 'PDP64_REGALIAS("%s", %d)\n' % (l, v)
    t += '#endif\n\n// base specifiers other than a register: name, number\n#ifdef PDP64_BASESPEC_TABLE\n'
    for l, v in items('basespec'):
        t += 'PDP64_BASESPEC("%s", %d)\n' % (l, v)
    t += '#endif\n\n'
    # page 2: the rows of common/p2.c with their numbers
    t += '// page 2 (common/p2.c): P2ROW(opcode, page-1 opcode, reg field or FIELD, mode, rm or FIELD/NONE, dsrc, scale, idx)\n#ifdef PDP64_P2_TABLE\n'
    dsrc = {'D_ZERO': 0, 'D_LOW': 1, 'D_LOWHI': 2, 'D_SLOW': 3, 'D_STEP': 4, 'D_BYTE': 5}
    for name, opc, reg, mode, rm, ds, scale, idx in P2:
        def num(x):
            return {'FIELD': -1, 'NONE': -2}[x] if x in ('FIELD', 'NONE') else const(x)
        t += 'PDP64_P2ROW(%d, %d, %d, %d, %d, %d, %d, %d)\n' % (const('P2OP_' + name), num(opc), num(reg), num(mode), num(rm), dsrc[ds], int(scale), int(idx))
    t += '#endif\n\n'
    # the widening chain: every record that has a longer form of the same instruction.  The names follow the multiclasses of PDP64InstrInfo.td.
    t += '// relaxation: PDP64_WIDEN(narrower, wider)\n#ifdef PDP64_WIDEN_TABLE\n'
    names = []
    mem = [(l, True) for l, v in real('mn-alu')]
    for n, w in widen_pairs():
        t += 'PDP64_WIDEN(%s, %s)\n' % (n, w)
    t += '#endif\n'
    return t


def widen_pairs():
    """(narrow record, wide record) for every instruction that has a longer form.  The record names are those of the multiclasses."""
    pairs = []
    modes = ['B', 'X', 'D', 'PC', 'I', 'A', 'PI', 'PD']
    memfam = []
    for l, v in real('mn-mov'):
        memfam.append((up(l), modes))
        memfam.append((up(l) + 'ST', [m for m in modes if m != 'I']))
    for l, v in real('mn-movz'):
        memfam.append((up(l), modes))
    memfam.append(('LEA', [m for m in modes if m != 'I']))
    for l, v in real('mn-alu'):
        memfam.append((up(l), modes))
    for l, v in real('mn-sop'):
        if l in ('pushm', 'popm'):
            continue
        memfam.append((up(l), modes))
    for l, v in real('mn-xfer'):
        memfam.append((up(l), ['X'] if l == 'jtag' else [m for m in modes]))
    for n, ms in memfam:
        for m in ms:
            pairs.append((n + '_' + m + '1', n + '_' + m + '2'))
    for l, v in real('mn-branch'):
        pairs.append((up(l) + '_0', up(l) + '_1'))
        pairs.append((up(l) + '_1', up(l) + '_2'))
    for l, v in real('mn-cbranch'):
        n = up(l)
        pairs.append((n, n + '_W'))             # four bytes -> six, wide immediate and 16-bit displacement
        pairs.append((n + '_W', n + '_L'))      # six bytes -> six, 5-bit immediate and 27-bit displacement
        pairs.append((n + '_RR1', n + '_RR2'))
    pairs.append(('SOB_1', 'SOB_2'))
    for l, v in real('mn-tag'):
        pairs.append((up(l) + '_1', up(l) + '_2'))
    return pairs


def fixups_def():
    t = hdr('//')
    t += '// PDP64_FIXUP(name, bits, parcels, pcrel, shift, relocation)\n'
    t += '//   bits: the width of the (signed) field; parcels: the length of the instruction; pcrel: measured from the first parcel;\n'
    t += '//   shift: 1 if counted in parcels; relocation: the ELF relocation type used if the value is not known (see relocs.h)\n'
    rows = [
        ('abs16', LIM['PDP64_WIDE_BITS_LEN1'], 2, 0, 0, 'INSN_ABS'),
        ('abs32', LIM['PDP64_WIDE_BITS_LEN2'], 3, 0, 0, 'INSN_ABS'),
        ('pc16', LIM['PDP64_WIDE_BITS_LEN1'], 2, 1, 0, 'INSN_PC'),
        ('pc32', LIM['PDP64_WIDE_BITS_LEN2'], 3, 1, 0, 'INSN_PC'),
        ('br8', LIM['PDP64_BRANCH_BITS_LEN0'], 1, 1, 1, 'INSN_BR'),
        ('br16', LIM['PDP64_BRANCH_BITS_LEN1'], 2, 1, 1, 'INSN_BR'),
        ('br32', LIM['PDP64_BRANCH_BITS_LEN2'], 3, 1, 1, 'INSN_BR'),
        ('cb11', LIM['PDP64_CB_BITS_LEN1'], 2, 1, 1, 'NONE'),
        ('cb27', LIM['PDP64_CB_BITS_LEN2'], 3, 1, 1, 'NONE'),
        ('cbw16', LIM['PDP64_CBW_BITS'], 3, 1, 1, 'NONE'),
        ('cbr12', LIM['PDP64_CBR_BITS_LEN1'], 2, 1, 1, 'NONE'),
        ('cbr28', LIM['PDP64_CBR_BITS_LEN2'], 3, 1, 1, 'NONE'),
    ]
    for name, bits, parcels, pcrel, shift, rel in rows:
        t += 'PDP64_FIXUP(%s, %d, %d, %d, %d, %s)\n' % (name, bits, parcels, pcrel, shift, rel)
    return t


def generate():
    o = Out()
    o.w('PDP64Consts.td', consts_td())
    o.w('PDP64RegisterInfo.td', regs_td())
    o.w('PDP64InstrDefs.td', instr_defs())
    o.w('PDP64Layout.h', layout_h())
    o.w('PDP64Tables.inc', tables_inc())
    o.w('PDP64Fixups.def', fixups_def())
    return o.files


def main():
    args = sys.argv[1:]
    check = '--check' in args
    out = OUT
    if '-o' in args:
        out = args[args.index('-o') + 1]
    files = generate()
    stale = 0
    os.makedirs(out, exist_ok=True)
    for name, text in files.items():
        p = os.path.join(out, name)
        if check:
            if not os.path.exists(p) or open(p).read() != text:
                print('stale: %s' % p)
                stale = 1
        else:
            open(p, 'w').write(text)
    if check:
        for name in os.listdir(out):
            if name not in files:
                print('extra: %s' % os.path.join(out, name))
                stale = 1
        if not stale:
            print('llvm/target/PDP64/gen is up to date')
        return stale
    print('wrote %d files to %s' % (len(files), out))
    return 0


if __name__ == '__main__':
    sys.exit(main())
