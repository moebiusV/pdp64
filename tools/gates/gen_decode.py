#!/usr/bin/env python3
"""gen_decode.py > decode.v -- the instruction decoder of the pdp64 as logic, generated from the grammar (tools/encgram.py): for each leaf, the match of its prefix on the first parcel,
and for each operand slot and the sub-opcode the AND-OR plane that extracts the bits of the matched leaf.  It is a count of the decoder's logic, not a working decoder
(the hot-register tables and the sign extension are left to the estimate): the structure and the sizes of the fields are the grammar's."""
import sys, os
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), '..'))
import encgram
d = encgram.load()
forms, leaves = d['forms'], d['leaves']
out = []
out.append('// generated by gen_decode.py from spec/pdp64/pdp64.hbnf: %d forms, %d leaves' % (len(forms), len(leaves)))
out.append('module decode(input [79:0] ib, output [2:0] nparcels, output [11:0] sub, output [31:0] f0, output [31:0] f1, output [31:0] f2, output [31:0] f3, output [7:0] form, output ill);')
def bit(b):			# b = 16*parcel + bit (bit 15 the top of the parcel)
    p, k = divmod(b, 16)
    return 'ib[%d]' % (79 - 16 * p - (15 - k))
nl = len(leaves)
for i, lf in enumerate(leaves):
    L = lf['L']; pre = lf['prefix']
    out.append('  wire h%d = (ib[79:%d] == %d\'d%d);' % (i, 80 - L, L, pre))
hits = ' | '.join('h%d' % i for i in range(nl))
out.append('  assign ill = ~(%s);' % hits)
fnum = lambda i: forms[leaves[i]['form']]['n']
for n in (1, 2, 3, 5):
    sel = ' | '.join('h%d' % i for i in range(nl) if fnum(i) == n) or '1\'b0'
    out.append('  wire n%d = %s;' % (n, sel))
out.append('  assign nparcels = n1 ? 3\'d1 : n2 ? 3\'d2 : n3 ? 3\'d3 : 3\'d5;')
# the form number (8 bits) as an OR of the hits
for b in range(8):
    sel = ' | '.join('h%d' % i for i, lf in enumerate(leaves) if (lf['form'] >> b) & 1) or '1\'b0'
    out.append('  wire fb%d = %s;' % (b, sel))
out.append('  assign form = {%s};' % ', '.join('fb%d' % b for b in range(7, -1, -1)))
# the sub-opcode: the bits of subbits (the positions of the sub-opcode of each leaf)
for b in range(12):
    terms = []
    for i, lf in enumerate(leaves):
        sb = lf['subbits']
        if b < len(sb): terms.append('(h%d & %s)' % (i, bit(sb[len(sb) - 1 - b])))
    out.append('  wire sb%d = %s;' % (b, ' | '.join(terms) or '1\'b0'))
out.append('  assign sub = {%s};' % ', '.join('sb%d' % b for b in range(11, -1, -1)))
# the operand fields: each leaf places the parts of its operands: concatenate the bits of operand oi in order (the width is the shape's)
for oi in range(4):
    for b in range(32):
        terms = []
        for i, lf in enumerate(leaves):
            bits = []
            for (o, pi, bl) in lf['place']:
                if o == oi: bits += bl
            # the first bit of the list is the top bit of the field: bit b of the field is the b-th from the bottom
            if b < len(bits): terms.append('(h%d & %s)' % (i, bit(bits[len(bits) - 1 - b])))
        out.append('  wire o%d_%d = %s;' % (oi, b, ' | '.join(terms) or '1\'b0'))
    out.append('  assign f%d = {%s};' % (oi, ', '.join('o%d_%d' % (oi, b) for b in range(31, -1, -1))))
out.append('endmodule')
print('\n'.join(out))
