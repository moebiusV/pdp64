#!/usr/bin/env python3
"""sum2d.py [OUTDIR] -- the tables of docs/encoding-work/vec-2d.md from OUTDIR/tiles.tsv (written by run2d.py).  Writes OUTDIR/summary.md.
Every number is a sim64 measurement of the cycle models of docs/sim64.md (model 1: instruction counts with the memory port; model 2: the latency model, fpga table, vpipe 1) with the driver's set-up
subtracted; the row advance costs `vrow` cycles a row (an ASSUMPTION: default 1).  Scalar instructions are 1 cycle each in both models."""
import csv, os, sys, collections
HERE = os.path.dirname(os.path.abspath(__file__))
OUT = sys.argv[1] if len(sys.argv) > 1 else os.path.join(HERE, '2d-results')
D = {}
for r in csv.DictReader(open(os.path.join(OUT, 'tiles.tsv')), delimiter='\t'):
    D[(r['kernel'], int(r['W']), int(r['H']), r['variant'], int(r['strip']), int(r['port']), int(r['vrow']), int(r['vmemlat']))] = r
def g(k, w, h, v, s=16, p=16, vr=1, vm=4, f='cycles_model1'):
    x = D.get((k, w, h, v, s, p, vr, vm)) or D.get((k, w, h, v, 16, 16, 1, 4))
    return int(x[f])
K = ['sad', 'avg', 'mblend', 'blend', 'put8h', 'gray', 'thresh', 'quant']
SQ = [(8, 8), (16, 16), (32, 32), (64, 64), (256, 256)]
WD = [(8, 16), (16, 16), (32, 16), (64, 16), (128, 16)]
o = []
w = o.append
w('# vec-2d measurements (generated by tools/gates/sum2d.py from tiles.tsv; sim64 cycle models, measured)\n')
def table(title, tiles, strip, f='cycles_model1'):
    w('### %s\n' % title)
    w('| kernel | tile | scalar C | lv (compiler, 1D blocks) | rows (hand, loop of 1D blocks) | 2D (vec2) | 2D over rows | rows over scalar | 2D over scalar |')
    w('|---|---|---:|---:|---:|---:|---:|---:|---:|')
    for k in K:
        for (a, b) in tiles:
            sc = g(k, a, b, 'scalar', f=f); lv = g(k, a, b, 'lv', strip, f=f); ro = g(k, a, b, 'rows', strip, f=f); t2 = g(k, a, b, '2d', strip, f=f)
            w('| %s | %dx%d | %d | %d | %d | %d | %.2f | %.1f | %.1f |' % (k, a, b, sc, lv, ro, t2, ro / t2, sc / ro, sc / t2))
    w('')
table('Square tiles, strip 16 (128-bit), port 16, model 1, row cost 1', SQ, 16)
table('Widths with 16 rows, strip 16, port 16, model 1', WD, 16)
table('Square tiles, strip 32 (256-bit), port 16, model 1', SQ, 32)
table('Square tiles, strip 16, port 16, model 2 (fpga latencies, vmemlat 4)', SQ, 16, 'cycles_model2')
table('Widths with 16 rows, strip 16, port 16, model 2', WD, 16, 'cycles_model2')
w('### Instructions executed (model 1 inputs): scalar instructions and vector instructions (one per strip), 16x16 and 64x64, strip 16\n')
w('| kernel | tile | form | scalar insns | vector insns | strips | rows |')
w('|---|---|---|---:|---:|---:|---:|')
for k in K:
    for (a, b) in ((16, 16), (64, 64)):
        for v in ('scalar', 'lv', 'rows', '2d'):
            x = D[(k, a, b, v, 16, 16, 1, 4)]
            w('| %s | %dx%d | %s | %s | %s | %s | %s |' % (k, a, b, v, x['scalar_insns'], x['vector_insns'], x['strips'], x['rows']))
w('')
# strip 32 against strip 16
w('### Does a 256-bit strip gain on narrow tiles? (cycles at strip 16 over cycles at strip 32; port 16; model 1; 1.00 is no gain)\n')
w('| kernel | form | 8x16 | 16x16 | 32x16 | 64x16 | 128x16 |')
w('|---|---|---:|---:|---:|---:|---:|')
for k in K:
    for v in ('rows', '2d'):
        w('| %s | %s | ' % (k, v) + ' | '.join('%.2f' % (g(k, a, b, v, 16) / g(k, a, b, v, 32)) for (a, b) in WD) + ' |')
w('')
# the break-even: the 2D gain over the loop of 1D blocks against the strips a row has
w('### The 2D block over the loop of 1D blocks against the strips of a row (model 1, port 16, 16 rows, strip 16 and 32; the value is rows cycles over 2D cycles)\n')
w('| kernel | W = 8 | 16 | 32 | 64 | 128 |   strips of 16 bytes a row (for a byte kernel): 0.5, 1, 2, 4, 8 |')
w('|---|---:|---:|---:|---:|---:|---|')
for k in K:
    for s in (16, 32):
        w('| %s strip %d | ' % (k, s) + ' | '.join('%.2f' % (g(k, a, b, 'rows', s) / g(k, a, b, '2d', s)) for (a, b) in WD) + ' | |')
w('')
w('### The same against the height (W = 16, strip 16): rows cycles over 2D cycles for 1, 2, 4, 8, 16 ... rows is not in the grid; the grid has 8x8, 16x16, 32x32, 64x64, 256x256 (above)\n')
# sensitivities
w('### Sensitivities (sad and blend 16x16 and 64x64, strip 16; cycles; 2D over rows in brackets)\n')
w('| kernel | tile | model | row cost 0 | row cost 1 | row cost 2 | vmemlat 2 | vmemlat 4 | vmemlat 8 | port 8 | port 16 | port 32 |')
w('|---|---|---|---|---|---|---|---|---|---|---|---|')
for k in ('sad', 'blend', 'avg'):
    for (a, b) in ((16, 16), (64, 64)):
        for f, nm in (('cycles_model1', '1'), ('cycles_model2', '2')):
            cells = []
            for (vr, vm, p) in ((0, 4, 16), (1, 4, 16), (2, 4, 16), (1, 2, 16), (1, 4, 16), (1, 8, 16), (1, 4, 8), (1, 4, 16), (1, 4, 32)):
                ro = g(k, a, b, 'rows', 16, p, vr, vm, f); t2 = g(k, a, b, '2d', 16, p, vr, vm, f)
                cells.append('%d (%.2f)' % (t2, ro / t2))
            w('| %s | %dx%d | %s | ' % (k, a, b, nm) + ' | '.join(cells) + ' |')
w('')
# checked
w('### The checked tile (chk2 once per row and stream in the loop of blocks; once per tile in the 2D block): scalar instructions, vector instructions, cycles (strip 16, port 16, model 1, model 2)\n')
w('| kernel | tile | form | scalar insns | cycles m1 | cycles m2 | check cost over the unchecked form (m1) |')
w('|---|---|---|---:|---:|---:|---:|')
for k in ('sad', 'mblend'):
    for (a, b) in SQ + [(8, 16), (32, 16), (64, 16), (128, 16)]:
        for v, base in (('rows', None), ('rows.chk', 'rows'), ('2d', None), ('2d.chk', '2d')):
            x = D[(k, a, b, v, 16, 16, 1, 4)]
            c1 = int(x['cycles_model1']); c2 = int(x['cycles_model2'])
            ov = '%+d (%+.1f%%)' % (c1 - g(k, a, b, base), 100.0 * (c1 - g(k, a, b, base)) / g(k, a, b, base)) if base else ''
            w('| %s | %dx%d | %s | %s | %d | %d | %s |' % (k, a, b, v, x['scalar_insns'], c1, c2, ov))
w('')
open(os.path.join(OUT, 'summary.md'), 'w').write('\n'.join(o) + '\n')
print('wrote', os.path.join(OUT, 'summary.md'))
