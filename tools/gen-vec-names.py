#!/usr/bin/env python3
"""gen-vec-names.py -- the executor's name table of the vec family, from spec/facts/vec.toml (errata 183).

    tools/gen-vec-names.py            write common/pdp64exec_vecbases.inc: the table `vbases[]` { base mnemonic, VO_ operation } that common/pdp64exec_vec.inc includes
    tools/gen-vec-names.py --check    exit 1 if the file on disk differs, or if the executor and the facts disagree:
                                        every `exec` of the facts is a member of the enum of pdp64exec_vec.inc and is handled by a `case` of its decoder (vec_classify) or
                                        its semantics, and every `case VO_x` of the executor is the `exec` of some base (VO_NONE excepted)

The executor's semantics (the `case VO_xxx` code) and the enum stay hand-written; the name table is the fact."""
import os, re, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, 'tools'))
import facts

OUT = os.path.join(ROOT, 'common', 'pdp64exec_vecbases.inc')
EXEC = os.path.join(ROOT, 'common', 'pdp64exec_vec.inc')


def generate():
    F = facts.load('vec')
    lines = ['/* The name table of the vec family: GENERATED by tools/gen-vec-names.py from spec/facts/vec.toml (the field exec of each base mnemonic); never edit it. */',
             'static const struct { const char *base; int op; } vbases[] = {']
    row = '\t'
    for b, t in F.items():
        item = '{ "%s", %s }, ' % (b, t['exec'])
        if len(row) + len(item) > 150:
            lines.append(row.rstrip())
            row = '\t'
        row += item
    lines.append(row.rstrip())
    lines.append('};')
    return '\n'.join(lines) + '\n'


def problems():
    out = []
    F = facts.load('vec')
    src = open(EXEC).read()
    enum = set(re.findall(r'\b(VO_[A-Z0-9]+)\b', src[src.index('enum {'):src.index('};', src.index('enum {'))])) - {'VO_NONE'}
    cases = set(re.findall(r'\bcase (VO_[A-Z0-9]+)\s*:', src)) | set(re.findall(r'\bvi->op [=!]= (VO_[A-Z0-9]+)', src)) | set(re.findall(r'\bop [=!]= (VO_[A-Z0-9]+)', src))
    have = {t['exec'] for t in F.values()}
    for b, t in F.items():
        if t['exec'] not in enum:
            out.append('%s: exec %s is not in the enum of pdp64exec_vec.inc' % (b, t['exec']))
        elif t['exec'] not in cases:
            out.append('%s: exec %s has no `case` (nor a test of the operation) in pdp64exec_vec.inc' % (b, t['exec']))
    for c in sorted(cases - have):
        out.append('pdp64exec_vec.inc has `case %s` and no base of spec/facts/vec.toml has exec = "%s"' % (c, c))
    for c in sorted(enum - have):
        out.append('the enum of pdp64exec_vec.inc has %s and no base has exec = "%s"' % (c, c))
    return out


def main(argv):
    text = generate()
    if argv[1:] == ['--check']:
        bad = ['exec: ' + p for p in problems()]
        if not os.path.exists(OUT) or open(OUT).read() != text:
            bad.append('common/pdp64exec_vecbases.inc is not what spec/facts/vec.toml says (run tools/gen-vec-names.py)')
        for p in bad:
            print('gen-vec-names: ' + p)
        if not bad:
            print('gen-vec-names: ok')
        return 1 if bad else 0
    open(OUT, 'w').write(text)
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv))
