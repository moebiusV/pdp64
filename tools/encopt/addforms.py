#!/usr/bin/env python3
"""addforms.py -- the committed grammar plus the forced forms of the vec, tile and GEMM family (docs/codegen-data/encoding/vecfam.py), without the corpus.

The prefix optimiser (export.py --write-grammar) needs the 841-file corpus compiled by pcc; this builds the same grammar from the committed one: it keeps every form,
drops the candidate forms named by --drop (they are chosen by tools/encopt/vecdrop.py from the value of each candidate per first-parcel pattern in the statistics of
tests/current.encopt: the least valuable go first), adds the forced forms of vecfam.py, and writes the grammar with the writer the optimiser uses.  The encodings of the
family are provisional by design (no usage weights: nothing emits these instructions yet): they are to be benchmarked and pruned, and the optimiser is to be run again on
the corpus compiled by the LLVM back end.

  addforms.py --grammar-out DIR [--drop NAME]... [--drop-file FILE]

  then  cp DIR/*.hbnf spec/grammars.d/ and  python3 tools/grammars_d.py --write

It writes the three generated parts of the encoding grammar and nothing else (errata 179, the owner's rule: "any generated hbnf should be an include into the master hbnf
file that is hand edited"; errata 180: the parts are the drop-in directory spec/grammars.d/): DIR/20-enc-forms.hbnf, 21-enc-shapes.hbnf and 80-mn-ext.hbnf, whole files that begin
`; GENERATED by ... do not edit`.  It owns the forms whose `form-` rule is in 20-enc-forms.hbnf: the forms of a hand-written part (a family a person dropped into spec/grammars.d/)
are read like the others but neither rewritten nor dropped by it, and `insn` (10-enc-insn.hbnf) is tools/grammars_d.py's (run `python3 tools/grammars_d.py --write` after copying).
The prefixes of the forms it owns are chosen without knowledge of a hand-written family's: a hand-written leaf takes a prefix that is free (tools/mkenc.py checks that the prefixes form
a prefix code and names the overlap).  Run on the committed tree with no change to vecfam.py it writes the committed parts byte for byte (tools/check-grammar-enc.sh checks that).
"""
import sys, os, json, argparse, re, difflib
HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, '..', '..'))
ENC = os.path.join(ROOT, 'docs', 'codegen-data', 'encoding')
sys.dont_write_bytecode = True
sys.path.insert(0, ENC)
sys.path.insert(0, os.path.join(ROOT, 'tools'))
sys.path.insert(0, HERE)
ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
ap.add_argument('--grammar-out', required=True)
ap.add_argument('--drop', action='append', default=[])
ap.add_argument('--drop-file')
ap.add_argument('--corpus', default='')
ap.add_argument('--remove-word', action='append', default=[], metavar='FORM=WORD', help='remove a word from a form (the form is rebuilt without it; every later word of its leaves moves down)')
ap.add_argument('--add-word', action='append', default=[], metavar='FORM=WORD', help='add a word at the end of a form (it is numbered by the group mn-ext, which this tool writes)')
ap.add_argument('--repack-hand', metavar='SPECDIR', help='after the forms are laid out, move the leaves of the hand-written parts of SPECDIR/grammars.d to the first free patterns behind the generated ones (their prefixes are rewritten in place, their length is kept)')
a = ap.parse_args()
os.environ['PDP64_CORPUS_DIR_R32'] = a.corpus
os.environ['PDP64_NO_CORPUS'] = '1'
import encgram, enc, grammars_d
from enc import *
import importlib.util
spec = importlib.util.spec_from_file_location('chk', os.path.join(ROOT, 'tools', 'check-enc.py'))
chk = importlib.util.module_from_spec(spec); spec.loader.exec_module(chk)
from variants import Scheme
import vecfam, export_forms, write_hbnf

drops = set(a.drop)
if a.drop_file:
    drops |= {l.strip() for l in open(a.drop_file) if l.strip()}
d = encgram.load()
owned = {os.path.normpath(p['path']) for p in grammars_d.parts() if p['tool'] == 'tools/encopt/addforms.py'}
forms = [Form(f['name'], f['n'], f['mns'], [chk.mkspec(s) for s in f['specs']], xbits=f['xbits']) for f in d['forms'] if os.path.normpath(f['file']) in owned]
# a word of a group in HAND_GROUPS (a part with a form of its own, such as the atomics of 30-mn-core.hbnf and 57-enc-atomic.hbnf) is not a word of a generated form: when a family moves
# to a part of its own the generated forms stop listing it, and the forms keep their prefixes (a form with xbits has a fixed prefix whatever the number of its words)
import mkgrammar
HAND_GROUPS = ('mn-atom',)
hand = {lit for g, items in mkgrammar.enums().items() if g in HAND_GROUPS for lit, v in items}
for f in forms:
    if any(m in hand for m in f.mns):
        f.mns = [m for m in f.mns if m not in hand]
        f._ms = set(f.mns)
# a word listed twice in a form is a second slot of the same instruction (nothing assembles to it): the form keeps the first
for f in forms:
    seen = []
    for m in f.mns:
        if m not in seen: seen.append(m)
    if len(seen) != len(f.mns):
        print('addforms: %s lists %s more than once: the second slot is removed' % (f.name, ' '.join(sorted({m for m in f.mns if f.mns.count(m) > 1}))))
        f.mns = seen; f._ms = set(seen)
for spec_ in a.remove_word:
    fn, w = spec_.split('=', 1)
    hit = [f for f in forms if f.name == fn and w in f.mns]
    if not hit:
        print('addforms: %s has no word %s (already removed)' % (fn, w)); continue
    hit[0].mns = [m for m in hit[0].mns if m != w]; hit[0]._ms = set(hit[0].mns)
for spec_ in a.add_word:
    fn, w = spec_.split('=', 1)
    hit = [f for f in forms if f.name == fn]
    if not hit:
        print('addforms: no form %s' % fn); sys.exit(1)
    if w in hit[0].mns:
        print('addforms: %s has the word %s (already added)' % (fn, w)); continue
    hit[0].mns = hit[0].mns + [w]; hit[0]._ms = set(hit[0].mns)
known = {f.name for f in forms}
# idempotent: a form already dropped is not an error, and the forms of the family that the grammar already has are replaced by the ones vecfam.py makes now
for n in sorted(drops - known):
    print('addforms: %s is not in the grammar (already dropped)' % n)
vec = vecfam.vec_forms(SR(5))
vnames = {f.name for f in vec}
forms = [f for f in forms if f.name not in drops and f.name not in vnames] + vec
sc = Scheme(forms)
print('addforms: %d forms (%d dropped, %d added), %d leaves, kraft %.5f (%d of 65536 patterns)' % (len(sc.forms), len(drops), len(vec), len(sc.code.leaves), sc.code.kraft, round(sc.code.kraft * 65536)))
hot = d['hot16']
dd = json.loads(json.dumps(export_forms.export('32', sc, 'r32', hot), default=str))
write_hbnf.write_all(a.grammar_out, [('32', dd)])


print('addforms: written to %s' % a.grammar_out)

if a.repack_hand:
    # the leaves of the hand-written parts take the first aligned free patterns behind the generated leaves, widest first; a prefix keeps its length
    gd = os.path.join(a.repack_hand, 'grammars.d')
    pat = re.compile(r'^(leaf-\S+ = 0b)([01]+)', re.M)
    hand_leaves = []
    for p_ in grammars_d.parts():
        if p_['generated'] or not p_['path'].endswith('.hbnf'): continue
        t = open(p_['path']).read()
        for m_ in pat.finditer(t): hand_leaves.append((len(m_.group(2)), p_['path'], m_.group(1) + m_.group(2)))
    free = [(sc.code.used, 65536)]
    order = sorted(range(len(hand_leaves)), key=lambda i: (hand_leaves[i][0], hand_leaves[i][1], hand_leaves[i][2]))
    new = {}
    for i in order:
        L, path, old = hand_leaves[i]; size = 1 << (16 - L)
        best = None
        for k, (lo, hi) in enumerate(free):
            at = (lo + size - 1) // size * size
            if at + size <= hi and (best is None or at < best[1]): best = (k, at)
        k, at = best
        lo, hi = free.pop(k)
        free[k:k] = [x for x in ((lo, at), (at + size, hi)) if x[0] < x[1]]
        new[(path, old)] = old[:-L] + format(at >> (16 - L), '0%db' % L)
    pos = 65536 - sum(hi - lo for lo, hi in free)
    for path in sorted({k[0] for k in new}):
        t = open(path).read()
        for (pth, old), nw in new.items():
            if pth == path: t = t.replace(old, nw, 1)
        open(path, 'w').write(t)
    print('addforms: %d hand-written leaves repacked behind the generated ones (patterns used: %d of 65536)' % (len(new), pos))

