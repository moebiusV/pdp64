/* the host's side of the shared instruction core (common/pdp64exec.c)                                                 */

static uint64_t h_ld(void *u, uint64_t a, int size) { (void)u; if (tm_on) tm_mem(0, a, size); return ld(a, size); }
static void h_st(void *u, uint64_t a, int size, uint64_t v) { (void)u; if (tm_on) tm_mem(1, a, size); st(a, size, v); }
static void h_fault(void *u, const char *what, uint64_t addr) { (void)u; die(what, addr); }
static void h_trap(void *u, int n) { (void)u; syscall_n(n); }
static void h_halt(void *u) { (void)u; if (trace) regdump(stderr); fflush(stdout); exit((int)(cpu.r[0] & 255)); }
static int h_probe(void *u, uint64_t a, int write, int mode) { (void)u; (void)write; (void)mode; return mapped(a); }
static uint64_t h_fetch(void *u, uint64_t a) { (void)u; return ld(a, 2); }
static int h_vecread(void *u, uint64_t pa, uint64_t *v)
{
	(void)u;
	if (!mapped(pa) || !mapped(pa + 7)) return 1;
	*v = 0;
	for (int i = 0; i < 8; i++) *v |= (uint64_t)*bp(pa + i, 0) << (8 * i);
	return 0;
}
static void h_check(void *u, uint64_t a, int size, int write) { (void)u; if (a & (size - 1)) memfault(VECTOR_MISALIGNED, "misaligned data access", a); bp(a, write); bp(a + size - 1, write); }
/* the atomic words (errata 211): one core, so the access is one load and one store; the checks come first and change nothing (alignment, the mapping, and the -x page that faults at its first store) */
static uint64_t h_atomic(void *u, uint64_t a, int size, int op, uint64_t x, uint64_t y)
{
	uint64_t old, nv;
	(void)u;
	if (a & (size - 1)) memfault(VECTOR_MISALIGNED, "misaligned atomic access", a);
	bp(a, 1); bp(a + size - 1, 1);
	if (op == PDP64_AMO_CHECK) return 0;
	if (tm_on) tm_mem(1, a, size);
	old = ld(a, size);
	if (pdp64_amo_result(op, size, old, x, y, &nv)) st(a, size, nv);
	return old;
}
static void h_tlb(void *u, int op, uint64_t a) { (void)u; (void)op; (void)a; }
static void h_raise(void *u, int vector, uint64_t eva) { (void)u; jvec = vector; jeva = eva; longjmp(jb, 1); }
static struct pdp64_env env = { h_ld, h_st, h_fault, h_trap, h_halt, h_probe, h_fetch, h_vecread, h_check, h_tlb, h_raise, NULL, NULL, NULL, h_atomic };

/* the profile (-P) */
static void h_profile(void *u, uint64_t pc, int nparcels, int cat)
{
	(void)u;
	if (tm_on) tm_begin(pc, nparcels);
	if (!profile_path) return;
	prof.ninsn++; prof.nbytes += 2 * nparcels; prof.cat[cat]++;
	if (pc >= prof.lo && pc < prof.hi) {
		uint64_t i = (pc - prof.lo) >> 1;
		if (!prof.count[i]++) { prof.len[i] = (uint8_t)(2 * nparcels); prof.cat_of[i] = (uint8_t)cat; }
	}
}
static void profile_write(void)
{
	static const char *const names[] = PDP64_CAT_NAMES;
	FILE *o = fopen(profile_path, "w");
	if (!o) { perror(profile_path); return; }
	fprintf(o, "#encoding pdp64\n#instructions %llu\n#bytes %llu\n",
	    (unsigned long long)prof.ninsn, (unsigned long long)prof.nbytes);
	for (int i = 0; i < PDP64_NCAT; i++) fprintf(o, "#category %s %llu\n", names[i], (unsigned long long)prof.cat[i]);
	for (uint64_t i = 0; i < ((prof.hi - prof.lo) >> 1); i++)
		if (prof.count[i]) fprintf(o, "%llx %u %u %u\n", (unsigned long long)(prof.lo + 2 * i), prof.count[i], prof.len[i], prof.cat_of[i]);
	fprintf(o, "#vec blocks %llu strips %llu ops %llu elems %llu\n", (unsigned long long)cpu.vblocks, (unsigned long long)cpu.vstrips, (unsigned long long)cpu.vops, (unsigned long long)cpu.velems);
	fclose(o);
}

/* -V: the counters of the vector blocks, to standard error at exit */
static const char *lat_arg = "fpga";
static int lat_set, vmix;
/* the latency table of the second model: a built-in one by name (a table for each strip of 8, 16 and 32 bytes: the depth of a tree or a network depends on the strip; a strip of 64 bytes takes the
   table of 32), or a file whose lines (`class latency interval`, or `class@strip latency interval` for one strip only) change classes of the fpga table; '#' starts a comment */
static void vlat_setup(void)
{
	int strip = cpu.vstrip ? cpu.vstrip : 32, si = strip == 8 ? 0 : strip == 16 ? 1 : 2;
	const int (*tab)[2] = !strcmp(lat_arg, "asic") ? vlat_asic[si] : vlat_fpga[si];
	for (int c = 0; c < VC_N; c++) { cpu.vlat[c] = tab[c][0]; cpu.vint[c] = tab[c][1]; }
	if (!strcmp(lat_arg, "fpga") || !strcmp(lat_arg, "asic")) return;
	FILE *f = fopen(lat_arg, "r");
	if (!f) { perror(lat_arg); exit(2); }
	char line[256];
	for (int ln = 1; fgets(line, sizeof line, f); ln++) {
		char *h = strchr(line, '#'); if (h) *h = 0;
		char name[64]; int lat, itv, at = 0;
		int n = sscanf(line, "%63s %d %d", name, &lat, &itv);
		if (n < 1) continue;
		char *amp = strchr(name, '@');
		if (amp) { *amp = 0; at = atoi(amp + 1); }
		int c;
		for (c = 0; c < VC_N; c++) if (!strcmp(name, pdp64_vclass_name(c))) break;
		if (n != 3 || c == VC_N || lat < 0 || itv < 1 || (amp && at != 8 && at != 16 && at != 32)) { fprintf(stderr, "sim64: %s:%d: expected `class[@strip] latency interval` with a known class (see docs/encoding-work/vec-latency.md)\n", lat_arg, ln); exit(2); }
		if (amp && at != strip && !(strip == 64 && at == 32)) continue;
		cpu.vlat[c] = lat; cpu.vint[c] = itv;
	}
	fclose(f);
}

static void vec_write(void)
{
	fprintf(stderr, "sim64: vec blocks %llu strips %llu ops %llu elems %llu\n", (unsigned long long)cpu.vblocks, (unsigned long long)cpu.vstrips, (unsigned long long)cpu.vops, (unsigned long long)cpu.velems);
	/* the cycle model (docs/sim64.md): scalar instructions started (the vec of a block is one of them) are one cycle each; the vector cycles are the vends and, for each strip, the greater of
	   its compute and memory-port cycles plus the commit cost.  `steps` is the number of instructions completed before the one that ended the program */
	unsigned long long scalar = (unsigned long long)steps + 1;
	fprintf(stderr, "sim64: vec model strip %d port %d commit %d: scalar %llu vector %llu (compute %llu memory %llu memory-bound strips %llu) total %llu\n",
	    cpu.vstrip ? cpu.vstrip : 32, cpu.vport ? cpu.vport : 16, cpu.vcommit_set ? cpu.vcommit : 1, scalar, (unsigned long long)cpu.vcycles,
	    (unsigned long long)cpu.vcyc_comp, (unsigned long long)cpu.vcyc_mem, (unsigned long long)cpu.vmemstrips, scalar + (unsigned long long)cpu.vcycles);
	/* the second model (latencies; docs/encoding-work/vec-latency.md): the scalar instructions are the same 1 cycle each */
	fprintf(stderr, "sim64: vec model2 latency %s strip %d port %d commit %d vpipe %d vmemlat %d: scalar %llu vector %llu (blocks with a hidden accumulator %llu, with a scalar dependence %llu) total %llu\n",
	    lat_arg, cpu.vstrip ? cpu.vstrip : 32, cpu.vport ? cpu.vport : 16, cpu.vcommit_set ? cpu.vcommit : 1, cpu.vpipe, cpu.vmemlat, scalar, (unsigned long long)cpu.v2cycles,
	    (unsigned long long)cpu.v2hidden, (unsigned long long)cpu.v2sdep, scalar + (unsigned long long)cpu.v2cycles);
	if (cpu.v2blocks) fprintf(stderr, "sim64: vec2 blocks %llu rows %llu vskips %llu row-cost %d\n", (unsigned long long)cpu.v2blocks, (unsigned long long)cpu.vrows, (unsigned long long)cpu.vskips, cpu.vrow_set ? cpu.vrow : 1);
	if (vmix) { fprintf(stderr, "sim64: vec mix"); for (int c = 0; c < VC_N; c++) fprintf(stderr, " %s %llu", pdp64_vclass_name(c), (unsigned long long)cpu.v2n[c]); fprintf(stderr, "\n"); }
}

/* -K: the pending interrupt requests; the highest level above the priority is taken */
static int take_interrupt(void)
{
	int best = -1;
	for (int i = 0; i < nirqs; i++)
		if (!irqs[i].done && irqs[i].count <= steps && (best < 0 || irqs[i].level > irqs[best].level)) best = i;
	if (best >= 0 && pdp64_interrupt(&cpu, &env, irqs[best].level, irqs[best].vector)) { irqs[best].done = 1; return 1; }
	return 0;
}

static void step(void)
{
	if (trace) {
		int len = pdp64_insn_parcels((uint16_t)ld(cpu.pc, 2)) - 1;
		if (len < 0) len = 0;
		fprintf(stderr, "%08llx:", (unsigned long long)cpu.pc);
		for (int i = 0; i <= len; i++) fprintf(stderr, " %04x", (unsigned)ld(cpu.pc + 2 * i, 2));
		fprintf(stderr, "%*s sp=%llx\n", (4 - len) * 5, "", (unsigned long long)cpu.r[14]);
	}
	pdp64_step(&cpu, &env);
	if (tm_on) tm_retire(tms, ntms, cpu.pc);
}

static void timing_write(void)
{
	FILE *o = timing_out ? fopen(timing_out, "a") : stderr;
	if (!o) { perror(timing_out); return; }
	tm_report(tms, ntms, o, prog_name);
	if (o != stderr) fclose(o);
	if (timing_pc) for (int k = 0; k < ntms; k++) {		/* FILE.NAME for each model */
		char path[512];
		snprintf(path, sizeof path, "%s.%s", timing_pc, tm_name(tms[k]));
		FILE *p = fopen(path, "w"); if (p) { tm_pcdump(tms[k], p); fclose(p); }
	}
}

static void step_k(void)
{
	if (setjmp(jb)) { pdp64_exception(&cpu, &env, jvec, jeva); return; }
	take_interrupt();
	if (cpu.hve) pdp64_virtual_interrupt(&cpu, &env);					/* a guest: a virtual line above its priority (after the physical requests, which exit first) */
	while (cpu.wait) {								/* wfe: nothing runs until a request arrives */
		if (pdp64_virq_pending(&cpu)) { cpu.wait = 0; break; }				/* a pending virtual line ends a WFE, even a masked one (7.10.2); it is taken when the guest's priority allows */
		long next = -1;
		for (int i = 0; i < nirqs; i++) if (!irqs[i].done && (next < 0 || irqs[i].count < next)) next = irqs[i].count;
		if (next < 0 || (steps < next && (steps = next, 0)) || !take_interrupt()) {
			fprintf(stderr, "sim64: wfe at pc=%#llx with no interrupt that can be taken\n", (unsigned long long)cpu.pc);
			exit(125);
		}
	}
	step();
}

int main(int argc, char **argv)
{
	int regs = 0, mode = MODE_USER, sys = 0, hve = 0, ntms_spec = 0, strip_set = 0, vml_set = 0;
	const char *prog = NULL, *timing_specs[32];
	for (int i = 1; i < argc; i++) {
		if (!strcmp(argv[i], "-t")) trace = 1;
		else if (!strcmp(argv[i], "-r")) regs = 1;
		else if (!strcmp(argv[i], "-V")) { atexit(vec_write); cpu.vm2 = 1; }
		else if (!strncmp(argv[i], "--latency=", 10)) { lat_arg = argv[i] + 10; lat_set = 1; }
		else if (!strcmp(argv[i], "--vmix")) vmix = 1;
		else if (!strncmp(argv[i], "--vpipe=", 8)) { int v = atoi(argv[i] + 8); if (v < 1 || v > 16) { fprintf(stderr, "sim64: --vpipe=N (1 to 16)\n"); return 2; } cpu.vpipe = v; }
		else if (!strncmp(argv[i], "--vmemlat=", 10)) { int v = atoi(argv[i] + 10); if (v < 0 || v > 1000) { fprintf(stderr, "sim64: --vmemlat=CYCLES (0 to 1000)\n"); return 2; } cpu.vmemlat = v; vml_set = 1; }
		else if (!strcmp(argv[i], "-S") && i + 1 < argc) { int v = atoi(argv[++i]); if (v != 8 && v != 16 && v != 32 && v != 64) { fprintf(stderr, "sim64: -S 8, 16, 32 or 64\n"); return 2; } cpu.vstrip = v; strip_set = 1; }
		else if (!strncmp(argv[i], "--vport=", 8)) { int v = atoi(argv[i] + 8); if (v < 1 || v > 1024) { fprintf(stderr, "sim64: --vport=BYTES (1 to 1024)\n"); return 2; } cpu.vport = v; }
		else if (!strncmp(argv[i], "--vrow=", 7)) { int v = atoi(argv[i] + 7); if (v < 0 || v > 1024) { fprintf(stderr, "sim64: --vrow=CYCLES (0 to 1024)\n"); return 2; } cpu.vrow = v; cpu.vrow_set = 1; }
		else if (!strncmp(argv[i], "--vcommit=", 10)) { int v = atoi(argv[i] + 10); if (v < 0 || v > 1024) { fprintf(stderr, "sim64: --vcommit=CYCLES (0 to 1024)\n"); return 2; } cpu.vcommit = v; cpu.vcommit_set = 1; }
		else if (!strcmp(argv[i], "-k")) mode = MODE_KERNEL;
		else if (!strcmp(argv[i], "-K")) mode = MODE_KERNEL, sys = 1;
		else if (!strcmp(argv[i], "-H")) mode = MODE_KERNEL, sys = 1, hve = 1;
		else if (!strcmp(argv[i], "-i") && i + 1 < argc && nirqs < 64) {
			struct irq *q = &irqs[nirqs++];
			if (sscanf(argv[++i], "%ld:%d:%d", &q->count, &q->level, &q->vector) != 3 || q->level < 1 || q->level > 7 || q->vector < 0 || q->vector >= VECTOR_COUNT) { fprintf(stderr, "sim64: -i N:LEVEL:VECTOR\n"); return 2; }
		}
		else if (!strcmp(argv[i], "-x") && i + 1 < argc) {
			unsigned long long lo, hi;
			if (sscanf(argv[++i], "%lli:%lli", (long long *)&lo, (long long *)&hi) != 2 || lo % PG || hi % PG || hi <= lo) { fprintf(stderr, "sim64: -x LO:HI (page aligned)\n"); return 2; }
			xlo = lo; xhi = hi; xarmed = malloc((xhi - xlo) / PG); memset(xarmed, 1, (xhi - xlo) / PG); addregion(xlo, xhi);
		}
		else if (!strcmp(argv[i], "-n") && i + 1 < argc) maxsteps = atol(argv[++i]);
		else if (!strcmp(argv[i], "-P") && i + 1 < argc) profile_path = argv[++i];
		else if (!strcmp(argv[i], "-m") && i + 1 < argc) { if (strcmp(argv[++i], "pdp64")) { fprintf(stderr, "sim64: -m %s: the only target is pdp64\n", argv[i]); return 2; } }
		else if (!strncmp(argv[i], "--timing=", 9) && ntms_spec < 32) timing_specs[ntms_spec++] = argv[i] + 9;
		else if (!strncmp(argv[i], "--timing-out=", 13)) timing_out = argv[i] + 13;
		else if (!strncmp(argv[i], "--timing-pc=", 12)) timing_pc = argv[i] + 12;
		else if (!strcmp(argv[i], "--timing-help")) { tm_help(stdout); return 0; }
		else if (argv[i][0] == '-') { fprintf(stderr, "usage: sim64 [-t] [-r] [-k | -K | -H] [-i N:LEVEL:VECTOR] [-x LO:HI] [-V] [-S bytes] [--vport=n] [--vcommit=n] [--vrow=n] [--latency=fpga|asic|file] [--vpipe=n] [--vmemlat=n] [-n steps] [-P file] [--timing=SPEC]... [--timing-out=FILE] [--timing-pc=FILE] program\n"); return 2; }
		else prog = argv[i];
	}
	if (!prog) { fprintf(stderr, "usage: sim64 [-t] [-r] [-k | -K | -H] [-i N:LEVEL:VECTOR] [-x LO:HI] [-V] [-S bytes] [--vport=n] [--vcommit=n] [--vrow=n] [--latency=fpga|asic|file] [--vpipe=n] [--vmemlat=n] [-n steps] [-P file] [--timing=SPEC]... [--timing-out=FILE] [--timing-pc=FILE] program\n"); return 2; }
	pdp64_init();
	if (!cpu.vpipe) cpu.vpipe = 1;
	if (!vml_set) cpu.vmemlat = 4;
	vlat_setup();
	if (!strip_set && getenv("PDP64_VSTRIP")) { int v = atoi(getenv("PDP64_VSTRIP")); if (v != 8 && v != 16 && v != 32 && v != 64) { fprintf(stderr, "sim64: PDP64_VSTRIP 8, 16, 32 or 64\n"); return 2; } cpu.vstrip = v; }
	if (cpu.vstrip == 8) fprintf(stderr, "sim64: warning: a strip of 8 bytes is outside the architecture (the least strip is 16 bytes, docs/encoding-work/vec-isa.md section 8): kept for the cycle study; a floating-point sum, a vtbl or a vdot may give other results\n");
	pdp64_set_psw(&cpu, mode << PSW_MODE | mode << PSW_PREV | (sys ? 7 << PSW_PRI : 0));
	cpu.deliver = sys; cpu.standin = !sys;
	if (hve) pdp64_set_hve(&cpu, 1);
	cpu.pc = load_elf(prog);
	if (elf_isa != EF_PDP64_ISA) { fprintf(stderr, "sim64: %s: e_flags names the instruction set %d, not the pdp64 (%d)\n", prog, elf_isa, EF_PDP64_ISA); return 1; }
	if (ntms_spec) {
		char e[200];
		if (sys) { fprintf(stderr, "sim64: --timing does not work with -K\n"); return 2; }
		for (int k = 0; k < ntms_spec; k++) {
			tms[ntms] = tm_new(timing_specs[k], e, sizeof e);
			if (!tms[ntms]) { fprintf(stderr, "sim64: %s\n", e); return 2; }
			ntms++;
		}
		tm_set_text(prof.lo, prof.hi);
		if (timing_pc) for (int k = 0; k < ntms; k++) tm_pcprof(tms[k]);
		prog_name = strrchr(prog, '/') ? strrchr(prog, '/') + 1 : prog;
		tm_on = 1; env.profile = h_profile;
		atexit(timing_write);
	}
	if (profile_path) {
		if (prof.hi <= prof.lo) { prof.lo = prof.hi = 0; }
		prof.count = calloc(((prof.hi - prof.lo) >> 1) + 1, 4); prof.len = calloc(((prof.hi - prof.lo) >> 1) + 1, 1); prof.cat_of = calloc(((prof.hi - prof.lo) >> 1) + 1, 1);
		env.profile = h_profile;
		atexit(profile_write);
	}
	addregion(0x7fff000000ULL, 0x7fffffffffULL & ~(uint64_t)(PG - 1));
	cpu.r[14] = 0x7ffffff000ULL;
	for (steps = 0; steps < maxsteps; steps++) { if (sys) step_k(); else step(); }
	if (regs) regdump(stderr);
	fprintf(stderr, "sim64: step limit reached\n");
	return 124;
}
