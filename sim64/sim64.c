/* sim64: a reference emulator for pdp64 (user mode).
 *
 * It loads an ELF executable written by ld64, decodes each instruction with the table codec (common/pdp64enc.c, the tables generated from
 * spec/pdp64/pdp64.hbnf) and executes it with the shared core (common/pdp64exec.c).
 *
 *   sim64 [-t] [-r] [-k | -K | -H] [-i N:LEVEL:VECTOR] [-n steps] [-P file] program
 *
 *   (-m pdp64 is accepted and ignored, for the driver convention of pcc: there is one target.)
 *   -P file  profile: count the executed instructions per pc and write them at exit: "#" lines (the target, the totals, the instructions per category)
 *       and one line "pc count bytes category" (pc in hex, category as the #category lines in order) for each pc that ran.  A block instruction (mcpy...) is one executed instruction.
 *
 *   -x LO:HI  (a test facility, with -K) the first access to each page of [LO, HI) faults once (a load or a store fault), then succeeds: "the handler maps the page" without an MMU
 *   -V  print the vector counters (blocks, strips, vector instructions, elements) to standard error at exit; -P also writes them as a "#vec" line; and the cycle model of the vec blocks
 *       (a second line, docs/sim64.md: a model with the parameters below, not a measurement)
 *   -S BYTES  the strip of the vector unit: 8, 16, 32 (default) or 64 bytes (the environment variable PDP64_VSTRIP is the default of -S).  A program's results do not depend on it
 *       (docs/encoding-work/vec-strip.md); the number of strips and the model's cycles do.
 *   --vport=BYTES  the model's memory port, bytes a cycle (default 16)     --vcommit=CYCLES  the model's commit cost of a strip (default 1)
 *   --vmix  with -V: a line with the number of vector instructions run in each class of the second model
 *   --latency=fpga|asic|FILE  the latency table of the second cycle model (docs/encoding-work/vec-latency.md): one line `class latency interval` a class; the built-in tables fpga (default) and asic;
 *       a FILE changes the classes it names (the rest stays as fpga).  --vpipe=N  strips in flight (1 to 16, default 1: no overlap)     --vmemlat=N  the memory's load-to-use latency, cycles (default 4)
 *   -t  trace: one line per instruction, to standard error     -r  print the registers and flags when the program stops
 *   -n  stop after that many instructions (default 200 million)
 *   -k  start in kernel mode (privileged instructions allowed); the system-call stand-in stays
 *   -K  System v1 kernel mode: start in kernel mode at priority 7, flat physical memory, no MMU; faults, traps and interrupts are exceptions
 *       delivered through the vector table at the physical address in VBR (the stand-in is off: trap #n is vector 256 + n, halt exits with r0)
 *   -H  (implies -K) the machine with the hypervisor mode (strap HVE; errata 195, 196): the core starts as the hypervisor (H = 1) with the hypervisor registers, GENTER and the exits of
 *       docs/encoding-work/hypervisor-design.md.  Without -H those registers and GENTER are illegal instructions.  There is no MMU: stage 2 and the guest tag are not modelled (QEMU only).
 *   -i N:LEVEL:VECTOR  (with -K, repeatable) an interrupt request of that level and vector, raised once N instructions have been started; it stays pending
 *       until it is taken.  wfe jumps to the next pending request (and stops with status 125 if none can be taken).
 *
 * The system call interface is a stand-in until there is an operating system (docs/sim64.md): `trap #n` with n = 0 exit(r0), 1 write(r0
 * fd, r1 buffer, r2 length) returning the count in r0, 2 read(...).  `halt` stops with the status in r0.  The program's exit status is the
 * emulator's.  A fault (misaligned data, an unmapped address, an unimplemented instruction, a divide by zero) prints a message and exits 139.
 */
