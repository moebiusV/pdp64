#!/usr/bin/env python3
"""
usage.py -- which vector instructions the compiled kernels use (writes llvm/vector-usage.md; the input of the next run of the encoding optimiser).

It compiles the kernels of the study (docs/encoding-work/arch-data/vec-forms, llvm/bench/simple.c) and the test programs llvm/tests/vec/*.c with clang and
llc -pdp64-vecloop, reads the vec blocks of the assembly (the lines between the `;APP` and `;NO_APP` of the inline assembly), and counts for each mnemonic of the
vector family of the grammar (the list in llvm/target/PDP64/gen/PDP64GenLayout.h, made from spec/pdp64/pdp64.hbnf): the blocks and the functions that use it.
A word of the grammar that no kernel uses is a dud for this compiler.   usage.py [--out file]
"""
import os, re, subprocess, sys, tempfile, argparse
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
R = os.path.dirname(os.path.dirname(HERE))
LLC = os.path.join(os.path.dirname(R), 'llvm-build', 'bin', 'llc')
VF = os.path.join(R, 'docs', 'encoding-work', 'arch-data', 'vec-forms')
SRCS = [os.path.join(VF, 'kernels.c'), os.path.join(VF, 'games', 'games.c'), os.path.join(VF, 'blas', 'blas.c'), os.path.join(VF, 'seg', 'seg.c'),
        os.path.join(HERE, 'simple.c')] + sorted(os.path.join(R, 'llvm', 'tests', 'vec', f) for f in os.listdir(os.path.join(R, 'llvm', 'tests', 'vec')) if f.endswith('.c')) + [os.path.join(R, 'llvm', 'tests', 'vec_lane_ops.ll')]
CFLAGS = ['-O2', '-m64', '-fno-builtin-memset', '-fno-builtin-memcpy', '-fno-stack-protector', '-mlong-double-64', '-mno-sse', '-mno-mmx', '-fno-vectorize', '-fno-slp-vectorize',
          '-fno-unroll-loops', '-ffp-contract=fast', '-ffast-math', '-w', '-S', '-emit-llvm']

# the groups of vec-isa.md section 2, for the table
GROUPS = [
    ('block', ['vec', 'vend', 'vlen']),
    ('load, store', ['vld', 'vst']),
    ('saturating narrow', ['vsts']),
    ('strided', ['vldt', 'vstt']),
    ('segment', ['vlseg2', 'vlseg3', 'vlseg4', 'vsseg2', 'vsseg3', 'vsseg4']),
    ('gather', ['vldx']),
    ('lane operations', ['vadd', 'vsub', 'vsubr', 'vmul', 'vand', 'vor', 'vxor', 'vshl', 'vshr', 'vsar', 'vabd', 'vabdu', 'vmin', 'vmax', 'vminu', 'vmaxu', 'vmov', 'vneg']),
    ('saturating', ['vadds', 'vsubs', 'vaddsu', 'vsubsu']),
    ('multiply-add', ['vmla', 'vfma', 'vfnma', 'vfmab']),
    ('int8 dot', ['vdot', 'vdotu', 'vdotsu']),
    ('reductions', ['vacc', 'vmaxacc', 'vminacc']),
    ('sliding window', ['vfir']),
    ('accumulators', ['vclr']),
    ('tile and GEMM', ['vtclr', 'vtfmopa', 'vtld', 'vtst', 'vtadd', 'gemm']),
]

def main():
    ap = argparse.ArgumentParser(); ap.add_argument('--out'); a = ap.parse_args()
    hdr = open(os.path.join(R, 'llvm', 'target', 'PDP64', 'gen', 'PDP64GenLayout.h')).read()
    allmn = re.findall(r'X\("([a-z0-9.]+)"\)', hdr[hdr.index('PDP64_VEC_MNEMONICS'):])
    tmp = tempfile.mkdtemp()
    use = {}         # mnemonic -> list of (source, function, count)
    nfun = set()
    nblocks = 0
    for src in SRCS:
        n = os.path.basename(src).rsplit('.', 1)[0]
        ll = os.path.join(tmp, n + '.ll')
        if src.endswith('.ll'):
            open(ll, 'w').write(open(src).read())
        else:
            r = subprocess.run(['clang'] + CFLAGS + ['-o', ll + '.0', src], capture_output=True, text=True)
            if r.returncode: continue
            t = open(ll + '.0').read()
            t = re.sub(r'^target (datalayout|triple).*\n', '', t, flags=re.M); t = re.sub(r'"(target-cpu|target-features|tune-cpu)"="[^"]*"', '', t)
            open(ll, 'w').write(t)
        r = subprocess.run([LLC, '-mtriple=pdp64-unknown-elf', '-O2', '-pdp64-vecloop', ll, '-o', ll[:-3] + '.s'], capture_output=True, text=True)
        if r.returncode: print('llc failed on', src, r.stderr[:200]); continue
        fn = None; inasm = False
        for ln in open(ll[:-3] + '.s'):
            m = re.match(r'^([A-Za-z_][A-Za-z0-9_]*):', ln)
            if m and not ln.startswith('.L'): fn = m.group(1)
            if ln.strip() == ';APP': inasm = True; continue
            if ln.strip() == ';NO_APP': inasm = False; continue
            if inasm:
                w = ln.split()
                if w and (w[0] in ('vec', 'vend') or re.match(r'^(v[a-z0-9]+|gemm)\.', w[0]) or w[0] in allmn):
                    mn = w[0]
                    use.setdefault(mn, []).append((n, fn))
                    if mn == 'vec': nblocks += 1
                    nfun.add((n, fn))
    out = []
    out.append('# Which vector instructions the compiled kernels use\n')
    out.append('Generated by `llvm/bench/usage.py` from the blocks that `llc -pdp64-vecloop` (approach (b): one `vec` block for a whole loop) makes for %d programs: the kernels of '
               '`docs/encoding-work/arch-data/vec-forms/` (`kernels.c`, `games`, `blas`, `seg`), `llvm/bench/simple.c`, and `llvm/tests/vec/*.c`. %d blocks in %d functions. '
               'The words are those of the vector family of the grammar (%d mnemonics). **A static count is a count of instructions in the blocks; the dynamic counts '
               '(vector instructions executed, elements) are in `llvm/bench/results.csv` and `llvm/README.md`.** Re-run: `llvm/bench/usage.py --out llvm/vector-usage.md`.\n' % (len(SRCS), nblocks, len(nfun), len(allmn)))
    # by base
    def base(m): return m.split('.')[0]
    bybase = {}
    for m, l in use.items():
        bybase.setdefault(base(m), []).extend(l)
    out.append('## By instruction (base mnemonic, all lane and memory suffixes together)\n')
    out.append('| group | instruction | words in the grammar | words used | static uses | functions that use it | used by |\n|---|---|---:|---:|---:|---:|---|')
    duds = []
    for g, bases in GROUPS:
        for b in bases:
            words = [m for m in allmn if base(m) == b]
            used = sorted(set(m for m in use if base(m) == b))
            l = bybase.get(b, [])
            fns = sorted(set(f for _, f in l))
            if not l: duds.append((g, b, len(words)))
            out.append('| %s | `%s` | %d | %d | %d | %d | %s |' % (g, b, len(words), len(used), len(l), len(fns), ', '.join(fns[:6]) + (' ...' if len(fns) > 6 else '') if fns else '**none: a dud for this compiler**'))
    out.append('\n## The words that are used (mnemonic with suffixes)\n')
    out.append('| word | static uses | functions |\n|---|---:|---:|')
    for m in sorted(use):
        out.append('| `%s` | %d | %d |' % (m, len(use[m]), len(set(f for _, f in use[m]))))
    unused_words = [m for m in allmn if m not in use]
    out.append('\n## Words of the grammar that no kernel uses\n')
    out.append('%d of the %d words of the family are not used. By base mnemonic (words unused / words in the grammar):\n' % (len(unused_words), len(allmn)))
    ub = {}
    for m in allmn:
        ub.setdefault(base(m), [0, 0]); ub[base(m)][1] += 1
        if m not in use: ub[base(m)][0] += 1
    out.append(', '.join('`%s` %d/%d' % (b, v[0], v[1]) for b, v in sorted(ub.items())) + '\n')
    out.append('\n## Instructions no kernel used, and why (what a compiler would need)\n')
    why = {
        'vlen': 'only needed by a program that must know VL (explicit tail folding, approach (c)); the loop-to-block pass has hardware strip mining and never asks',
        'vclr': 'hidden accumulation across strips: nothing here reads an accumulator after the block ends (there is no vector-to-scalar move outside a block), so a block that needs one must reduce inside it (`vacc` each strip), which is what the compiler does',
        'vfir': 'needs the recogniser for a window of consecutive loads times invariant taps (put8h): the pass makes eight shifted streams instead (8 loads, 8 multiplies, 7 adds)',
        'vlseg2': 'the pass makes one strided load (`vldt`) for each field instead; a grouping of the fields of one structure would use these', 'vlseg3': 'same', 'vlseg4': 'same',
        'vsseg2': 'same (stores)', 'vsseg3': 'same', 'vsseg4': 'same',
        'vldx': 'a gather (k_hist, k_ssm): the loop reads an address from a load; not recognised',
        'vdot': 'int8 dot products (k_q8dot, k_q4dot): the block of the pass already runs 8 elements per strip because the reduction `vacc.l` makes the widest lane 32 bits; `vdot.b` would not widen the strip (see the findings)',
        'vdotu': 'same', 'vdotsu': 'same',
        'vmla': 'integer multiply-add by a scalar (`vmla.l vD, vA, Rs`): the pass emits `vmul` then `vadd` for integers; not fused yet',
        'vfmab': 'the broadcast multiply-add of a GEMM micro-kernel: needs a loop nest, not an innermost loop',
        'vabdu': 'the kernels take `abs(a - b)` of widened bytes: the signed `vabd` serves',
        'vtclr': 'tile and GEMM: no kernel loop nest is turned into tiles (`k_sgemm_nt` is vectorised on its inner dot product)', 'vtfmopa': 'same', 'vtld': 'same', 'vtst': 'same', 'vtadd': 'same', 'gemm': 'same: a call of the GEMM unit would be recognised from `llvm.matrix.multiply` or the triple loop; not done',
    }
    supported = {'vsub', 'vor', 'vmax', 'vminu', 'vmaxu', 'vneg', 'vsubs', 'vaddsu', 'vsubsu', 'vminacc', 'vsubr', 'vand', 'vxor'}
    for g, b, nw in duds:
        out.append('* `%s` (%s, %d words): %s' % (b, g, nw, why.get(b, 'the pass emits it, but no kernel of this set has the operation' if b in supported else '')))
    txt = '\n'.join(out) + '\n'
    if a.out: open(a.out, 'w').write(txt)
    else: print(txt)
main()
