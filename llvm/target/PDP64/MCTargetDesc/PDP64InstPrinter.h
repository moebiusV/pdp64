//===-- PDP64InstPrinter.h - Convert PDP64 MCInst to asm syntax -*- C++ -*-===//
#ifndef LLVM_LIB_TARGET_PDP64_MCTARGETDESC_PDP64INSTPRINTER_H
#define LLVM_LIB_TARGET_PDP64_MCTARGETDESC_PDP64INSTPRINTER_H

#include "llvm/MC/MCInstPrinter.h"

namespace llvm {
class PDP64InstPrinter : public MCInstPrinter {
public:
  PDP64InstPrinter(const MCAsmInfo &MAI, const MCInstrInfo &MII, const MCRegisterInfo &MRI)
      : MCInstPrinter(MAI, MII, MRI) {}

  void printRegName(raw_ostream &O, MCRegister Reg) override;
  void printInst(const MCInst *MI, uint64_t Address, StringRef Annot, const MCSubtargetInfo &STI,
                 raw_ostream &O) override;

  // Autogenerated by tblgen.
  std::pair<const char *, uint64_t> getMnemonic(const MCInst &MI) const override;
  void printInstruction(const MCInst *MI, uint64_t Address, raw_ostream &O);
  static const char *getRegisterName(MCRegister Reg);

private:
  void printOperand(const MCInst *MI, unsigned OpNo, raw_ostream &O);
  void printImm(const MCInst *MI, unsigned OpNo, raw_ostream &O);
  void printCC(const MCInst *MI, unsigned OpNo, raw_ostream &O);
  void printSysReg(const MCInst *MI, unsigned OpNo, raw_ostream &O);
  void printTarget(const MCInst *MI, unsigned OpNo, raw_ostream &O);
  void printMemBase(const MCInst *MI, unsigned OpNo, raw_ostream &O);
  void printMemIndex(const MCInst *MI, unsigned OpNo, raw_ostream &O);
  void printMemDP(const MCInst *MI, unsigned OpNo, raw_ostream &O);
  void printMemPC(const MCInst *MI, unsigned OpNo, raw_ostream &O);
  void printMemImm(const MCInst *MI, unsigned OpNo, raw_ostream &O);
  void printMemAbs(const MCInst *MI, unsigned OpNo, raw_ostream &O);
  void printMemPostInc(const MCInst *MI, unsigned OpNo, raw_ostream &O);
  void printMemPreDec(const MCInst *MI, unsigned OpNo, raw_ostream &O);
  void printReg(raw_ostream &O, const MCOperand &Op);
  void printValue(raw_ostream &O, const MCOperand &Op);
  unsigned defaultStride(const MCInst *MI) const;
};
} // namespace llvm

#endif
